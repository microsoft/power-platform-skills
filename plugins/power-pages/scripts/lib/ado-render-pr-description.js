#!/usr/bin/env node

// Translates a Connect-to-Git pending-changes diff (the items[] array from
// list-pending-changes.js) into a human-readable Markdown PR description for
// the ado-create-pr skill (Skill 10 open-pr).
//
// Why this lives in `lib/`: the rendering logic is the same regardless of
// where the PR is opened from (the open-pr skill, the plan-inner-loop summary,
// or a future bulk-PR tool). Decoupling rendering from posting also makes
// the output deterministically testable.
//
// PURE function — no HTTP, no I/O unless `--items-file` / `--stdin` is used.
//
// Output (JSON to stdout in CLI mode, OR the rendered string directly via
// `--raw` flag):
//   {
//     markdown: "<full PR description>",
//     summary:  "<one-line summary, suitable for PR title>",
//     stats:    { added: int, modified: int, deleted: int, total: int },
//   }
//
// PR description layout:
//   ## Summary
//   <X added, Y modified, Z deleted>
//
//   ## Changes
//   ### Added (N)
//   - **<componentName>** (`<componentType>`)
//
//   ### Modified (N)
//   - ...
//
//   ### Deleted (N)
//   - ...
//
//   ---
//   _Generated by Power Pages Inner Dev Loop · plugin v<plugin version>_
//
// Usage:
//   node ado-render-pr-description.js --items-file <path> [--raw]
//   node ado-render-pr-description.js --pending-file <path>
//   echo '<json>' | node ado-render-pr-description.js --stdin
//
// As a library:
//   const { renderPrDescription } = require('./ado-render-pr-description');
//   const { markdown, summary, stats } = renderPrDescription(items, { commitMessage });

'use strict';

const fs = require('node:fs');

function parseArgs(argv) {
  const args = argv.slice(2);
  const out = {
    itemsFile: null, pendingFile: null, stdin: false,
    raw: false,
    commitMessage: null,
    title: null,
    footer: null,
  };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--items-file' && args[i + 1]) out.itemsFile = args[++i];
    else if (args[i] === '--pending-file' && args[i + 1]) out.pendingFile = args[++i];
    else if (args[i] === '--stdin') out.stdin = true;
    else if (args[i] === '--raw') out.raw = true;
    else if (args[i] === '--commitMessage' && args[i + 1]) out.commitMessage = args[++i];
    else if (args[i] === '--title' && args[i + 1]) out.title = args[++i];
    else if (args[i] === '--footer' && args[i + 1]) out.footer = args[++i];
  }
  return out;
}

function escapeMd(s) {
  if (s === null || s === undefined) return '';
  return String(s).replace(/([\\`*_{}[\]()#+\-.!|])/g, '\\$1');
}

function groupByChangeType(items) {
  const groups = { Add: [], Modify: [], Delete: [], Other: [] };
  for (const it of items) {
    if (!it || typeof it !== 'object') continue;
    const t = it.changeType;
    if (t === 'Add' || t === 'Modify' || t === 'Delete') groups[t].push(it);
    else groups.Other.push(it);
  }
  return groups;
}

function renderSection(title, items) {
  if (items.length === 0) return '';
  const lines = [`### ${title} (${items.length})`];
  for (const it of items) {
    const name = escapeMd(it.componentName || '(unnamed)');
    // Inside code spans, escaping is unnecessary and renders ugly. We strip
    // backticks from the type itself to keep the span balanced.
    const typeRaw = it.componentType ? String(it.componentType).replace(/`/g, '') : '';
    const type = typeRaw ? `\`${typeRaw}\`` : '';
    const path = it.filePath ? ` — _${escapeMd(it.filePath)}_` : '';
    lines.push(`- **${name}**${type ? ' (' + type + ')' : ''}${path}`);
  }
  return lines.join('\n');
}

/**
 * Render a Markdown PR description from a pending-changes items[] array.
 *
 * @param {Array<object>} items
 * @param {object} [options]
 * @param {string} [options.commitMessage]  Surfaced under a "Commit message" callout
 * @param {string} [options.title]          Used in summary if provided
 * @param {string} [options.footer]         Override the default footer
 * @returns {{ markdown: string, summary: string, stats: object }}
 */
function renderPrDescription(items, { commitMessage = null, title = null, footer = null } = {}) {
  if (!Array.isArray(items)) {
    throw new Error('renderPrDescription: items must be an array');
  }
  const groups = groupByChangeType(items);
  const stats = {
    added: groups.Add.length,
    modified: groups.Modify.length,
    deleted: groups.Delete.length,
    other: groups.Other.length,
    total: items.length,
  };

  const parts = ['Add', 'Modify', 'Delete']
    .map((k) => stats[k.toLowerCase() + (k === 'Add' ? 'ed' : (k === 'Modify' ? 'ied' : 'd'))])
    .filter((n) => n > 0);
  const parts2 = [];
  if (stats.added)    parts2.push(`${stats.added} added`);
  if (stats.modified) parts2.push(`${stats.modified} modified`);
  if (stats.deleted)  parts2.push(`${stats.deleted} deleted`);
  if (stats.other)    parts2.push(`${stats.other} other`);
  const summaryLine = parts2.length > 0 ? parts2.join(', ') : 'no component changes';

  const sections = [];
  sections.push('## Summary');
  if (title) sections.push(`**${escapeMd(title)}**`);
  sections.push(summaryLine);

  if (commitMessage) {
    sections.push('');
    sections.push('> **Commit message:**');
    sections.push('> ' + escapeMd(commitMessage).split('\n').join('\n> '));
  }

  sections.push('');
  sections.push('## Changes');
  const added = renderSection('Added', groups.Add);
  const modified = renderSection('Modified', groups.Modify);
  const deleted = renderSection('Deleted', groups.Delete);
  const other = renderSection('Other', groups.Other);
  if (added) sections.push(added);
  if (modified) sections.push(modified);
  if (deleted) sections.push(deleted);
  if (other) sections.push(other);
  if (!added && !modified && !deleted && !other) {
    sections.push('_No detectable component changes in this commit._');
  }

  sections.push('');
  sections.push('---');
  sections.push(footer || '_Generated by Power Pages Inner Dev Loop · ado-render-pr-description_');

  const markdown = sections.join('\n');

  // Derived single-line summary (max ~80 chars), useful for PR title
  const shortSummary = title
    ? `${title} (${summaryLine})`
    : summaryLine;

  return { markdown, summary: shortSummary, stats };
}

async function readStdin() {
  return new Promise((resolve, reject) => {
    let s = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (c) => { s += c; });
    process.stdin.on('end', () => resolve(s));
    process.stdin.on('error', reject);
  });
}

async function main() {
  const args = parseArgs(process.argv);
  let items = [];
  if (args.itemsFile) items = JSON.parse(fs.readFileSync(args.itemsFile, 'utf8'));
  else if (args.pendingFile) items = JSON.parse(fs.readFileSync(args.pendingFile, 'utf8')).items || [];
  else if (args.stdin) {
    const parsed = JSON.parse(await readStdin());
    items = Array.isArray(parsed) ? parsed : (parsed.items || []);
  } else {
    process.stderr.write('ado-render-pr-description: provide --items-file, --pending-file, or --stdin\n');
    process.exit(1);
  }
  const r = renderPrDescription(items, {
    commitMessage: args.commitMessage,
    title: args.title,
    footer: args.footer,
  });
  if (args.raw) {
    process.stdout.write(r.markdown + '\n');
  } else {
    process.stdout.write(JSON.stringify(r, null, 2) + '\n');
  }
}

if (require.main === module) {
  main().catch((e) => {
    process.stderr.write('ado-render-pr-description: ' + e.message + '\n');
    process.exit(1);
  });
}

module.exports = { renderPrDescription, escapeMd, groupByChangeType };
