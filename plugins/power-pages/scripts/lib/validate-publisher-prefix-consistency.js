#!/usr/bin/env node

// V-10 HTTP validator: WARN per pending Change whose schemaname / component
// name does NOT start with the bound solution's publisher prefix. Such
// changes commit cleanly but are a common signal of accidental
// cross-solution edits — and Pull on a downstream env may fail to resolve
// the dependent component if the source solution isn't installed there.
//
// Strategy:
//   1. Query DV for the bound solution's publisher customizationprefix
//      (`solutions?$filter=uniquename eq '<x>'&$expand=publisherid($select=customizationprefix,uniquename)`).
//   2. For each pending Change item, derive the component's effective
//      schemaname:
//        - prefer `it.componentName`
//        - fall back to last path segment of `it.componentpath` / `it.filePath`
//      Skip items whose name matches a known Microsoft / system prefix
//      (e.g. `msdyn_`, `cdm_`, `system_`, `Microsoft`) — those are
//      *expected* cross-solution edits.
//   3. WARN per non-matching item, citing the actual prefix that prevailed.
//
// Output (JSON to stdout): standard envelope.
//   {
//     ok: true,                       // never blocks
//     totalChecked: <int>,
//     blocking: [],
//     warnings: [ { severity:'warn', key:'publisher-prefix-mismatch', ... } ],
//     info: [ ... ],
//   }
//
// Usage:
//   node validate-publisher-prefix-consistency.js
//     --pending-file <path>
//     --envUrl <url>
//     --solutionUniqueName <name>
//     [--token <bearer>]
//     [--solutionId <guid>]            // resolved from --solutionUniqueName if omitted

'use strict';

const fs = require('node:fs');
const { getAuthToken, getEnvironmentUrl, makeRequest } = require('./validation-helpers');

// Schema prefixes whose components are expected to appear cross-solution
// in user-bound solutions. WARNs on these would be noise.
//
// Includes:
//  - Custom-solution placeholders / legacy defaults (`new`, `system`, `Microsoft`)
//  - Microsoft-published Dataverse / Dynamics product prefixes
//    (`cdm`, `msdyn*`, `msft`, `ppt`, `crc`, `crmsl`, `mscrm`)
//  - Dataverse-AUTO relationship prefixes that surface as the first
//    underscore-segment on lookup/cascade columns
//    (e.g. `lk_sri_widget_createdby`, `user_sri_widget`,
//    `team_sri_widget`, `owner_sri_widget`, `business_unit_sri_widget`).
//    These are NOT user-configurable publisher prefixes — they're auto-
//    generated by Dataverse on relationships pointing at system tables.
const SYSTEM_PREFIXES = Object.freeze(new Set([
  // Solution / publisher placeholders + Microsoft product prefixes
  'new', 'system', 'microsoft', 'organization',
  'cdm', 'msdyn', 'msdynce', 'msft', 'ppt', 'crc', 'crmsl', 'mscrm',
  // Dataverse-auto relationship prefixes (lookup + system-table related)
  'lk', 'user', 'team', 'owner', 'business', 'processsession',
  'principal', 'queue', 'asyncoperation',
]));

// Schema-name regex: leading prefix (alphanumerics) + underscore + body.
const SCHEMA_NAME_REGEX = /^([a-z0-9]+)_/i;

function parseArgs(argv) {
  const a = argv.slice(2);
  const out = {
    envUrl: null, token: null, pendingFile: null,
    solutionUniqueName: null, solutionId: null,
  };
  for (let i = 0; i < a.length; i++) {
    if      (a[i] === '--envUrl'             && a[i+1]) out.envUrl             = a[++i];
    else if (a[i] === '--token'              && a[i+1]) out.token              = a[++i];
    else if (a[i] === '--pending-file'       && a[i+1]) out.pendingFile        = a[++i];
    else if (a[i] === '--solutionUniqueName' && a[i+1]) out.solutionUniqueName = a[++i];
    else if (a[i] === '--solutionId'         && a[i+1]) out.solutionId         = a[++i];
  }
  return out;
}

async function resolvePublisherPrefix({ base, tok, solutionUniqueName, solutionId }) {
  const filter = solutionId
    ? `solutionid eq ${solutionId}`
    : `uniquename eq '${solutionUniqueName}'`;
  const url = `${base}/api/data/v9.2/solutions?$filter=${encodeURIComponent(filter)}&$select=solutionid,uniquename&$expand=publisherid($select=customizationprefix,uniquename)`;
  const res = await makeRequest({
    url, method: 'GET',
    headers: {
      Authorization: `Bearer ${tok}`,
      Accept: 'application/json',
      'OData-MaxVersion': '4.0', 'OData-Version': '4.0',
    },
  });
  if (res.error) return { error: res.error };
  if (res.statusCode !== 200) {
    let msg = `HTTP ${res.statusCode}`;
    try { msg = JSON.parse(res.body).error.message || msg; } catch {}
    return { error: msg, statusCode: res.statusCode };
  }
  let parsed;
  try { parsed = JSON.parse(res.body); } catch (e) { return { error: 'parse: ' + e.message }; }
  const sol = (parsed.value || [])[0];
  if (!sol) return { error: `Solution '${solutionUniqueName || solutionId}' not found.` };
  const prefix = sol.publisherid && sol.publisherid.customizationprefix;
  if (!prefix) return { error: `Publisher prefix not exposed for solution '${sol.uniquename}'.` };
  return { prefix: String(prefix).toLowerCase(), publisherUniqueName: sol.publisherid.uniquename || null };
}

function extractSchemaName(it) {
  if (!it) return null;
  if (typeof it.componentName === 'string' && it.componentName.length > 0) return it.componentName;
  for (const p of [it.componentpath, it.filePath]) {
    if (typeof p !== 'string' || !p) continue;
    const seg = p.split(/[\\/]/).pop();
    if (seg && seg !== '') {
      return seg.replace(/\.[a-z]+$/i, ''); // strip extension
    }
  }
  return null;
}

function isSystemPrefix(prefix) {
  return SYSTEM_PREFIXES.has(String(prefix || '').toLowerCase());
}

async function validatePublisherPrefixConsistency({ envUrl, token, pendingFile, solutionUniqueName, solutionId } = {}) {
  if (!pendingFile)              return { error: '--pending-file is required.' };
  if (!fs.existsSync(pendingFile)) return { error: `Snapshot file not found: ${pendingFile}` };
  if (!solutionUniqueName && !solutionId) {
    return { error: '--solutionUniqueName (or --solutionId) is required to resolve publisher prefix.' };
  }

  const url = envUrl || getEnvironmentUrl();
  if (!url) return { error: 'Could not determine environment URL.' };
  const tok = token || getAuthToken(url);
  if (!tok) return { error: 'Could not acquire auth token.' };
  const base = url.replace(/\/+$/, '');

  let snap;
  try { snap = JSON.parse(fs.readFileSync(pendingFile, 'utf8')); }
  catch (e) { return { error: 'snapshot parse: ' + e.message }; }
  const items = Array.isArray(snap.items) ? snap.items : (Array.isArray(snap) ? snap : []);

  const lookup = await resolvePublisherPrefix({ base, tok, solutionUniqueName, solutionId });
  if (lookup.error) return { error: lookup.error, statusCode: lookup.statusCode };

  const expectedPrefix = lookup.prefix; // already lowercased
  const warnings = [];
  const info = [];
  let totalChecked = 0;
  let skippedSystem = 0;

  for (const it of items) {
    const name = extractSchemaName(it);
    if (!name) continue;
    const m = SCHEMA_NAME_REGEX.exec(name);
    if (!m) continue; // unprefixed (e.g. file-resource paths); skip
    totalChecked++;
    const actualPrefix = m[1].toLowerCase();
    if (actualPrefix === expectedPrefix) continue;
    if (isSystemPrefix(actualPrefix)) { skippedSystem++; continue; }

    warnings.push({
      severity: 'warn',
      key: 'publisher-prefix-mismatch',
      message: `Component '${name}' uses publisher prefix '${actualPrefix}_' but bound solution expects '${expectedPrefix}_'.`,
      ref: null,
      details: {
        componentName: name,
        componentType: it.componentType || null,
        componentpath: it.componentpath || it.filePath || null,
        actualPrefix,
        expectedPrefix,
      },
      remediation:
        `Verify this component belongs in the '${solutionUniqueName || solutionId}' solution. ` +
        'Cross-solution accidental edits commit but break Pull on target envs that lack the source solution.',
    });
  }

  if (skippedSystem > 0) {
    info.push({
      severity: 'info',
      key: 'publisher-prefix-system-skipped',
      message: `Skipped ${skippedSystem} component(s) with system / Microsoft prefixes — expected cross-solution edits.`,
      ref: null,
      details: { skippedSystemCount: skippedSystem, systemPrefixes: [...SYSTEM_PREFIXES] },
      remediation: null,
    });
  }

  return {
    ok: true,
    totalChecked,
    blocking: [],
    warnings,
    info,
    scope: { solutionUniqueName, solutionId, expectedPrefix, publisherUniqueName: lookup.publisherUniqueName },
  };
}

if (require.main === module) {
  const args = parseArgs(process.argv);
  validatePublisherPrefixConsistency(args)
    .then((r) => {
      process.stdout.write(JSON.stringify(r, null, 2) + '\n');
      process.exit(r && r.error ? 1 : 0);
    })
    .catch((e) => {
      process.stderr.write('validate-publisher-prefix-consistency: ' + e.message + '\n');
      process.exit(1);
    });
}

module.exports = {
  validatePublisherPrefixConsistency,
  SYSTEM_PREFIXES,
  SCHEMA_NAME_REGEX,
  extractSchemaName,
  isSystemPrefix,
};
