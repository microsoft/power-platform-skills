#!/usr/bin/env node

// V-8 HTTP validator: warn-only. Compares the bound solution's current
// version (queried from Dataverse) to `lastCommittedSolutionVersion` from
// the previous validation run (read from
// docs/inner-loop/last-validation.json). If the version is unchanged AND
// there are pending non-trivial Changes in the snapshot, emits a WARN
// finding to nudge the user to bump the solution version before commit.
//
// Why this matters: downstream ALM pipelines often gate "install only if
// version > installed version". A same-version commit can silently skip
// in higher envs, and the user blames the pipeline instead of the
// authoring env.
//
// Output (JSON to stdout):
//   {
//     ok: true,                       // never blocks
//     totalChecked: 1,
//     blocking: [],
//     warnings: [
//       {
//         severity: 'warn',
//         key: 'solution-version-not-bumped',
//         message: 'Solution version 1.0.0.0 unchanged since last commit, but N non-trivial Changes pending.',
//         ref: 'IL-VERSION-002',
//         details: { current, lastCommitted, pendingNonTrivialCount },
//         remediation: 'Bump the solution version (Maker Portal → Solutions → ... → Properties).',
//       },
//     ],
//     info: [...],
//   }
//
// Usage:
//   node validate-solution-version-bumped.js
//     --solutionUniqueName <name>            // REQUIRED
//     [--envUrl <url>] [--token <token>]
//     [--last-validation-file <path>]        // default: <projectRoot>/docs/inner-loop/last-validation.json
//     [--pending-file <path>]                // optional; if provided, used to compute non-trivial count
//     [--project-root <path>]                // for default file resolution

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { getAuthToken, getEnvironmentUrl, makeRequest, findProjectRoot } = require('./validation-helpers');
const { innerLoopPath } = require('./inner-loop-paths');

// "Non-trivial" excludes trivial autogenerated rows. For now we treat all
// pending changes as non-trivial; an empirical follow-up can refine.
function countNonTrivialPending(items) {
  if (!Array.isArray(items)) return 0;
  return items.length;
}

function parseArgs(argv) {
  const args = argv.slice(2);
  const out = {
    envUrl: null, token: null,
    solutionUniqueName: null,
    lastValidationFile: null,
    pendingFile: null,
    projectRoot: null,
  };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--envUrl' && args[i + 1]) out.envUrl = args[++i];
    else if (args[i] === '--token' && args[i + 1]) out.token = args[++i];
    else if (args[i] === '--solutionUniqueName' && args[i + 1]) out.solutionUniqueName = args[++i];
    else if (args[i] === '--last-validation-file' && args[i + 1]) out.lastValidationFile = args[++i];
    else if (args[i] === '--pending-file' && args[i + 1]) out.pendingFile = args[++i];
    else if (args[i] === '--project-root' && args[i + 1]) out.projectRoot = args[++i];
  }
  return out;
}

/**
 * @param {object} options
 * @returns {Promise<object>}
 */
async function validateSolutionVersionBumped({
  envUrl, token, solutionUniqueName,
  lastValidationFile, pendingFile, projectRoot,
} = {}) {
  if (!solutionUniqueName) return { error: '--solutionUniqueName is required.' };

  const url = envUrl || getEnvironmentUrl();
  if (!url) return { error: 'Could not determine environment URL.' };
  const tok = token || getAuthToken(url);
  if (!tok) return { error: 'Could not acquire auth token.' };
  const base = url.replace(/\/+$/, '');

  // 1. Current version via Dataverse.
  const versionUrl = `${base}/api/data/v9.2/solutions?$filter=uniquename eq '${encodeURIComponent(solutionUniqueName)}'&$select=solutionid,uniquename,version&$top=1`;
  const res = await makeRequest({
    url: versionUrl, method: 'GET',
    headers: {
      Authorization: `Bearer ${tok}`,
      'OData-MaxVersion': '4.0',
      'OData-Version': '4.0',
      Accept: 'application/json',
    },
  });
  if (res.error) return { error: res.error };
  if (res.statusCode !== 200) {
    let msg = `HTTP ${res.statusCode}`;
    try { msg = JSON.parse(res.body).error.message || msg; } catch {}
    return { error: msg, statusCode: res.statusCode };
  }
  let parsed;
  try { parsed = JSON.parse(res.body); } catch (e) { return { error: 'parse: ' + e.message }; }
  if (!parsed.value || parsed.value.length === 0) {
    return { error: `Solution '${solutionUniqueName}' not found.` };
  }
  const currentVersion = parsed.value[0].version;

  // 2. Last-committed version (best-effort) from last-validation.json.
  const root = projectRoot || findProjectRoot(process.cwd());
  const lvFile = lastValidationFile
    || (root ? innerLoopPath(root, 'lastValidation') : null);
  let lastCommitted = null;
  if (lvFile && fs.existsSync(lvFile)) {
    try {
      const lv = JSON.parse(fs.readFileSync(lvFile, 'utf8'));
      lastCommitted = lv.lastCommittedSolutionVersion || null;
    } catch { /* tolerate corrupt file */ }
  }

  // 3. Pending non-trivial count from snapshot (best-effort).
  let pendingNonTrivialCount = null;
  if (pendingFile && fs.existsSync(pendingFile)) {
    try {
      const pf = JSON.parse(fs.readFileSync(pendingFile, 'utf8'));
      pendingNonTrivialCount = countNonTrivialPending(pf.items || pf);
    } catch { /* tolerate corrupt file */ }
  }

  const scope = { solutionUniqueName, current: currentVersion, lastCommitted };
  const info = [];

  if (lastCommitted === null) {
    info.push({
      severity: 'info',
      key: 'version-bump-no-prior-baseline',
      message: 'No prior lastCommittedSolutionVersion baseline found — skipping version-bump check.',
      ref: 'IL-VERSION-001',
      details: { currentVersion, lastValidationFile: lvFile },
      remediation: 'After the next successful commit, the orchestrator will record lastCommittedSolutionVersion automatically.',
    });
    return { ok: true, totalChecked: 1, blocking: [], warnings: [], info, scope };
  }

  if (currentVersion === lastCommitted && (pendingNonTrivialCount === null || pendingNonTrivialCount > 0)) {
    const detailedCount = pendingNonTrivialCount !== null ? pendingNonTrivialCount : '?';
    return {
      ok: true,
      totalChecked: 1,
      blocking: [],
      warnings: [{
        severity: 'warn',
        key: 'solution-version-not-bumped',
        message: `Solution version ${currentVersion} unchanged since last commit, but ${detailedCount} non-trivial Changes pending.`,
        ref: 'IL-VERSION-002',
        details: {
          currentVersion,
          lastCommittedVersion: lastCommitted,
          pendingNonTrivialCount,
        },
        remediation:
          'Bump the solution version (Maker Portal → Solutions → ' +
          `${solutionUniqueName} → Properties → Version → patch+1) before committing, ` +
          'so downstream ALM pipelines that install-on-version-bump pick up the change.',
      }],
      info,
      scope,
    };
  }

  return { ok: true, totalChecked: 1, blocking: [], warnings: [], info, scope };
}

if (require.main === module) {
  const args = parseArgs(process.argv);
  validateSolutionVersionBumped(args)
    .then((r) => {
      process.stdout.write(JSON.stringify(r, null, 2) + '\n');
      process.exit(r && r.error ? 1 : 0);
    })
    .catch((e) => {
      process.stderr.write('validate-solution-version-bumped: ' + e.message + '\n');
      process.exit(1);
    });
}

module.exports = { validateSolutionVersionBumped, countNonTrivialPending };
