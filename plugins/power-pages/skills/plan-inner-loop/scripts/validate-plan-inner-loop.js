#!/usr/bin/env node
/**
 * validate-plan-inner-loop.js — PostToolUse hook validator for plan-inner-loop.
 *
 * Verifies docs/inner-loop/inner-loop-plan.html exists and is well-formed
 * (≥ 500 bytes, contains the "plan-status" marker that every rendered
 * template includes).
 *
 * Gracefully approves when:
 *   - no project root found (not a Power Pages session)
 *   - the HTML file does not exist (skill didn't run / not its session)
 */

'use strict';

const path = require('path');
const fs = require('fs');
const {
  runValidation, findProjectRoot, block, approve,
} = require('../../../scripts/lib/validation-helpers');

const PATH_FRAGMENT = path.join('docs', 'inner-loop', 'inner-loop-plan.html');

runValidation((cwd) => {
  const projectRoot = findProjectRoot(cwd);
  if (!projectRoot) return approve();

  const htmlPath = path.join(projectRoot, PATH_FRAGMENT);
  if (!fs.existsSync(htmlPath)) return approve();

  let stat;
  try { stat = fs.statSync(htmlPath); }
  catch (e) { return block(`validate-plan-inner-loop: stat failed for ${htmlPath}: ${e.message}`); }

  if (stat.size < 500) {
    return block(
      `validate-plan-inner-loop: ${PATH_FRAGMENT} is too small (${stat.size} bytes). ` +
      `Expected at least 500 bytes. The file may be empty or truncated — re-run the renderer.`
    );
  }

  let content;
  try { content = fs.readFileSync(htmlPath, 'utf8'); }
  catch (e) { return block(`validate-plan-inner-loop: read failed for ${htmlPath}: ${e.message}`); }

  if (!content.includes('plan-status')) {
    return block(
      `validate-plan-inner-loop: ${PATH_FRAGMENT} does not contain the expected "plan-status" marker. ` +
      `The file may be corrupt or was not generated by render-inner-loop-plan.js.`
    );
  }

  approve();
});
