/**
 * Formats a date for use in a file name (YYYY-MM-DD-HHmmss)
 */
function formatDateForFileName(date) {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");
    const hours = String(date.getHours()).padStart(2, "0");
    const minutes = String(date.getMinutes()).padStart(2, "0");
    const seconds = String(date.getSeconds()).padStart(2, "0");
    return `${year}-${month}-${day}-${hours}${minutes}${seconds}`;
}
/**
 * Formats a date for display in the report (includes timezone)
 */
function formatDateForDisplay(date) {
    const options = {
        year: "numeric",
        month: "short",
        day: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        timeZoneName: "short"
    };
    return date.toLocaleString(undefined, options);
}
/**
 * Checks if a file is too large to include in the diff report
 */
async function isFileTooLarge(filePath) {
    try {
        const uri = vscode.Uri.file(filePath);
        const stat = await vscode.workspace.fs.stat(uri);
        return stat.size > MAX_FILE_SIZE_FOR_DIFF;
    }
    catch {
        return false; // If we can't stat, let it try to read
    }
}
/**
 * Reads file contents for all comparison results
 * Skips binary files, large files, and handles missing files gracefully
 */
async function readFileContents(comparisonResults) {
    const fileContents = [];
    for (const result of comparisonResults) {
        const isBinary = isBinaryFile(result.relativePath);
        if (isBinary) {
            fileContents.push({
                result,
                localContent: null,
                remoteContent: null,
                isBinary: true,
                isTooLarge: false
            });
            continue;
        }
        // Check if files are too large
        let localTooLarge = false;
        let remoteTooLarge = false;
        if (result.status !== FileComparisonStatus.DELETED) {
            localTooLarge = await isFileTooLarge(result.localPath);
        }
        if (result.status !== FileComparisonStatus.ADDED) {
            remoteTooLarge = await isFileTooLarge(result.remotePath);
        }
        if (localTooLarge || remoteTooLarge) {
            fileContents.push({
                result,
                localContent: null,
                remoteContent: null,
                isBinary: false,
                isTooLarge: true
            });
            continue;
        }
        let localContent = null;
        let remoteContent = null;
        try {
            if (result.status !== FileComparisonStatus.DELETED) {
                const localUri = vscode.Uri.file(result.localPath);
                const localData = await vscode.workspace.fs.readFile(localUri);
                localContent = new TextDecoder().decode(localData);
            }
        }
        catch {
            // File may not exist or be readable
            localContent = null;
        }
        try {
            if (result.status !== FileComparisonStatus.ADDED) {
                const remoteUri = vscode.Uri.file(result.remotePath);
                const remoteData = await vscode.workspace.fs.readFile(remoteUri);
                remoteContent = new TextDecoder().decode(remoteData);
            }
        }
        catch {
            // File may not exist or be readable
            remoteContent = null;
        }
        fileContents.push({
            result,
            localContent,
            remoteContent,
            isBinary: false,
            isTooLarge: false
        });
    }
    return fileContents;
}
