function renderConnectorStub(connector) {
  const message = `Connector "${connector.apiName}" (${connector.displayName}) is planned but unavailable in prototype mode. Run /prototype-to-real-app to provision it.`;
  const safePurpose = connector.purpose.replace(/\*\//g, '* /');
  return `// ${GENERATOR_MARKER}\n// Prototype-mode throw-stub for ${connector.displayName}.\n// Planned purpose: ${safePurpose}\nconst MESSAGE = ${JSON.stringify(message)};\n\ntype ConnectorStub = Record<string, (...args: unknown[]) => Promise<unknown>>;\n\nexport const ${connector.serviceName}Service: ConnectorStub = new Proxy({} as ConnectorStub, {\n  get(_target, property: string | symbol) {\n    if (typeof property === 'symbol' || property === 'then' || property === 'toJSON') return undefined;\n    return (..._args: unknown[]) => Promise.reject(new Error(MESSAGE));\n  },\n});\n\nexport default ${connector.serviceName}Service;\n`;
}

function renderStrictService(entity) {
  // Generated row schemas are interfaces without index signatures. Reflect.get
  // keeps user-selected orderBy fields strict-mode compatible without emitting
  // a broad Record assertion into every generated service.
  return renderService(entity)
    .replace('(left as Record<string, unknown>)[field]', 'Reflect.get(left, field)')
    .replace('(right as Record<string, unknown>)[field]', 'Reflect.get(right, field)');
}

function renderDataSourcesInfo(entities, connectors) {
  const serviceExports = entities.map((entity) => `export { ${entity.serviceName}Service } from './${entity.serviceName}Service';`);
  const typeExports = entities.map((entity) => `export type { ${entity.serviceName} } from '../schemas/${entity.serviceName}.Schema';`);
  const connectorExports = connectors.map((connector) => `export { ${connector.serviceName}Service } from './${connector.serviceName}Service';`);
  return `// ${GENERATOR_MARKER}\n${[...serviceExports, ...connectorExports, '', ...typeExports].join('\n')}\n\nexport const REGISTERED_DATA_SOURCES = ${JSON.stringify(entities.map((entity) => entity.logicalName), null, 2)} as const;\nexport const REGISTERED_CONNECTORS = ${JSON.stringify(connectors.map((connector) => connector.apiName), null, 2)} as const;\n`;
}

function writeGeneratedFile(projectDir, relativePath, content, generatedFiles) {
  const filePath = path.join(projectDir, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
  generatedFiles.push(relativePath.split(path.sep).join('/'));
}

function main() {
  const projectArg = process.argv[2];
  if (!projectArg) fail('usage: node gen-mock-services.js <project-dir>');
  const projectDir = path.resolve(projectArg);
  const planPath = path.join(projectDir, 'native-app-plan.md');
  if (!fs.existsSync(projectDir)) fail(`project directory not found: ${projectDir}`);
  if (!fs.existsSync(planPath)) fail(`native-app-plan.md not found under ${projectDir}`);

  const planText = fs.readFileSync(planPath, 'utf8');
  const briefText = readOptional(path.join(projectDir, 'brief.md'));
  const { entities, source } = loadEntities(projectDir, planText);
  const connectors = parseConnectors(planText);
  const duplicate = entities.find((entity, index) => entities.findIndex((candidate) => candidate.logicalName === entity.logicalName) !== index);
  if (duplicate) fail(`duplicate table logicalName in schema contract: ${duplicate.logicalName}`);

  const seedMerge = mergeExistingSeeds(projectDir, entities, `${briefText}\n${planText}`);
  const rowsByEntity = seedMerge.rowsByEntity;
  const generatedFiles = [];
  for (const entity of entities) {
    writeGeneratedFile(projectDir, `src/generated/services/${entity.serviceName}Service.ts`, renderStrictService(entity), generatedFiles);
    writeGeneratedFile(projectDir, `src/generated/services/${entity.serviceName}.seed.json`, `${JSON.stringify(rowsByEntity.get(entity.logicalName), null, 2)}\n`, generatedFiles);
    writeGeneratedFile(projectDir, `src/generated/schemas/${entity.serviceName}.Schema.ts`, renderSchema(entity), generatedFiles);
  }
  for (const connector of connectors) {
    writeGeneratedFile(projectDir, `src/generated/services/${connector.serviceName}Service.ts`, renderConnectorStub(connector), generatedFiles);
  }
  writeGeneratedFile(projectDir, 'src/generated/services/dataSourcesInfo.ts', renderDataSourcesInfo(entities, connectors), generatedFiles);
  writeGeneratedFile(projectDir, 'src/generated/services/index.ts', "// Generated by create-mobile-prototype/gen-mock-services.js\nexport * from './dataSourcesInfo';\n", generatedFiles);
  writeGeneratedFile(projectDir, 'src/generated/index.ts', "// Generated by create-mobile-prototype/gen-mock-services.js\nexport * from './services';\n", generatedFiles);

  const removedGeneratedFiles = archiveStaleGeneratedFiles(
    projectDir,
    seedMerge.previousManifest,
    generatedFiles,
  );

  const regenerationReportPath = path.join(projectDir, '.tmp', 'prototype-seed-regeneration.json');
  fs.mkdirSync(path.dirname(regenerationReportPath), { recursive: true });
  fs.writeFileSync(regenerationReportPath, `${JSON.stringify({
    schemaVersion: 1,
    tables: seedMerge.tableReports,
    removedGeneratedFiles,
  }, null, 2)}\n`);

  const manifestPath = path.join(projectDir, 'src', 'generated', '.prototype-manifest.json');
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, `${JSON.stringify({
    schemaVersion: 1,
    generator: 'create-mobile-prototype/gen-mock-services.js',
    schemaSource: source,
    tables: entities.map((entity) => entity.logicalName),
    tableSchemas: entities.map((entity) => ({
      logicalName: entity.logicalName,
      displayName: entity.displayName,
      serviceName: entity.serviceName,
      seedFile: `src/generated/services/${entity.serviceName}.seed.json`,
      primaryKey: entity.primaryKey,
      dependencyTier: entity.dependencyTier,
      fields: entity.fields.map((field) => ({
        name: field.name,
        type: field.type,
        required: field.required,
        lookupTarget: field.lookupTarget,
        options: field.options,
      })),
    })),
    connectors: connectors.map((connector) => connector.apiName),
    files: generatedFiles,
    seedRegenerationReport: '.tmp/prototype-seed-regeneration.json',
  }, null, 2)}\n`);

  console.log(`prototype-mocks: generated ${entities.length} table service(s) and ${connectors.length} connector stub(s)`);
  console.log(`prototype-mocks: schema source ${source}`);
}

main();