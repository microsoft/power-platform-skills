function fail(message) {
  console.error(`prototype-mocks: ${message}`);
  process.exit(1);
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    fail(`${path.relative(process.cwd(), filePath)} is not valid JSON: ${error.message}`);
  }
}

function readOptional(filePath) {
  return fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
}

function serviceIdentifier(logicalName) {
  const identifier = logicalName.replace(/[^A-Za-z0-9_$]/g, '_');
  return identifier.charAt(0).toUpperCase() + identifier.slice(1);
}

function normalizeType(rawType) {
  const type = String(rawType || 'string').toLowerCase();
  if (['integer', 'bigint', 'decimal', 'double', 'money', 'number', 'int'].includes(type)) return 'number';
  if (['boolean', 'bool', 'yes/no'].includes(type)) return 'boolean';
  if (['choice', 'picklist', 'multiselectchoice'].includes(type)) return 'choice';
  if (['datetime', 'date'].includes(type)) return 'date';
  if (type === 'lookup') return 'lookup';
  if (type === 'image') return 'image';
  if (type === 'file') return 'file';
  return 'string';
}

function normalizeContractTable(table) {
  if (!table || !table.logicalName) fail('schema contract contains a table without logicalName');
  const decision = String(table.plannedDecision || table.decision || '').toLowerCase();
  if (decision === 'defer' || table.serviceRequired === false) return null;

  const logicalName = String(table.logicalName);
  const fields = (table.columns || [])
    .filter((column) => String(column.plannedDecision || column.decision || '').toLowerCase() !== 'defer')
    .map((column) => ({
      name: String(column.logicalName || ''),
      displayName: String(column.displayName || column.logicalName || ''),
      type: normalizeType(column.type || column.attributeType),
      rawType: String(column.type || column.attributeType || 'string'),
      required: /required/i.test(String(column.requiredLevel || '')),
      lookupTarget: column.lookupTarget || column.target || null,
      options: Array.isArray(column.options) ? column.options : [],
      primaryName: column.primaryName === true,
    }))
    .filter((column) => column.name);

  return {
    logicalName,
    displayName: String(table.displayName || logicalName),
    serviceName: serviceIdentifier(logicalName),
    primaryKey: String(table.primaryIdAttribute || `${logicalName}id`),
    dependencyTier: Number.isInteger(table.dependencyTier) ? table.dependencyTier : 0,
    fields,
  };
}

function parseLegacyEntities(markdown) {
  const entities = [];
  const blockPattern = /\*\*([A-Z][\w\s]+?)\*\*\s*\(`([a-z][a-z0-9_]+)`\)[^\n]*\n((?:\s*-\s*`[^`]+`[^\n]*\n?)+)/g;
  let match;
  while ((match = blockPattern.exec(markdown)) !== null) {
    const logicalName = match[2];
    const fields = [];
    for (const line of match[3].split('\n')) {
      const fieldMatch = line.match(/-\s*`([^`]+)`\s*\(([^)]+)\)/);
      if (!fieldMatch) continue;
      const rawType = fieldMatch[2];
      const lookupMatch = rawType.match(/lookup\s*(?:to|->|:)?\s*`?([a-z][a-z0-9_]*)/i);
      fields.push({
        name: fieldMatch[1],
        displayName: fieldMatch[1],
        type: normalizeType(rawType.split(/[,(]/)[0].trim()),
        rawType,
        required: !/nullable|optional/i.test(rawType),
        lookupTarget: lookupMatch ? lookupMatch[1].toLowerCase() : null,
        options: [],
        primaryName: /(^|_)name$/.test(fieldMatch[1]),
      });
    }
    if (fields.length) {
      entities.push({
        logicalName,
        displayName: match[1].trim(),
        serviceName: serviceIdentifier(logicalName),
        primaryKey: `${logicalName}id`,
        fields,
      });
    }
  }
  return entities;
}

function loadEntities(projectDir, planText) {
  const contractPath = path.join(projectDir, '.tmp', 'dataverse-schema-contract.json');
  if (fs.existsSync(contractPath)) {
    const contract = readJson(contractPath);
    if (!Array.isArray(contract.tables)) fail('schema contract must contain a tables array');
    const entities = contract.tables.map(normalizeContractTable).filter(Boolean);
    if (!entities.length) fail('schema contract contains no service-required tables');
    return { entities, source: '.tmp/dataverse-schema-contract.json' };
  }

  const entities = parseLegacyEntities(planText);
  if (!entities.length) {
    fail('no entities found; create .tmp/dataverse-schema-contract.json during planning or use the legacy entity-block format');
  }
  return { entities, source: 'native-app-plan.md (legacy fallback)' };
}

function connectorServiceName(apiName) {
  if (CONNECTOR_SERVICE_NAMES[apiName]) return CONNECTOR_SERVICE_NAMES[apiName];
  return apiName
    .replace(/[^a-z0-9]+/gi, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

function parseConnectors(markdown) {
  const heading = /^##\s+Connectors\s*\n/m.exec(markdown);
  if (!heading) return [];
  const remainder = markdown.slice(heading.index + heading[0].length);
  const nextHeading = remainder.search(/^##\s+/m);
  const body = nextHeading >= 0 ? remainder.slice(0, nextHeading) : remainder;
  if (/^\s*[_*]?none[_*]?\s*(?:-|$)/im.test(body)) return [];

  const connectors = [];
  const rowPattern = /^\|\s*([^|]+?)\s*\|\s*`([a-z0-9_-]+)`\s*\|\s*([^|]+?)\s*\|\s*[^|]+\|\s*$/gim;
  let match;
  while ((match = rowPattern.exec(body)) !== null) {
    if (/^connector$/i.test(match[1].trim())) continue;
    connectors.push({
      displayName: match[1].trim(),
      apiName: match[2].trim(),
      purpose: match[3].trim(),
      serviceName: connectorServiceName(match[2].trim()),
    });
  }
  return connectors;
}

function domainPack(contextText) {
  const lower = contextText.toLowerCase();
  return Object.values(DOMAIN_PACKS).find((pack) => pack.match.test(lower)) || DOMAIN_PACKS.generic;
}

function deterministicGuid(seed) {
  const hex = crypto.createHash('sha256').update(seed).digest('hex').slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function dateValue(index, fieldName) {
  const offsets = /created|modified|completed|closed|submitted/i.test(fieldName)
    ? [-30, -14, -7, -3, -1, 0, -21, -5]
    : [-7, -1, 0, 1, 3, 7, 14, 30];
  const value = new Date('2026-01-15T09:00:00.000Z');
  value.setUTCDate(value.getUTCDate() + offsets[index % offsets.length]);
  return value.toISOString();
}

function resolveLookupTarget(field, entities) {
  if (field.lookupTarget) {
    const target = String(field.lookupTarget).toLowerCase();
    const exact = entities.find((entity) => entity.logicalName.toLowerCase() === target);
    if (exact) return exact;
  }
  const compact = field.name.toLowerCase().replace(/^_/, '').replace(/_value$/, '').replace(/id$/, '').replace(/_/g, '');
  return entities.find((entity) => {
    const logical = entity.logicalName.toLowerCase().replace(/_/g, '');
    return compact === logical || compact.endsWith(logical) || logical.endsWith(compact);
  }) || null;
}

function textValue(field, entity, index, pack) {
  const name = field.name.toLowerCase();
  if (field.primaryName || /(^|_)(name|title|subject)$/.test(name)) return pack.titles[index % pack.titles.length];
  if (/email/.test(name)) return `user${index + 1}@example.com`;
  if (/phone/.test(name)) return `+1-555-01${String(index).padStart(2, '0')}`;
  if (/status|state|phase/.test(name)) return ['Draft', 'In progress', 'Blocked', 'Needs review', 'Complete', 'Overdue', 'Approved', 'Archived'][index % 8];
  if (/priority|severity|risk|urgency/.test(name)) return ['Critical', 'High', 'Medium', 'Low'][index % 4];
  if (/person|contact|owner|assignee|patient|technician|user/.test(name)) return pack.people[index % pack.people.length];
  if (/location|site|store|facility|warehouse|bin|address/.test(name)) return pack.locations[index % pack.locations.length];
  if (/category|type|segment/.test(name)) return pack.categories[index % pack.categories.length];
  if (/description|notes|summary|comment|reason/.test(name)) return pack.notes[index % pack.notes.length];
  return `${entity.displayName} ${index + 1}`;
}

function fieldValue(field, entity, index, entities, rowsByEntity, pack) {
  const target = field.type === 'lookup' ? resolveLookupTarget(field, entities) : null;
  if (target) {
    const parentRows = rowsByEntity.get(target.logicalName) || [];
    return parentRows.length
      ? parentRows[index % parentRows.length][target.primaryKey]
      : deterministicGuid(`${target.logicalName}-${index}`);
  }

  if (field.type === 'number') {
    if (/amount|total|cost|price|budget|revenue/i.test(field.name)) return [42.5, 128.99, 319.45, 875, 1499.95, 12.75, 64.2, 240][index % 8];
    if (/quantity|count|stock|available|variance/i.test(field.name)) return [0, 3, 12, 48, 96, 5, 21, 64][index % 8];
    return index + 1;
  }
  if (field.type === 'boolean') return index % 3 !== 1;
  if (field.type === 'date') return dateValue(index, field.name);
  if (field.type === 'choice' && field.options.length) {
    const option = field.options[index % field.options.length];
    return typeof option === 'object' && option !== null ? option.value : option;
  }
  if (field.type === 'image') {
    return `https://images.unsplash.com/photo-1581092918056-0c4c3acd3789?auto=format&fit=crop&w=640&q=80&ix=${index}`;
  }
  if (field.type === 'file') {
    return JSON.stringify({ fileName: `${entity.logicalName}-${index + 1}.pdf`, mimeType: 'application/pdf', sizeKb: 128 + index * 32 });
  }
  return textValue(field, entity, index, pack);
}

function generateSeeds(entities, contextText) {
  const rowsByEntity = new Map();
  for (const entity of entities) {
    rowsByEntity.set(entity.logicalName, Array.from({ length: 8 }, (_, index) => ({
      [entity.primaryKey]: deterministicGuid(`${entity.logicalName}-${index}`),
    })));
  }

  const pack = domainPack(contextText);
  for (const entity of entities) {
    const rows = rowsByEntity.get(entity.logicalName);
    for (let index = 0; index < rows.length; index += 1) {
      for (const field of entity.fields) {
        if (field.name === entity.primaryKey) continue;
        rows[index][field.name] = fieldValue(field, entity, index, entities, rowsByEntity, pack);
      }
    }
  }
  return rowsByEntity;
}

function loadPreviousPrototype(projectDir, entities) {
  const manifestPath = path.join(projectDir, 'src', 'generated', '.prototype-manifest.json');
  if (!fs.existsSync(manifestPath)) {
    return { manifest: null, rowsByEntity: new Map(), schemaByEntity: new Map() };
  }

  const manifest = readJson(manifestPath);
  const schemaByEntity = new Map(
    (manifest.tableSchemas || []).map((schema) => [schema.logicalName, schema]),
  );
  const rowsByEntity = new Map();
  for (const entity of entities) {
    const previousSchema = schemaByEntity.get(entity.logicalName);
    const relativeSeedPath = previousSchema?.seedFile
      || `src/generated/services/${entity.serviceName}.seed.json`;
    const seedPath = path.join(projectDir, relativeSeedPath);
    if (!fs.existsSync(seedPath)) continue;
    const rows = readJson(seedPath);
    if (!Array.isArray(rows)) fail(`${relativeSeedPath} must contain a JSON array`);
    rowsByEntity.set(entity.logicalName, rows);
  }
  return { manifest, rowsByEntity, schemaByEntity };
}

function seedValueIsCompatible(field, value, previousField, validIdsByEntity, entities) {
  if (value === null || value === undefined) return !field.required;
  if (previousField && previousField.type !== field.type) return false;
  if (field.type === 'number') return typeof value === 'number' && Number.isFinite(value);
  if (field.type === 'boolean') return typeof value === 'boolean';
  if (field.type === 'choice') {
    if (typeof value !== 'number' || !Number.isFinite(value)) return false;
    if (!field.options.length) return true;
    return field.options.some((option) => {
      const optionValue = typeof option === 'object' && option !== null ? option.value : option;
      return optionValue === value;
    });
  }
  if (field.type === 'lookup') {
    if (typeof value !== 'string') return false;
    const target = resolveLookupTarget(field, entities);
    return !target || (validIdsByEntity.get(target.logicalName) || new Set()).has(value);
  }
  return typeof value === 'string';
}

function mergeExistingSeeds(projectDir, entities, contextText) {
  const generatedRows = generateSeeds(entities, contextText);
  const previous = loadPreviousPrototype(projectDir, entities);
  const validIdsByEntity = new Map();

  for (const entity of entities) {
    const ids = new Set();
    for (const row of previous.rowsByEntity.get(entity.logicalName) || []) {
      if (typeof row?.[entity.primaryKey] === 'string') ids.add(row[entity.primaryKey]);
    }
    for (const row of generatedRows.get(entity.logicalName) || []) ids.add(row[entity.primaryKey]);
    validIdsByEntity.set(entity.logicalName, ids);
  }

  const rowsByEntity = new Map();
  const tableReports = [];
  for (const entity of [...entities].sort((left, right) => left.dependencyTier - right.dependencyTier)) {
    const existingRows = previous.rowsByEntity.get(entity.logicalName) || [];
    const baselineRows = generatedRows.get(entity.logicalName) || [];
    const previousSchema = previous.schemaByEntity.get(entity.logicalName);
    const previousFields = new Map(
      (previousSchema?.fields || []).map((field) => [field.name, field]),
    );
    const currentFields = new Set(entity.fields.map((field) => field.name));
    const addedFields = entity.fields
      .filter((field) => !previousFields.has(field.name))
      .map((field) => field.name);
    const removedFields = [...previousFields.keys()].filter((field) => !currentFields.has(field));
    const regeneratedFields = new Set();

    const mergedRows = existingRows.length
      ? existingRows.map((existingRow, index) => {
        const baseline = baselineRows[index % Math.max(1, baselineRows.length)] || {};
        const merged = {
          [entity.primaryKey]: typeof existingRow?.[entity.primaryKey] === 'string'
            ? existingRow[entity.primaryKey]
            : deterministicGuid(`${entity.logicalName}-${index}`),
        };
        for (const field of entity.fields) {
          if (field.name === entity.primaryKey) continue;
          const existingValue = existingRow?.[field.name];
          if (Object.prototype.hasOwnProperty.call(existingRow || {}, field.name)
            && seedValueIsCompatible(
              field,
              existingValue,
              previousFields.get(field.name),
              validIdsByEntity,
              entities,
            )) {
            merged[field.name] = existingValue;
          } else {
            merged[field.name] = baseline[field.name];
            if (Object.prototype.hasOwnProperty.call(existingRow || {}, field.name)) {
              regeneratedFields.add(field.name);
            }
          }
        }
        return merged;
      })
      : baselineRows;

    rowsByEntity.set(entity.logicalName, mergedRows);
    tableReports.push({
      logicalName: entity.logicalName,
      rows: mergedRows.length,
      preservedRows: existingRows.length,
      addedFields,
      removedFields,
      regeneratedFields: [...regeneratedFields].sort(),
    });
  }

  return { rowsByEntity, previousManifest: previous.manifest, tableReports };
}

function archiveStaleGeneratedFiles(projectDir, previousManifest, generatedFiles) {
  if (!previousManifest || !Array.isArray(previousManifest.files)) return [];
  const generatedSet = new Set(generatedFiles);
  const removed = [];
  const archiveRoot = path.join(projectDir, '.tmp', 'prototype-seed-archive');

  for (const relativePath of previousManifest.files) {
    if (generatedSet.has(relativePath)) continue;
    const normalized = String(relativePath).split('\\').join('/');
    if (!normalized.startsWith('src/generated/')) continue;
    const filePath = path.join(projectDir, normalized);
    if (!fs.existsSync(filePath)) continue;
    if (normalized.endsWith('.seed.json')) {
      const archivePath = path.join(archiveRoot, normalized);
      fs.mkdirSync(path.dirname(archivePath), { recursive: true });
      fs.copyFileSync(filePath, archivePath);
      fs.rmSync(filePath, { force: true });
      removed.push({ file: normalized, archivedTo: path.relative(projectDir, archivePath).split(path.sep).join('/') });
      continue;
    }
    const contents = readOptional(filePath);
    if (contents.includes(GENERATOR_MARKER)) {
      fs.rmSync(filePath, { force: true });
      removed.push({ file: normalized, archivedTo: null });
    }
  }
  return removed;
}

function schemaType(field) {
  if (field.type === 'number' || field.type === 'choice') return 'number';
  if (field.type === 'boolean') return 'boolean';
  return 'string';
}

function renderSchema(entity) {
  const properties = [`  ${JSON.stringify(entity.primaryKey)}: string;`];
  for (const field of entity.fields) {
    if (field.name === entity.primaryKey) continue;
    properties.push(`  ${JSON.stringify(field.name)}${field.required ? '' : '?'}: ${schemaType(field)};`);
  }
  return `// ${GENERATOR_MARKER}\n// Prototype schema for ${entity.logicalName}; real generated models replace this during graduation.\nexport interface ${entity.serviceName} {\n${properties.join('\n')}\n}\n`;
}

