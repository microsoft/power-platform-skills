#!/usr/bin/env node
'use strict';

/**
 * Generate local, in-memory service implementations for a mobile prototype.
 *
 * The current planner writes a normalized Dataverse schema contract under
 * `.tmp/dataverse-schema-contract.json`. Reading that contract first avoids
 * rebuilding executable schema from human-oriented Markdown. A small legacy
 * parser remains for prototypes created by the earlier test-branch workflow.
 *
 * Usage: node gen-mock-services.js <project-dir>
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const IMAGE_PLACEHOLDER_PATH = path.resolve(__dirname, '../../../template/assets/image-placeholder.png');
let imagePlaceholderDataUri;

const { validateVocabulary } = require('../../../scripts/validate-seed-vocabulary');

const GENERATOR_MARKER = 'Generated by create-mobile-prototype/gen-mock-services.js';

const CONNECTOR_SERVICE_NAMES = {
  sharepointonline: 'SharePointOnline',
  office365: 'Office365',
  office365users: 'Office365Users',
  office365groups: 'Office365Groups',
  outlook: 'Office365Outlook',
  teams: 'Teams',
  excelonlinebusiness: 'ExcelOnlineBusiness',
  onedriveforbusiness: 'OneDriveForBusiness',
  azuredevops: 'AzureDevOps',
  azureblob: 'AzureBlob',
  azurequeues: 'AzureQueues',
  mcscopilot: 'McsCopilot',
  sql: 'Sql',
};

function fail(message) {
  console.error(`prototype-mocks: ${message}`);
  process.exit(1);
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    fail(`${path.relative(process.cwd(), filePath)} is not valid JSON: ${error.message}`);
  }
}

function readOptional(filePath) {
  return fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
}

function loadVocabulary(projectDir) {
  const vocabularyPath = path.join(projectDir, '.tmp', 'seed-vocabulary.json');
  if (!fs.existsSync(vocabularyPath)) {
    fail('missing .tmp/seed-vocabulary.json; derive it from brief.md before generating mocks');
  }
  const vocabulary = readJson(vocabularyPath);
  const briefText = readOptional(path.join(projectDir, 'brief.md'));
  const validation = validateVocabulary(vocabulary, {
    ...(briefText ? { briefText } : {}),
  });
  if (!validation.valid) {
    fail(`invalid .tmp/seed-vocabulary.json: ${validation.errors.join('; ')}`);
  }
  return vocabulary;
}

function serviceIdentifier(logicalName) {
  const identifier = logicalName.replace(/[^A-Za-z0-9_$]/g, '_');
  return identifier.charAt(0).toUpperCase() + identifier.slice(1);
}

function normalizeType(rawType) {
  const type = String(rawType || 'string').toLowerCase();
  if (['integer', 'bigint', 'decimal', 'double', 'money', 'number', 'int'].includes(type)) return 'number';
  if (['boolean', 'bool', 'yes/no'].includes(type)) return 'boolean';
  if (['choice', 'picklist', 'multiselectchoice'].includes(type)) return 'choice';
  if (['datetime', 'date'].includes(type)) return 'date';
  if (type === 'lookup') return 'lookup';
  if (type === 'image') return 'image';
  if (type === 'file') return 'file';
  return 'string';
}

function normalizeContractTable(table) {
  if (!table || !table.logicalName) fail('schema contract contains a table without logicalName');
  const decision = String(table.plannedDecision || table.decision || '').toLowerCase();
  if (decision === 'defer' || table.serviceRequired === false) return null;

  const logicalName = String(table.logicalName);
  const fields = (table.columns || [])
    .filter((column) => String(column.plannedDecision || column.decision || '').toLowerCase() !== 'defer')
    .map((column) => ({
      name: String(column.logicalName || ''),
      displayName: String(column.displayName || column.logicalName || ''),
      type: normalizeType(column.type || column.attributeType),
      rawType: String(column.type || column.attributeType || 'string'),
      required: /required/i.test(String(column.requiredLevel || '')),
      lookupTarget: column.lookupTarget || column.target || null,
      options: Array.isArray(column.options) ? column.options : [],
      primaryName: column.primaryName === true,
      minValue: Number.isFinite(column.minValue) ? column.minValue : null,
      maxValue: Number.isFinite(column.maxValue) ? column.maxValue : null,
    }))
    .filter((column) => column.name);

  return {
    logicalName,
    displayName: String(table.displayName || logicalName),
    serviceName: serviceIdentifier(logicalName),
    primaryKey: String(table.primaryIdAttribute || `${logicalName}id`),
    dependencyTier: Number.isInteger(table.dependencyTier) ? table.dependencyTier : 0,
    fields,
  };
}

function parseLegacyEntities(markdown) {
  const entities = [];
  const blockPattern = /\*\*([A-Z][\w\s]+?)\*\*\s*\(`([a-z][a-z0-9_]+)`\)[^\n]*\n((?:\s*-\s*`[^`]+`[^\n]*\n?)+)/g;
  let match;
  while ((match = blockPattern.exec(markdown)) !== null) {
    const logicalName = match[2];
    const fields = [];
    for (const line of match[3].split('\n')) {
      const fieldMatch = line.match(/-\s*`([^`]+)`\s*\(([^)]+)\)/);
      if (!fieldMatch) continue;
      const rawType = fieldMatch[2];
      const lookupMatch = rawType.match(/lookup\s*(?:to|->|:)?\s*`?([a-z][a-z0-9_]*)/i);
      fields.push({
        name: fieldMatch[1],
        displayName: fieldMatch[1],
        type: normalizeType(rawType.split(/[,(]/)[0].trim()),
        rawType,
        required: !/nullable|optional/i.test(rawType),
        lookupTarget: lookupMatch ? lookupMatch[1].toLowerCase() : null,
        options: [],
        primaryName: /(^|_)name$/.test(fieldMatch[1]),
      });
    }
    if (fields.length) {
      entities.push({
        logicalName,
        displayName: match[1].trim(),
        serviceName: serviceIdentifier(logicalName),
        primaryKey: `${logicalName}id`,
        fields,
      });
    }
  }
  return entities;
}

function loadEntities(projectDir, planText) {
  const contractPath = path.join(projectDir, '.tmp', 'dataverse-schema-contract.json');
  if (fs.existsSync(contractPath)) {
    const contract = readJson(contractPath);
    if (!Array.isArray(contract.tables)) fail('schema contract must contain a tables array');
    const entities = contract.tables.map(normalizeContractTable).filter(Boolean);
    if (!entities.length) fail('schema contract contains no service-required tables');
    return { entities, source: '.tmp/dataverse-schema-contract.json' };
  }

  const entities = parseLegacyEntities(planText);
  if (!entities.length) {
    fail('no entities found; create .tmp/dataverse-schema-contract.json during planning or use the legacy entity-block format');
  }
  return { entities, source: 'native-app-plan.md (legacy fallback)' };
}

function connectorServiceName(apiName) {
  if (CONNECTOR_SERVICE_NAMES[apiName]) return CONNECTOR_SERVICE_NAMES[apiName];
  return apiName
    .replace(/[^a-z0-9]+/gi, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

function parseConnectors(markdown) {
  const heading = /^##\s+Connectors\s*\n/m.exec(markdown);
  if (!heading) return [];
  const remainder = markdown.slice(heading.index + heading[0].length);
  const nextHeading = remainder.search(/^##\s+/m);
  const body = nextHeading >= 0 ? remainder.slice(0, nextHeading) : remainder;
  if (/^\s*[_*]?none[_*]?\s*(?:-|$)/im.test(body)) return [];

  const connectors = [];
  const rowPattern = /^\|\s*([^|]+?)\s*\|\s*`([a-z0-9_-]+)`\s*\|\s*([^|]+?)\s*\|\s*[^|]+\|\s*$/gim;
  let match;
  while ((match = rowPattern.exec(body)) !== null) {
    if (/^connector$/i.test(match[1].trim())) continue;
    connectors.push({
      displayName: match[1].trim(),
      apiName: match[2].trim(),
      purpose: match[3].trim(),
      serviceName: connectorServiceName(match[2].trim()),
    });
  }
  return connectors;
}

function deterministicGuid(seed) {
  const hex = crypto.createHash('sha256').update(seed).digest('hex').slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function hashNumber(value) {
  return Number.parseInt(crypto.createHash('sha256').update(String(value)).digest('hex').slice(0, 8), 16);
}

function greatestCommonDivisor(left, right) {
  let a = Math.abs(left);
  let b = Math.abs(right);
  while (b) [a, b] = [b, a % b];
  return a;
}

function requirePool(vocabulary, poolName, context) {
  const pool = vocabulary.pools?.[poolName];
  if (!Array.isArray(pool) || pool.length === 0) {
    fail(`seed vocabulary pool "${poolName}" is required for ${context}`);
  }
  return pool;
}

function localImagePlaceholder() {
  if (imagePlaceholderDataUri) return imagePlaceholderDataUri;
  if (!fs.existsSync(IMAGE_PLACEHOLDER_PATH)) {
    fail(`local image placeholder is missing: ${IMAGE_PLACEHOLDER_PATH}`);
  }
  imagePlaceholderDataUri = `data:image/png;base64,${fs.readFileSync(IMAGE_PLACEHOLDER_PATH).toString('base64')}`;
  return imagePlaceholderDataUri;
}

function pickPool(vocabulary, poolName, index, seed) {
  const pool = requirePool(vocabulary, poolName, seed);
  if (pool.length === 1) return pool[0];
  const hash = hashNumber(`${vocabulary.domain}:${seed}`);
  const offset = hash % pool.length;
  let stride = 1 + (hash % (pool.length - 1));
  while (greatestCommonDivisor(stride, pool.length) !== 1) {
    stride = (stride % (pool.length - 1)) + 1;
  }
  return pool[(offset + index * stride) % pool.length];
}

function formatId(vocabulary, formatName, index, seed) {
  const format = vocabulary.idFormats?.[formatName];
  if (typeof format !== 'string' || !format.trim()) {
    fail(`seed vocabulary idFormats.${formatName} is required for ${seed}`);
  }
  const hash = hashNumber(`${vocabulary.domain}:${seed}`);
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  return format
    .replaceAll('{seq4}', String(1041 + (hash % 31) + index * 7).padStart(4, '0'))
    .replaceAll('{seq3}', String(11 + (hash % 17) + index * 3).padStart(3, '0'))
    .replaceAll('{year}', String(new Date().getUTCFullYear()))
    .replaceAll('{ALPHA2}', `${alphabet[hash % alphabet.length]}${alphabet[(hash + index * 5 + 3) % alphabet.length]}`);
}

function dateValue(index, fieldName) {
  const name = semanticFieldName(fieldName);
  const cycle = index % 12;
  const variant = hashNumber(name) % 5;
  let offset;
  if (/created/.test(name)) offset = -30 + cycle;
  else if (/issued|completed|closed/.test(name)) offset = -24 + cycle + variant;
  else if (/validfrom|start|fromdate/.test(name)) offset = -7 + cycle;
  else if (/validto|expiry|expires|end|until|todate/.test(name)) offset = 23 + cycle + variant;
  else if (/modified|submitted/.test(name)) offset = -14 + cycle + variant;
  else offset = -5 + ((cycle * 3 + variant) % 31);
  const value = new Date();
  value.setUTCHours(9, 0, 0, 0);
  value.setUTCDate(value.getUTCDate() + offset);
  return value.toISOString();
}

function resolveLookupTarget(field, entities) {
  if (field.lookupTarget) {
    const target = String(field.lookupTarget).toLowerCase();
    const exact = entities.find((entity) => entity.logicalName.toLowerCase() === target);
    if (exact) return exact;
  }
  const compact = field.name.toLowerCase().replace(/^_/, '').replace(/_value$/, '').replace(/id$/, '').replace(/_/g, '');
  return entities.find((entity) => {
    const logical = entity.logicalName.toLowerCase().replace(/_/g, '');
    return compact === logical || compact.endsWith(logical) || logical.endsWith(compact);
  }) || null;
}

function semanticFieldName(fieldName) {
  return String(fieldName).toLowerCase().replace(/^[a-z][a-z0-9]*_/, '');
}

function slug(value) {
  return String(value)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '.')
    .replace(/^\.|\.$/g, '');
}

function primaryNamePool(entity) {
  const entityName = `${entity.logicalName} ${entity.displayName}`.toLowerCase();
  if (/category|type|segment/.test(entityName)) return 'category';
  if (/staff|member|user|person|contact|employee|approver|visitor/.test(entityName)) return 'person';
  if (/door|room|gate|entrance|zone|area/.test(entityName)) return 'door';
  if (/building|site|location|facility|depot|warehouse|premises/.test(entityName)) return 'location';
  return 'title';
}

function textValue(field, entity, index, vocabulary) {
  const name = semanticFieldName(field.name);
  const seed = `${entity.logicalName}:${field.name}`;
  if (/serial|badgeno|badgenumber|sku/.test(name)) return formatId(vocabulary, 'serial', index, seed);
  if (/reference|refno|requestno|ticket|orderno|caseno/.test(name)) return formatId(vocabulary, 'reference', index, seed);
  if (/code$|itemcode|doorcode|areacode/.test(name)) return formatId(vocabulary, 'code', index, seed);
  if (/brand|company|supplier|vendor|organisation|organization|employer/.test(name)) {
    return pickPool(vocabulary, 'company', index, seed);
  }
  if (/subjectname|personname|passenger|visitor|holder|candidate|guest/.test(name)) {
    return pickPool(vocabulary, 'person', index, seed);
  }
  if (field.primaryName || /(^|_)(name|title|subject)$/.test(field.name.toLowerCase())) {
    const entityName = `${entity.logicalName} ${entity.displayName}`.toLowerCase();
    if (/cart|order/.test(entityName) && !/item|line/.test(entityName)) {
      return formatId(vocabulary, 'reference', index, seed);
    }
    return pickPool(vocabulary, primaryNamePool(entity), index, seed);
  }
  if (/email/.test(name)) {
    const person = pickPool(vocabulary, 'person', index, `${seed}:person`);
    const company = pickPool(vocabulary, 'company', index, `${seed}:company`);
    return `${slug(person)}@${slug(company).replaceAll('.', '')}.example`;
  }
  if (/phone|mobile/.test(name)) {
    const number = String(hashNumber(`${vocabulary.domain}:${seed}:${index}`) % 10000000).padStart(7, '0');
    return `+1-555-${number.slice(0, 3)}-${number.slice(3)}`;
  }
  if (/status|state|phase/.test(name)) return pickPool(vocabulary, 'status', index, seed);
  if (/priority|severity|risk|urgency/.test(name)) return pickPool(vocabulary, 'priority', index, seed);
  if (/role|position/.test(name)) return pickPool(vocabulary, 'role', index, seed);
  if (/person|contact|owner|assignee|patient|technician|user/.test(name)) {
    return pickPool(vocabulary, 'person', index, seed);
  }
  if (/seat/.test(name)) return pickPool(vocabulary, 'seat', index, seed);
  if (/flight/.test(name)) return pickPool(vocabulary, 'flight', index, seed);
  if (/door|room|gate|entrance|zone|area/.test(name)) return pickPool(vocabulary, 'door', index, seed);
  if (/location|site|store|facility|warehouse|bin|address/.test(name)) {
    return pickPool(vocabulary, 'location', index, seed);
  }
  if (/category|type|segment/.test(name)) return pickPool(vocabulary, 'category', index, seed);
  if (/description|notes|summary|comment|reason/.test(name)) return pickPool(vocabulary, 'note', index, seed);
  if (/image|photo|thumbnail/.test(name)) return localImagePlaceholder();
  if (/url|website/.test(name)) return pickPool(vocabulary, 'url', index, seed);
  return pickPool(vocabulary, 'title', index, seed);
}

function uniqueLookupOffset(field, entity, target, entities, parentCount) {
  const siblings = entity.fields
    .filter((candidate) => candidate.type === 'lookup')
    .filter((candidate) => resolveLookupTarget(candidate, entities)?.logicalName === target.logicalName)
    .sort((left, right) => left.name.localeCompare(right.name));
  const offsets = new Map();
  const used = new Set();
  for (const sibling of siblings) {
    let offset = hashNumber(sibling.name) % parentCount;
    while (used.has(offset) && used.size < parentCount) offset = (offset + 1) % parentCount;
    used.add(offset);
    offsets.set(sibling.name, offset);
  }
  return offsets.get(field.name) ?? 0;
}

function numericValue(field, entity, index, vocabulary) {
  const name = semanticFieldName(field.name);
  const numericFields = entity.fields
    .filter((candidate) => candidate.type === 'number')
    .sort((left, right) => left.name.localeCompare(right.name));
  const ordinal = Math.max(0, numericFields.findIndex((candidate) => candidate.name === field.name));
  const hash = hashNumber(`${vocabulary.domain}:${field.name}`);
  const stride = 2 + (hash % 11);
  const offset = hash % 17;
  if (/latitude|^lat$|lat$/.test(name)) {
    return Number((-55 + (hash % 110) + ((index * stride + offset) % 1000) / 1000).toFixed(5));
  }
  if (/longitude|^lon$|^lng$|long$/.test(name)) {
    return Number((-150 + (hash % 300) + ((index * stride + offset) % 1000) / 1000).toFixed(5));
  }
  if (/amount|total|cost|price|budget|revenue|fee/.test(name) || /money|decimal|double/.test(field.rawType.toLowerCase())) {
    return Number((19.5 + ordinal * 23 + ((index + 1) * stride + offset) * 4.25).toFixed(2));
  }
  if (/damaged/.test(name)) return (index * stride + offset) % 5;
  if (/expected/.test(name)) return 80 + ((index * stride + offset) % 40);
  if (/received/.test(name)) return 40 + ((index * stride + offset) % 40);
  if (/variance/.test(name)) return ((index * stride + offset) % 11) - 5;
  if (/qty|quantity|count|stock|available|pallet|carton/.test(name)) {
    const candidates = /available|stock/.test(name)
      ? [0, 1, 2, 3, 5, 8, 12, 16]
      : [1, 1, 2, 2, 3, 4];
    const value = candidates[(index * stride + offset + ordinal) % candidates.length];
    return Math.min(
      field.maxValue ?? value,
      Math.max(field.minValue ?? value, value),
    );
  }
  return 1 + ((index * stride + offset + ordinal * 19) % 997);
}

function fieldValue(field, entity, index, entities, rowsByEntity, vocabulary) {
  const target = field.type === 'lookup' ? resolveLookupTarget(field, entities) : null;
  if (target) {
    const parentRows = rowsByEntity.get(target.logicalName) || [];
    if (!parentRows.length) return deterministicGuid(`${target.logicalName}:${field.name}:${index}`);
    const offset = uniqueLookupOffset(field, entity, target, entities, parentRows.length);
    return parentRows[(index + offset) % parentRows.length][target.primaryKey];
  }

  if (field.type === 'number') return numericValue(field, entity, index, vocabulary);
  if (field.type === 'boolean') return (index + hashNumber(field.name)) % 3 !== 1;
  if (field.type === 'date') return dateValue(index, field.name);
  if (field.type === 'choice' && field.options.length) {
    const option = field.options[index % field.options.length];
    return typeof option === 'object' && option !== null ? option.value : option;
  }
  if (field.type === 'image') return localImagePlaceholder();
  if (field.type === 'file') {
    const fileName = `${slug(pickPool(vocabulary, 'title', index, `${entity.logicalName}:${field.name}`))}-${formatId(vocabulary, 'reference', index, field.name)}.pdf`;
    return JSON.stringify({ fileName, mimeType: 'application/pdf', sizeKb: 128 + index * 32 });
  }
  return textValue(field, entity, index, vocabulary);
}

function generateSeeds(entities, vocabulary) {
  const rowsByEntity = new Map();
  for (const entity of entities) {
    const entityName = `${entity.logicalName} ${entity.displayName}`.toLowerCase();
    const rowCount = /category/.test(entityName)
      ? requirePool(vocabulary, 'category', entity.logicalName).length
      : vocabulary.rowCount;
    rowsByEntity.set(entity.logicalName, Array.from({ length: rowCount }, (_, index) => ({
      [entity.primaryKey]: deterministicGuid(`${entity.logicalName}-${index}`),
    })));
  }

  for (const entity of entities) {
    const rows = rowsByEntity.get(entity.logicalName);
    for (let index = 0; index < rows.length; index += 1) {
      for (const field of entity.fields) {
        if (field.name === entity.primaryKey) continue;
        rows[index][field.name] = fieldValue(field, entity, index, entities, rowsByEntity, vocabulary);
      }
    }
  }

  const orderItems = rowsByEntity.get('cr_orderitem') || [];
  for (const row of orderItems) {
    if (typeof row.cr_quantity === 'number' && typeof row.cr_unitprice === 'number') {
      row.cr_lineamount = Number((row.cr_quantity * row.cr_unitprice).toFixed(2));
    }
  }
  const orders = rowsByEntity.get('cr_order') || [];
  for (const row of orders) {
    const matchingItems = orderItems.filter((item) => item.cr_orderid === row.cr_orderid);
    if (matchingItems.length) {
      row.cr_totalamount = Number(
        matchingItems.reduce((total, item) => total + item.cr_lineamount, 0).toFixed(2),
      );
    }
  }

  return rowsByEntity;
}

function loadPreviousPrototype(projectDir, entities) {
  const manifestPath = path.join(projectDir, 'src', 'generated', '.prototype-manifest.json');
  if (!fs.existsSync(manifestPath)) {
    return { manifest: null, rowsByEntity: new Map(), schemaByEntity: new Map() };
  }

  const manifest = readJson(manifestPath);
  const schemaByEntity = new Map(
    (manifest.tableSchemas || []).map((schema) => [schema.logicalName, schema]),
  );
  const rowsByEntity = new Map();
  for (const entity of entities) {
    const previousSchema = schemaByEntity.get(entity.logicalName);
    const relativeSeedPath = previousSchema?.seedFile
      || `src/generated/services/${entity.serviceName}.seed.json`;
    const seedPath = path.join(projectDir, relativeSeedPath);
    if (!fs.existsSync(seedPath)) continue;
    const rows = readJson(seedPath);
    if (!Array.isArray(rows)) fail(`${relativeSeedPath} must contain a JSON array`);
    rowsByEntity.set(entity.logicalName, rows);
  }
  return { manifest, rowsByEntity, schemaByEntity };
}

function seedValueIsCompatible(field, value, previousField, validIdsByEntity, entities) {
  if (value === null || value === undefined) return !field.required;
  if (previousField && previousField.type !== field.type) return false;
  if (field.type === 'number') return typeof value === 'number' && Number.isFinite(value);
  if (field.type === 'boolean') return typeof value === 'boolean';
  if (field.type === 'choice') {
    if (typeof value !== 'number' || !Number.isFinite(value)) return false;
    if (!field.options.length) return true;
    return field.options.some((option) => {
      const optionValue = typeof option === 'object' && option !== null ? option.value : option;
      return optionValue === value;
    });
  }
  if (field.type === 'lookup') {
    if (typeof value !== 'string') return false;
    const target = resolveLookupTarget(field, entities);
    return !target || (validIdsByEntity.get(target.logicalName) || new Set()).has(value);
  }
  return typeof value === 'string';
}

function mergeExistingSeeds(projectDir, entities, vocabulary) {
  const seedVocabularySha256 = crypto
    .createHash('sha256')
    .update(JSON.stringify(vocabulary))
    .digest('hex');
  const seedProfile = `vocabulary-${seedVocabularySha256.slice(0, 16)}`;
  const generatedRows = generateSeeds(entities, vocabulary);
  const previous = loadPreviousPrototype(projectDir, entities);
  const preservePrevious = previous.manifest?.seedProfile === seedProfile;
  const previousRowsByEntity = preservePrevious ? previous.rowsByEntity : new Map();
  const previousSchemaByEntity = preservePrevious ? previous.schemaByEntity : new Map();
  const validIdsByEntity = new Map();

  for (const entity of entities) {
    const ids = new Set();
    for (const row of previousRowsByEntity.get(entity.logicalName) || []) {
      if (typeof row?.[entity.primaryKey] === 'string') ids.add(row[entity.primaryKey]);
    }
    for (const row of generatedRows.get(entity.logicalName) || []) ids.add(row[entity.primaryKey]);
    validIdsByEntity.set(entity.logicalName, ids);
  }

  const rowsByEntity = new Map();
  const tableReports = [];
  for (const entity of [...entities].sort((left, right) => left.dependencyTier - right.dependencyTier)) {
    const existingRows = previousRowsByEntity.get(entity.logicalName) || [];
    const baselineRows = generatedRows.get(entity.logicalName) || [];
    const previousSchema = previousSchemaByEntity.get(entity.logicalName);
    const previousFields = new Map(
      (previousSchema?.fields || []).map((field) => [field.name, field]),
    );
    const currentFields = new Set(entity.fields.map((field) => field.name));
    const addedFields = entity.fields
      .filter((field) => !previousFields.has(field.name))
      .map((field) => field.name);
    const removedFields = [...previousFields.keys()].filter((field) => !currentFields.has(field));
    const regeneratedFields = new Set();

    const mergedRows = existingRows.length
      ? existingRows.map((existingRow, index) => {
        const baseline = baselineRows[index % Math.max(1, baselineRows.length)] || {};
        const merged = {
          [entity.primaryKey]: typeof existingRow?.[entity.primaryKey] === 'string'
            ? existingRow[entity.primaryKey]
            : deterministicGuid(`${entity.logicalName}-${index}`),
        };
        for (const field of entity.fields) {
          if (field.name === entity.primaryKey) continue;
          const existingValue = existingRow?.[field.name];
          if (Object.prototype.hasOwnProperty.call(existingRow || {}, field.name)
            && seedValueIsCompatible(
              field,
              existingValue,
              previousFields.get(field.name),
              validIdsByEntity,
              entities,
            )) {
            merged[field.name] = existingValue;
          } else {
            merged[field.name] = baseline[field.name];
            if (Object.prototype.hasOwnProperty.call(existingRow || {}, field.name)) {
              regeneratedFields.add(field.name);
            }
          }
        }
        return merged;
      })
      : baselineRows;

    rowsByEntity.set(entity.logicalName, mergedRows);
    tableReports.push({
      logicalName: entity.logicalName,
      rows: mergedRows.length,
      preservedRows: existingRows.length,
      addedFields,
      removedFields,
      regeneratedFields: [...regeneratedFields].sort(),
    });
  }

  return {
    rowsByEntity,
    previousManifest: previous.manifest,
    seedProfile,
    seedVocabularySha256,
    tableReports,
  };
}

function archiveStaleGeneratedFiles(projectDir, previousManifest, generatedFiles) {
  if (!previousManifest || !Array.isArray(previousManifest.files)) return [];
  const generatedSet = new Set(generatedFiles);
  const removed = [];
  const archiveRoot = path.join(projectDir, '.tmp', 'prototype-seed-archive');

  for (const relativePath of previousManifest.files) {
    if (generatedSet.has(relativePath)) continue;
    const normalized = String(relativePath).split('\\').join('/');
    if (!normalized.startsWith('src/generated/')) continue;
    const filePath = path.join(projectDir, normalized);
    if (!fs.existsSync(filePath)) continue;
    if (normalized.endsWith('.seed.json')) {
      const archivePath = path.join(archiveRoot, normalized);
      fs.mkdirSync(path.dirname(archivePath), { recursive: true });
      fs.copyFileSync(filePath, archivePath);
      fs.rmSync(filePath, { force: true });
      removed.push({ file: normalized, archivedTo: path.relative(projectDir, archivePath).split(path.sep).join('/') });
      continue;
    }
    const contents = readOptional(filePath);
    if (contents.includes(GENERATOR_MARKER)) {
      fs.rmSync(filePath, { force: true });
      removed.push({ file: normalized, archivedTo: null });
    }
  }
  return removed;
}

function schemaType(field) {
  if (field.type === 'number' || field.type === 'choice') return 'number';
  if (field.type === 'boolean') return 'boolean';
  return 'string';
}

function renderSchema(entity) {
  const properties = [`  ${JSON.stringify(entity.primaryKey)}: string;`];
  for (const field of entity.fields) {
    if (field.name === entity.primaryKey) continue;
    properties.push(`  ${JSON.stringify(field.name)}${field.required ? '' : '?'}: ${schemaType(field)};`);
  }
  return `// ${GENERATOR_MARKER}\n// Prototype schema for ${entity.logicalName}; real generated models replace this during graduation.\nexport interface ${entity.serviceName} {\n${properties.join('\n')}\n}\n`;
}

function renderService(entity) {
  return `// ${GENERATOR_MARKER}\n// In-memory prototype service. State resets when the JavaScript bundle reloads.\nimport seedRows from './${entity.serviceName}.seed.json';\nimport type { ${entity.serviceName} } from '../schemas/${entity.serviceName}.Schema';\n\nlet _rows: ${entity.serviceName}[] | null = null;\n\nfunction load(): ${entity.serviceName}[] {\n  if (_rows === null) _rows = JSON.parse(JSON.stringify(seedRows)) as ${entity.serviceName}[];\n  return _rows;\n}\n\nfunction newId(): string {\n  return 'xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx'.replace(/x/g, () => Math.floor(Math.random() * 16).toString(16));\n}\n\nexport type ${entity.serviceName}GetAllOptions = {\n  orderBy?: string;\n  top?: number;\n};\n\nexport const ${entity.serviceName}Service = {\n  async getAll(options?: ${entity.serviceName}GetAllOptions): Promise<${entity.serviceName}[]> {\n    let result = [...load()];\n    if (options?.orderBy) {\n      const [field, direction = 'asc'] = options.orderBy.split(/\\s+/);\n      result.sort((left, right) => {\n        const a = (left as Record<string, unknown>)[field];\n        const b = (right as Record<string, unknown>)[field];\n        if (a === b) return 0;\n        const comparison = String(a).localeCompare(String(b), undefined, { numeric: true });\n        return direction.toLowerCase() === 'desc' ? -comparison : comparison;\n      });\n    }\n    return options?.top ? result.slice(0, options.top) : result;\n  },\n  async getById(id: string): Promise<${entity.serviceName} | undefined> {\n    return load().find((row) => row[${JSON.stringify(entity.primaryKey)}] === id);\n  },\n  async create(input: Omit<${entity.serviceName}, ${JSON.stringify(entity.primaryKey)}>): Promise<${entity.serviceName}> {\n    const created = { ...input, [${JSON.stringify(entity.primaryKey)}]: newId() } as ${entity.serviceName};\n    _rows = [...load(), created];\n    return created;\n  },\n  async update(id: string, patch: Partial<${entity.serviceName}>): Promise<${entity.serviceName}> {\n    const currentRows = load();
    const index = currentRows.findIndex((row) => row[${JSON.stringify(entity.primaryKey)}] === id);\n    if (index < 0) throw new Error('${entity.displayName} ' + id + ' not found');\n    currentRows[index] = { ...currentRows[index], ...patch };\n    return currentRows[index];\n  },\n  async delete(id: string): Promise<void> {\n    _rows = load().filter((row) => row[${JSON.stringify(entity.primaryKey)}] !== id);\n  },\n  async clear(): Promise<void> {\n    _rows = null;\n  },\n};\n\nexport default ${entity.serviceName}Service;\n`;
}

function renderConnectorStub(connector) {
  const message = `Connector "${connector.apiName}" (${connector.displayName}) is planned but unavailable in prototype mode. Run /prototype-to-real-app to provision it.`;
  const safePurpose = connector.purpose.replace(/\*\//g, '* /');
  return `// ${GENERATOR_MARKER}\n// Prototype-mode throw-stub for ${connector.displayName}.\n// Planned purpose: ${safePurpose}\nconst MESSAGE = ${JSON.stringify(message)};\n\ntype ConnectorStub = Record<string, (...args: unknown[]) => Promise<unknown>>;\n\nexport const ${connector.serviceName}Service: ConnectorStub = new Proxy({} as ConnectorStub, {\n  get(_target, property: string | symbol) {\n    if (typeof property === 'symbol' || property === 'then' || property === 'toJSON') return undefined;\n    return (..._args: unknown[]) => Promise.reject(new Error(MESSAGE));\n  },\n});\n\nexport default ${connector.serviceName}Service;\n`;
}

function renderStrictService(entity) {
  // Generated row schemas are interfaces without index signatures. Reflect.get
  // keeps user-selected orderBy fields strict-mode compatible. The update path
  // also mutates the narrowed array returned by load(), never nullable storage.
  return renderService(entity)
    .replace('(left as Record<string, unknown>)[field]', 'Reflect.get(left, field)')
    .replace('(right as Record<string, unknown>)[field]', 'Reflect.get(right, field)')
    .replace(/\bcurrentRows\b/g, 'current');
}

function renderDataSourcesInfo(entities, connectors) {
  const serviceExports = entities.map((entity) => `export { ${entity.serviceName}Service } from './${entity.serviceName}Service';`);
  const typeExports = entities.map((entity) => `export type { ${entity.serviceName} } from '../schemas/${entity.serviceName}.Schema';`);
  const connectorExports = connectors.map((connector) => `export { ${connector.serviceName}Service } from './${connector.serviceName}Service';`);
  return `// ${GENERATOR_MARKER}\n${[...serviceExports, ...connectorExports, '', ...typeExports].join('\n')}\n\nexport const REGISTERED_DATA_SOURCES = ${JSON.stringify(entities.map((entity) => entity.logicalName), null, 2)} as const;\nexport const REGISTERED_CONNECTORS = ${JSON.stringify(connectors.map((connector) => connector.apiName), null, 2)} as const;\n`;
}

function choiceMapName(entity, field) {
  return `${serviceIdentifier(`${entity.logicalName}_${field.name}`)}_LABELS`;
}

function renderChoiceLabels(entities) {
  const maps = [];
  for (const entity of entities) {
    for (const field of entity.fields) {
      if (field.type !== 'choice' || field.options.length === 0) continue;
      const entries = field.options.map((option, index) => {
        if (!option || typeof option !== 'object' || !Number.isInteger(option.value) || !String(option.label || '').trim()) {
          fail(`${entity.logicalName}.${field.name} option ${index} requires an integer value and non-empty label`);
        }
        if (/^1000000\d\d$/.test(String(option.label).trim())) {
          fail(`${entity.logicalName}.${field.name} option ${index} label must be human-readable, not a raw optionset integer`);
        }
        return `  ${JSON.stringify(String(option.value))}: ${JSON.stringify(String(option.label))},`;
      });
      maps.push(
        `export const ${choiceMapName(entity, field)}: Record<string, string> = {\n${entries.join('\n')}\n};`,
      );
    }
  }
  const mapSource = maps.length > 0
    ? maps.join('\n\n')
    : '// This schema contract does not declare any choice columns.';
  return `// ${GENERATOR_MARKER}\n// Choice labels come from the approved schema contract; screens must not render raw option integers.\n${mapSource}\n\nexport function choiceLabel(map: Record<string, string>, value: unknown): string {\n  const key = String(value ?? '');\n  return map[key] ?? 'Unknown';\n}\n`;
}

function writeGeneratedFile(projectDir, relativePath, content, generatedFiles) {
  const filePath = path.join(projectDir, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
  generatedFiles.push(relativePath.split(path.sep).join('/'));
}

function main() {
  const projectArg = process.argv[2];
  if (!projectArg) fail('usage: node gen-mock-services.js <project-dir>');
  const projectDir = path.resolve(projectArg);
  const planPath = path.join(projectDir, 'native-app-plan.md');
  if (!fs.existsSync(projectDir)) fail(`project directory not found: ${projectDir}`);
  if (!fs.existsSync(planPath)) fail(`native-app-plan.md not found under ${projectDir}`);

  const planText = fs.readFileSync(planPath, 'utf8');
  const { entities, source } = loadEntities(projectDir, planText);
  const vocabulary = loadVocabulary(projectDir);
  const connectors = parseConnectors(planText);
  const duplicate = entities.find((entity, index) => entities.findIndex((candidate) => candidate.logicalName === entity.logicalName) !== index);
  if (duplicate) fail(`duplicate table logicalName in schema contract: ${duplicate.logicalName}`);

  const seedMerge = mergeExistingSeeds(projectDir, entities, vocabulary);
  const rowsByEntity = seedMerge.rowsByEntity;
  const generatedFiles = [];
  for (const entity of entities) {
    writeGeneratedFile(projectDir, `src/generated/services/${entity.serviceName}Service.ts`, renderStrictService(entity), generatedFiles);
    writeGeneratedFile(projectDir, `src/generated/services/${entity.serviceName}.seed.json`, `${JSON.stringify(rowsByEntity.get(entity.logicalName), null, 2)}\n`, generatedFiles);
    writeGeneratedFile(projectDir, `src/generated/schemas/${entity.serviceName}.Schema.ts`, renderSchema(entity), generatedFiles);
  }
  for (const connector of connectors) {
    writeGeneratedFile(projectDir, `src/generated/services/${connector.serviceName}Service.ts`, renderConnectorStub(connector), generatedFiles);
  }
  writeGeneratedFile(projectDir, 'src/generated/services/dataSourcesInfo.ts', renderDataSourcesInfo(entities, connectors), generatedFiles);
  writeGeneratedFile(projectDir, 'src/generated/services/index.ts', "// Generated by create-mobile-prototype/gen-mock-services.js\nexport * from './dataSourcesInfo';\n", generatedFiles);
  writeGeneratedFile(projectDir, 'src/generated/choiceLabels.ts', renderChoiceLabels(entities), generatedFiles);
  writeGeneratedFile(projectDir, 'src/generated/index.ts', "// Generated by create-mobile-prototype/gen-mock-services.js\nexport * from './services';\nexport * from './choiceLabels';\n", generatedFiles);

  const removedGeneratedFiles = archiveStaleGeneratedFiles(
    projectDir,
    seedMerge.previousManifest,
    generatedFiles,
  );

  const regenerationReportPath = path.join(projectDir, '.tmp', 'prototype-seed-regeneration.json');
  fs.mkdirSync(path.dirname(regenerationReportPath), { recursive: true });
  fs.writeFileSync(regenerationReportPath, `${JSON.stringify({
    schemaVersion: 1,
    seedProfile: seedMerge.seedProfile,
    seedVocabularySha256: seedMerge.seedVocabularySha256,
    tables: seedMerge.tableReports,
    removedGeneratedFiles,
  }, null, 2)}\n`);

  const manifestPath = path.join(projectDir, 'src', 'generated', '.prototype-manifest.json');
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, `${JSON.stringify({
    schemaVersion: 1,
    generator: 'create-mobile-prototype/gen-mock-services.js',
    schemaSource: source,
    seedProfile: seedMerge.seedProfile,
    seedVocabulary: '.tmp/seed-vocabulary.json',
    seedVocabularySha256: seedMerge.seedVocabularySha256,
    tables: entities.map((entity) => entity.logicalName),
    tableSchemas: entities.map((entity) => ({
      logicalName: entity.logicalName,
      displayName: entity.displayName,
      serviceName: entity.serviceName,
      seedFile: `src/generated/services/${entity.serviceName}.seed.json`,
      primaryKey: entity.primaryKey,
      dependencyTier: entity.dependencyTier,
      fields: entity.fields.map((field) => ({
        name: field.name,
        type: field.type,
        required: field.required,
        lookupTarget: field.lookupTarget,
        options: field.options,
      })),
    })),
    connectors: connectors.map((connector) => connector.apiName),
    choiceLabelFile: 'src/generated/choiceLabels.ts',
    files: generatedFiles,
    seedRegenerationReport: '.tmp/prototype-seed-regeneration.json',
  }, null, 2)}\n`);

  console.log(`prototype-mocks: generated ${entities.length} table service(s) and ${connectors.length} connector stub(s)`);
  console.log(`prototype-mocks: schema source ${source}`);
}

main();