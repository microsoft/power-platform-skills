function buildAssetManifest(model, mediaPolicy) {
  const assets = {};
  const records = {};
  for (const entity of model.entities) {
    const imageFields = entity.fields.filter((field) => field.type === 'image');
    if (!imageFields.length) continue;
    for (const row of model.fixtures[entity.key] || []) {
      for (const field of imageFields) {
        const media = row[field.key];
        if (!media) continue;
        if (mediaPolicy === 'local-first' && media.imageUrl) fail(`${entity.key}.${field.key} uses imageUrl under local-first policy`);
        if (['remote-cdn-cached', 'remote-allowed'].includes(mediaPolicy) && !media.imageUrl) fail(`${entity.key}.${field.key} requires imageUrl under ${mediaPolicy}`);
        const assetKey = media.imageAssetKey;
        assets[assetKey] = {
          key: assetKey,
          kind: 'bundled-raster',
          family: media.family || semanticMediaFamily(entity.displayName, row[entity.primaryNameField]),
          label: String(row[entity.primaryNameField]),
          category: null,
          materialized: false,
        };
        records[`${entity.key}:${row.id}:${field.key}`] = {
          imageUrl: media.imageUrl || null,
          imageAltText: media.imageAltText,
          imageCacheKey: media.imageCacheKey || `prototype:${entity.key}:${row.id}:${field.key}`,
          imageAssetKey: assetKey,
          source: media.imageUrl ? 'approved-cdn-with-bundled-fallback' : 'bundled-local',
          delivery: mediaPolicy === 'local-first' ? 'bundled-first' : 'remote-cached-with-bundled-fallback',
        };
      }
    }
  }
  return {
    schemaVersion: 2,
    generator: 'prototype-domain-data',
    assetPolicy: mediaPolicy,
    assets,
    fallbacks: {},
    media: {
      policy: mediaPolicy,
      approvedHosts: ['images.unsplash.com'],
      fields: ['imageUrl', 'imageAltText', 'imageCacheKey', 'imageAssetKey'],
      critical: Object.keys(records).length > 0,
      records,
    },
  };
}

function renderMedia(manifest) {
  const sources = Object.entries(manifest.assets).filter(([, asset]) => asset.materialized && asset.localPath).map(([key, asset]) => `  ${JSON.stringify(key)}: require(${JSON.stringify(`../../${asset.localPath}`)}),`).join('\n');
  return `// ${MARKER}\nimport type { ImageSourcePropType } from 'react-native';\nimport type { DomainMedia } from './model';\n\nconst SOURCES: Record<string, ImageSourcePropType> = {\n${sources}\n};\n\nexport function resolveDomainMedia(media: DomainMedia) {\n  const fallbackSource = SOURCES[media.imageAssetKey] || null;\n  const remoteSource = media.imageUrl ? { uri: media.imageUrl } : null;\n  return {\n    ...media,\n    imageSource: ${manifest.assetPolicy === 'local-first' ? 'fallbackSource' : 'remoteSource || fallbackSource'},\n    fallbackSource,\n    sourcePriority: ${manifest.assetPolicy === 'local-first' ? "'local' as const" : "remoteSource ? 'remote' as const : 'local' as const"},\n  };\n}\n`;
}

function renderIndex(model) {
  const models = model.entities.map((entity) => identifier(entity.key)).join(', ');
  const choices = model.choices.map((choice) => `${identifier(choice.key)}Options`).join(', ');
  return `// ${MARKER}\nexport type { EntityId, Money, DomainMedia, DomainFile, ${models} } from './model';\nexport type { RepositoryMap } from './contracts';\n${choices ? `export { ${choices} } from './choices';\n` : ''}export { PROTOTYPE_CONTEXT } from './context';\nexport { FIXTURES, FIXTURE_SCENARIOS } from './fixtures';\nexport { resolveDomainMedia } from './media';\nexport { PrototypeDataProvider, useRepositories } from './PrototypeDataProvider';\nexport * from './hooks';\n\nexport function isDomainRecordActionable(record: Record<string, unknown>): boolean {\n  const inventory = record.inventoryQuantity;\n  if (typeof inventory === 'number' && inventory <= 0) return false;\n  const status = String(record.status || record.availability || '').toLowerCase();\n  return !['sold-out', 'sold out', 'unavailable', 'blocked', 'inactive'].includes(status);\n}\n`;
}

function generateDataLayer(projectRoot, model, experienceContract = null, screenContract = null, executionContract = null, contextContract = null) {
  const contextRevision = contextContract ? contextEnrichmentRevision(contextContract) : null;
  const validation = validatePrototypeDomainModel(model, {
    experienceContractSha256: experienceContract?.schemaVersion === 1 ? contractHash(experienceContract) : null,
    contextEnrichmentSha256: contextRevision,
  });
  if (!validation.valid) fail(validation.errors.join('; '));
  if (contextContract) {
    const contextValidation = validateContextEnrichment(contextContract, { experienceContract });
    if (!contextValidation.valid) fail(contextValidation.errors.join('; '));
  }
  if (experienceContract?.assetPolicy?.media && model.mediaPolicy.mode !== experienceContract.assetPolicy.media) fail('domain mediaPolicy does not match the Experience Contract');
  const connectorOperations = plannedConnectorOperations(screenContract, executionContract, model);
  const root = fs.realpathSync(path.resolve(projectRoot));
  const manifestPath = path.join(root, MANIFEST_PATH);
  const dataRoot = path.join(root, 'src', 'data');
  if (fs.existsSync(dataRoot) && !fs.existsSync(manifestPath)) fail('src/data exists without an owned prototype domain manifest');
  const previousManifest = fs.existsSync(manifestPath) ? readJson(manifestPath, 'prototype domain manifest') : null;
  if (previousManifest && (previousManifest.mode !== 'prototype-domain' || !Array.isArray(previousManifest.files))) fail('existing prototype domain manifest is not owned by this generator');
  const previousFiles = [...new Set([...(previousManifest?.files || []), ...(previousManifest ? [MANIFEST_PATH] : [])])];
  for (const relative of previousFiles) generatedPath(root, relative);

  const stagingRoot = path.join(root, '.mobile-app', `.prototype-data-stage-${process.pid}-${Date.now()}`);
  assertNoSymlink(root, path.dirname(stagingRoot));
  fs.mkdirSync(path.dirname(stagingRoot), { recursive: true });
  fs.mkdirSync(stagingRoot, { recursive: false });
  const files = [];
  try {
    writeFile(stagingRoot, 'src/data/model.ts', renderModel(model), files);
    writeFile(stagingRoot, 'src/data/contracts.ts', renderContracts(model, connectorOperations), files);
    writeFile(stagingRoot, 'src/data/choices.ts', renderChoices(model), files);
    writeFile(stagingRoot, 'src/data/context.ts', renderContext(contextContract), files);
    writeFile(stagingRoot, 'src/data/fixtures.ts', renderFixtures(model), files);
    writeFile(stagingRoot, 'src/data/validation.ts', renderValidation(model), files);
    writeFile(stagingRoot, 'src/data/repositories/mockRepositories.ts', renderMockRepositories(model), files);
    writeFile(stagingRoot, 'src/data/repositories/mockConnectorRepositories.ts', renderMockConnectorRepositories(connectorOperations), files);
    writeFile(stagingRoot, 'src/data/repositories/dataverseRepositories.ts', renderDataverseRepositories(), files);
    writeFile(stagingRoot, 'src/data/repositories/connectorRepositories.ts', renderConnectorRepositories(connectorOperations), files);
    writeFile(stagingRoot, 'src/data/repositories/index.ts', renderRepositoryIndex(), files);
    writeFile(stagingRoot, 'src/data/PrototypeDataProvider.tsx', renderProvider(model, connectorOperations), files);
    for (const operation of model.operations) {
      const entity = model.entities.find((candidate) => candidate.key === operation.entity);
      writeFile(stagingRoot, `src/data/hooks/${operation.hook}.ts`, renderHook(operation, entity), files);
    }
    for (const operation of connectorOperations) writeFile(stagingRoot, `src/data/hooks/${operation.hook}.ts`, renderConnectorHook(operation), files);
    writeFile(stagingRoot, 'src/data/hooks/index.ts', renderHookIndex(model, connectorOperations), files);

    const mediaPolicy = model.mediaPolicy.mode;
    const assetManifest = buildAssetManifest(model, mediaPolicy);
    const materialized = materializeExperienceAssets(stagingRoot, assetManifest);
    files.push(...materialized.files);
    writeFile(stagingRoot, 'assets/experience/manifest.json', `${JSON.stringify(materialized.manifest, null, 2)}\n`, files);
    writeFile(stagingRoot, 'src/data/media.ts', renderMedia(materialized.manifest), files);
    writeFile(stagingRoot, 'src/data/index.ts', renderIndex(model), files);

    const manifest = {
      schemaVersion: 1,
      mode: 'prototype-domain',
      domainModelRevision: domainModelRevision(model),
      contextEnrichmentRevision: contextRevision,
      domainModelPath: '.tmp/prototype-domain-model.json',
      provider: 'src/data/PrototypeDataProvider.tsx',
      repositoryFactory: 'src/data/repositories/index.ts',
      files: [...new Set(files)].sort(),
      generatedAt: new Date().toISOString(),
    };
    writeFile(stagingRoot, MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`, files);
    installGeneratedFiles(root, stagingRoot, previousFiles, [...new Set(files)]);
    return manifest;
  } catch (error) {
    fs.rmSync(stagingRoot, { recursive: true, force: true });
    throw error;
  }
}

function main(argv) {
  const projectArg = argv[0];
  if (!projectArg) {
    process.stderr.write('Usage: node gen-data-layer.js <project-dir>\n');
    return 2;
  }
  try {
    const projectRoot = path.resolve(projectArg);
    const model = readJson(path.join(projectRoot, '.tmp', 'prototype-domain-model.json'), 'prototype domain model');
    const experiencePath = path.join(projectRoot, '.tmp', 'experience-contract.json');
    const experience = fs.existsSync(experiencePath) ? readJson(experiencePath, 'Experience Contract') : null;
    const screenPath = path.join(projectRoot, '.tmp', 'experience-screen-contract.json');
    const executionPath = path.join(projectRoot, '.tmp', 'mobile-plan-execution-contract.json');
    const contextPath = path.join(projectRoot, '.tmp', 'context-enrichment-contract.json');
    const screen = fs.existsSync(screenPath) ? readJson(screenPath, 'Experience Screen Contract') : null;
    const execution = fs.existsSync(executionPath) ? readJson(executionPath, 'Mobile Plan Execution Contract') : null;
    if (!fs.existsSync(contextPath)) fail('context enrichment contract is missing');
    const context = readJson(contextPath, 'Context Enrichment Contract');
    const manifest = generateDataLayer(projectRoot, model, experience, screen, execution, context);
    process.stdout.write(`prototype-data: generated ${manifest.files.length} file(s) from ${manifest.domainModelRevision}\n`);
    return 0;
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    return 2;
  }
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { generateDataLayer, renderContracts, renderModel };