function renderHook(operation, entity) {
  const hook = identifier(operation.hook);
  const repository = identifier(operation.repository);
  const method = identifier(operation.method);
  const type = identifier(entity.key);
  const keyRoot = JSON.stringify([entity.key, operation.key]);
  const listInputType = operation.kind === 'list' ? operationInputType(operation, entity) : null;
  if (operation.kind === 'list' && operation.pagination.mode === 'cursor') {
    return `// ${MARKER}\nimport { useInfiniteQuery } from '@tanstack/react-query';\nimport { useRepositories } from '../PrototypeDataProvider';\nimport type { ${type} } from '../model';\n\nexport function ${hook}(input: ${listInputType} = {}) {\n  const { ${repository} } = useRepositories();\n  return useInfiniteQuery({\n    queryKey: [...${keyRoot}, input],\n    initialPageParam: undefined as string | undefined,\n    queryFn: ({ pageParam }) => ${repository}.${method}({ ...input, cursor: pageParam }),\n    getNextPageParam: (page) => page.nextCursor,\n    select: (data) => data.pages.flatMap((page) => page.data),\n  });\n}\n`;
  }
  if (operation.kind === 'list') {
    return `// ${MARKER}\nimport { useQuery } from '@tanstack/react-query';\nimport { useRepositories } from '../PrototypeDataProvider';\nimport type { ${type} } from '../model';\n\nexport function ${hook}(input: ${listInputType} = {}) {\n  const { ${repository} } = useRepositories();\n  return useQuery({ queryKey: [...${keyRoot}, input], queryFn: async () => (await ${repository}.${method}(input)).data });\n}\n`;
  }
  if (operation.kind === 'get') {
    return `// ${MARKER}\nimport { useQuery } from '@tanstack/react-query';\nimport { useRepositories } from '../PrototypeDataProvider';\nimport type { EntityId } from '../model';\n\nexport function ${hook}(id: EntityId | undefined) {\n  const { ${repository} } = useRepositories();\n  return useQuery({ queryKey: [...${keyRoot}, id], enabled: Boolean(id), queryFn: () => ${repository}.${method}(id as EntityId) });\n}\n`;
  }
  const inputType = operationInputType(operation, entity);
  const mutationExpression = operation.kind === 'update' ? 'input' : operation.kind === 'delete' ? 'id' : 'input';
  const typeImports = operation.kind === 'delete' ? 'EntityId' : operation.kind === 'update' ? `EntityId, ${type}` : type;
  return `// ${MARKER}\nimport { useMutation, useQueryClient } from '@tanstack/react-query';\nimport { useRepositories } from '../PrototypeDataProvider';\nimport type { ${typeImports} } from '../model';\n\nexport function ${hook}() {\n  const { ${repository} } = useRepositories();\n  const queryClient = useQueryClient();\n  return useMutation({\n    mutationFn: (${operation.kind === 'delete' ? 'id: EntityId' : `input: ${inputType}`}) => ${repository}.${method}(${mutationExpression}),\n    onSuccess: async () => { await queryClient.invalidateQueries({ queryKey: [${JSON.stringify(entity.key)}] }); },\n  });\n}\n`;
}

