function fail(message) {
  throw new Error(`prototype-data: ${message}`);
}

function readJson(filePath, label) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    fail(`${label} is invalid JSON: ${error.message}`);
  }
}

function writeFile(projectRoot, relativePath, content, files) {
  const filePath = path.join(projectRoot, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
  files.push(relativePath.replace(/\\/g, '/'));
}

function assertNoSymlink(root, target) {
  const relative = path.relative(root, target);
  let cursor = root;
  for (const part of relative.split(path.sep).filter(Boolean)) {
    cursor = path.join(cursor, part);
    if (fs.existsSync(cursor) && fs.lstatSync(cursor).isSymbolicLink()) fail(`generated path must not contain a symlink: ${relativePath(root, cursor)}`);
  }
}

function relativePath(root, target) {
  return path.relative(root, target).replace(/\\/g, '/');
}

function generatedPath(root, relative) {
  const normalized = String(relative || '').replace(/\\/g, '/');
  if (path.isAbsolute(normalized) || normalized.split('/').includes('..') || (normalized !== MANIFEST_PATH && !GENERATED_PREFIXES.some((prefix) => normalized.startsWith(prefix)))) {
    fail(`unsafe generated path ${JSON.stringify(relative)}`);
  }
  const target = path.resolve(root, normalized);
  if (target !== root && !target.startsWith(`${root}${path.sep}`)) fail(`generated path escapes project root: ${normalized}`);
  assertNoSymlink(root, path.dirname(target));
  if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) fail(`generated target must not be a symlink: ${normalized}`);
  return target;
}

function installGeneratedFiles(projectRoot, stagingRoot, previousFiles, nextFiles) {
  const previous = new Set(previousFiles);
  const next = new Set(nextFiles);
  const backupRoot = path.join(projectRoot, '.mobile-app', `.prototype-data-backup-${process.pid}-${Date.now()}`);
  const backups = [];
  const installed = [];
  const preserved = new Set();
  try {
    for (const relative of next) {
      const source = generatedPath(stagingRoot, relative);
      const target = generatedPath(projectRoot, relative);
      if (!fs.existsSync(source) || !fs.lstatSync(source).isFile()) fail(`staged generated file is missing: ${relative}`);
      const targetSource = fs.existsSync(target) && fs.lstatSync(target).isFile() ? fs.readFileSync(target, 'utf8') : '';
      const preservedAdapter = (relative === DATAVERSE_ADAPTER_PATH && targetSource.startsWith(`// ${DATAVERSE_ADAPTER_MARKER}`))
        || (relative === CONNECTOR_ADAPTER_PATH && targetSource.startsWith(`// ${CONNECTOR_ADAPTER_MARKER}`));
      if (preservedAdapter) {
        preserved.add(relative);
        continue;
      }
      if (fs.existsSync(target) && !previous.has(relative) && relative !== MANIFEST_PATH) fail(`refusing to overwrite unowned file: ${relative}`);
      if (fs.existsSync(target)) {
        if (!fs.lstatSync(target).isFile()) fail(`generated target must be a regular file: ${relative}`);
        const backup = generatedPath(backupRoot, relative);
        fs.mkdirSync(path.dirname(backup), { recursive: true });
        fs.renameSync(target, backup);
        backups.push({ target, backup });
      }
    }
    for (const relative of previous) {
      if (next.has(relative)) continue;
      const target = generatedPath(projectRoot, relative);
      if (!fs.existsSync(target)) continue;
      if (!fs.lstatSync(target).isFile()) fail(`stale generated target must be a regular file: ${relative}`);
      const backup = generatedPath(backupRoot, relative);
      fs.mkdirSync(path.dirname(backup), { recursive: true });
      fs.renameSync(target, backup);
      backups.push({ target, backup });
    }
    for (const relative of next) {
      if (preserved.has(relative)) continue;
      const source = generatedPath(stagingRoot, relative);
      const target = generatedPath(projectRoot, relative);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.renameSync(source, target);
      installed.push(target);
    }
    fs.rmSync(backupRoot, { recursive: true, force: true });
  } catch (error) {
    for (const target of installed.reverse()) fs.rmSync(target, { force: true });
    for (const { target, backup } of backups.reverse()) {
      if (fs.existsSync(backup)) {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.renameSync(backup, target);
      }
    }
    throw error;
  } finally {
    fs.rmSync(stagingRoot, { recursive: true, force: true });
    if (!backups.some(({ backup }) => fs.existsSync(backup))) fs.rmSync(backupRoot, { recursive: true, force: true });
  }
}

function identifier(value) {
  const normalized = String(value || '').replace(/[^A-Za-z0-9_$]/g, '');
  if (!normalized || !/^[A-Za-z_$]/.test(normalized)) fail(`unsafe TypeScript identifier ${JSON.stringify(value)}`);
  return normalized;
}

function lowerIdentifier(value) {
  const safe = identifier(value);
  return safe.charAt(0).toLowerCase() + safe.slice(1);
}

function choiceType(choice) {
  return (choice.options || []).map((option) => JSON.stringify(option.key)).join(' | ') || 'never';
}

function fieldType(field) {
  if (['id', 'text', 'multiline-text', 'date', 'date-time', 'url', 'email', 'phone', 'reference'].includes(field.type)) return 'string';
  if (field.type === 'boolean') return 'boolean';
  if (['whole-number', 'decimal'].includes(field.type)) return 'number';
  if (field.type === 'money') return 'Money';
  if (field.type === 'image') return 'DomainMedia';
  if (field.type === 'file') return 'DomainFile';
  if (field.type === 'choice') return identifier(field.choiceKey);
  if (field.type === 'multi-choice') return `${identifier(field.choiceKey)}[]`;
  return 'unknown';
}

function renderModel(model) {
  const choiceTypes = model.choices.map((choice) => `export type ${identifier(choice.key)} = ${choiceType(choice)};`).join('\n');
  const entities = model.entities.map((entity) => {
    const fields = entity.fields.map((field) => `  ${field.key}${field.required ? '' : '?'}: ${fieldType(field)};`).join('\n');
    return `export type ${identifier(entity.key)} = {\n${fields}\n};`;
  }).join('\n\n');
  return `// ${MARKER}\n\nexport type EntityId = string;\n\nexport type Money = {\n  amount: number;\n  currencyCode: string;\n};\n\nexport type DomainMedia = {\n  imageUrl?: string;\n  imageAltText: string;\n  imageCacheKey?: string;\n  imageAssetKey: string;\n  family?: 'travel' | 'beauty' | 'watch' | 'food' | 'wellness' | 'product';\n};\n\nexport type DomainFile = {\n  fileName: string;\n  mimeType: string;\n  localUri?: string;\n};\n\n${choiceTypes}\n\n${entities}\n`;
}

function operationInputType(operation, entity) {
  if (operation.kind === 'list') {
    const filters = (operation.filterFields || []).map((field) => `  ${field}?: ${identifier(entity.key)}[${JSON.stringify(field)}];`).join('\n');
    return `{\n${filters}${filters ? '\n' : ''}  cursor?: string;\n  pageSize?: number;\n}`;
  }
  if (operation.kind === 'get' || operation.kind === 'delete') return 'EntityId';
  const fields = operation.writeFields || [];
  const pick = fields.length ? fields.map(JSON.stringify).join(' | ') : 'never';
  if (operation.kind === 'create') return `Pick<${identifier(entity.key)}, ${pick}>`;
  return `{ id: EntityId; patch: Pick<${identifier(entity.key)}, ${pick}> }`;
}

function operationReturnType(operation, entity) {
  const type = identifier(entity.key);
  if (operation.kind === 'list') return `RepositoryPage<${type}>`;
  if (operation.kind === 'get') return `${type} | null`;
  if (operation.kind === 'delete') return 'void';
  return type;
}

function renderContracts(model, connectorOperations = []) {
  const imports = model.entities.map((entity) => identifier(entity.key)).join(', ');
  const repositories = new Map();
  for (const operation of model.operations) {
    const entries = repositories.get(operation.repository) || [];
    entries.push(operation);
    repositories.set(operation.repository, entries);
  }
  const connectorRepositories = new Map();
  for (const operation of connectorOperations) {
    if (repositories.has(operation.repository)) fail(`connector repository ${operation.repository} collides with a domain repository`);
    const entries = connectorRepositories.get(operation.repository) || [];
    entries.push(operation);
    connectorRepositories.set(operation.repository, entries);
  }
  const interfaces = [...repositories.entries()].map(([repository, operations]) => {
    const methods = operations.map((operation) => {
      const entity = model.entities.find((candidate) => candidate.key === operation.entity);
      return `  ${operation.method}(input${operation.kind === 'list' ? '?' : ''}: ${operationInputType(operation, entity)}): Promise<${operationReturnType(operation, entity)}>;`;
    }).join('\n');
    return `export interface ${identifier(repository)} {\n${methods}\n}`;
  }).join('\n\n');
  const connectorInterfaces = [...connectorRepositories.entries()].map(([repository, operations]) => {
    const methods = operations.map((operation) => `  ${operation.repositoryMethod}(input: Record<string, unknown>): Promise<Record<string, unknown>>;`).join('\n');
    return `export interface ${identifier(repository)} {\n${methods}\n}`;
  }).join('\n\n');
  const domainFields = [...repositories.keys()].map((repository) => `  ${identifier(repository)}: ${identifier(repository)};`).join('\n');
  const connectorFields = [...connectorRepositories.keys()].map((repository) => `  ${identifier(repository)}: ${identifier(repository)};`).join('\n');
  return `// ${MARKER}\nimport type { EntityId, ${imports} } from './model';\n\nexport type RepositoryPage<T> = {\n  data: T[];\n  nextCursor?: string;\n};\n\n${interfaces}\n${interfaces && connectorInterfaces ? '\n\n' : ''}${connectorInterfaces}\n\nexport type DomainRepositoryMap = {\n${domainFields}\n};\n\nexport type ConnectorRepositoryMap = {\n${connectorFields}\n};\n\nexport type RepositoryMap = DomainRepositoryMap & ConnectorRepositoryMap;\n`;
}

