function plannedConnectorOperations(screenContract, executionContract, model = { operations: [] }) {
  const executable = new Set((executionContract?.connectorOperations || []).map((operation) => operation.id));
  const operations = (screenContract?.screens || []).flatMap((screen) => screen.data?.operations || []).filter((operation) => operation.kind === 'connector');
  const identities = new Set();
  const hooks = new Set((model.operations || []).map((operation) => operation.hook));
  for (const operation of operations) {
    for (const field of ['repository', 'repositoryMethod', 'hook', 'connectorOperationId']) {
      if (typeof operation[field] !== 'string' || !operation[field]) fail(`connector screen operation ${operation.id || '<unknown>'} is missing ${field}`);
    }
    if (!executable.has(operation.connectorOperationId)) fail(`connector screen operation ${operation.id} references unknown execution operation ${operation.connectorOperationId}`);
    const identity = `${operation.repository}.${operation.repositoryMethod}`;
    if (identities.has(identity)) fail(`connector repository method is duplicated: ${identity}`);
    if (hooks.has(operation.hook)) fail(`connector hook is duplicated: ${operation.hook}`);
    identities.add(identity);
    hooks.add(operation.hook);
  }
  return operations;
}

