function deriveAppName(sources) {
  // The .msapp filename in Properties.json/Header.json is often base64-encoded
  // (URL-safe). Decode it when it looks base64-ish; otherwise return verbatim.
  const raw = sources.properties?.Name || sources.header?.Name || null;
  if (!raw) return null;
  const stem = raw.replace(/\.msapp$/i, '');
  if (/^[A-Za-z0-9+/=_-]+$/.test(stem) && stem.length >= 4) {
    try {
      const decoded = Buffer.from(stem.replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8');
      // Heuristic: decoded result should be mostly printable ASCII/UTF-8.
      if (/^[\x20-\x7e\u00a0-\uffff]+$/.test(decoded) && decoded.length >= 2) {
        return decoded;
      }
    } catch (_err) {
      /* fall through */
    }
  }
  return stem;
}

function parseDataSources(properties, dataSourcesRefs) {
  const dataverseByDisplay = new Map();
  const connectors = new Map();
  // Power Automate flows surfaced through `ServiceInfo` + `ConnectedWadl` +
  // `shared_logicflows` ApiId. These are real flows wired into the app even
  // when no `xxxFlow.Run()` call appears in screen formulas — without
  // capturing them we lose flows declared in `LocalConnectionReferences`.
  const flowsByName = new Map();
  // SharePoint lists surfaced through `ConnectedDataSourceInfo`.
  const sharepointLists = [];
  // Dataverse saved views surfaced through `ViewInfo` — keyed by table
  // logical name so we can attach view names to the table rollup.
  const viewsByLogical = new Map();

  // 1) LocalDatabaseReferences (the canonical Dataverse table inventory).
  if (properties && properties.LocalDatabaseReferences) {
    try {
      const ref = JSON.parse(properties.LocalDatabaseReferences);
      const ds = ref?.['default.cds']?.dataSources || {};
      for (const [displayName, info] of Object.entries(ds)) {
        dataverseByDisplay.set(displayName, {
          displayName,
          logicalName: info.logicalName,
          entitySetName: info.entitySetName,
          kind: 'dataverse',
        });
      }
    } catch (err) {
      console.warn(`[brief] WARN failed to parse LocalDatabaseReferences: ${err.message}`);
    }
  }

  // 2) LocalConnectionReferences (connectors). The raw shape is
  //     { "<lcrKey>": { dataSources: ["DsName1", "DsName2"], connectionInstanceId, ... } }
  // where `dataSources` is always an array of strings (the friendly DS names
  // from References/DataSources.json). We normalize to a stable shape so
  // downstream consumers don't have to second-guess the raw format. Note that
  // the LCR key itself is usually a GUID — the friendly connector name comes
  // from joining against the `ServiceInfo` rows in DataSources.json (handled
  // in step 3 below).
  if (properties && properties.LocalConnectionReferences) {
    try {
      const ref = JSON.parse(properties.LocalConnectionReferences);
      for (const [name, info] of Object.entries(ref)) {
        const rawDs = info?.dataSources;
        const dsList = Array.isArray(rawDs)
          ? rawDs.filter((x) => typeof x === 'string')
          : (rawDs && typeof rawDs === 'object')
            ? Object.keys(rawDs)
            : [];
        // Some LCR entries (notably standalone SharePoint connections) carry
        // friendly connector metadata under `connectionRef` even when their
        // `dataSources` list is empty — preserve that here so
        // `buildConnectorInventory` can fall back to it for the friendly
        // name + ApiId join.
        const connectionInstanceId =
          info?.connectionInstanceId || info?.connectionId || null;
        let apiIdFromInstance = null;
        if (typeof connectionInstanceId === 'string') {
          const m = connectionInstanceId.match(/\/apis\/(shared_[^/]+)/i);
          if (m) apiIdFromInstance = `/providers/microsoft.powerapps/apis/${m[1]}`;
        }
        const apiId = info?.apiId || info?.connectionRef?.id || apiIdFromInstance || null;
        connectors.set(name, {
          name,
          kind: classifyConnectorKind(apiId),
          dataSources: dsList,
          apiId,
          // Source connection IDs and display names are environment-specific
          // and can identify a tenant/account. Preserve only whether a source
          // connection existed; the target must resolve its own connection.
          connectionId: null,
          sourceConnectionPresent: !!connectionInstanceId,
          connectionRefDisplayName: null,
        });
      }
    } catch (err) {
      console.warn(`[brief] WARN failed to parse LocalConnectionReferences: ${err.message}`);
    }
  }

  // 3) References/DataSources.json — augment Dataverse with OptionSet info per
  //    column, detect ConnectedDataSourceInfo (SharePoint), ViewInfo
  //    (Dataverse saved views) and ServiceInfo entries that represent
  //    Power Automate flows (`ConnectedWadl` + `shared_logicflows`).
  const optionSetsByTable = new Map();
  // Keep a side map of friendly DS name -> ServiceInfo row so the connector
  // inventory builder can join LCR GUID entries to their friendly metadata.
  const serviceInfoByDataSource = new Map();
  if (dataSourcesRefs && Array.isArray(dataSourcesRefs.DataSources)) {
    for (const ds of dataSourcesRefs.DataSources) {
      // OptionSet column metadata (used by Dataverse schema enrichment).
      if (ds.Type === 'OptionSetInfo' && ds.RelatedEntityName) {
        const entry = optionSetsByTable.get(ds.RelatedEntityName) || [];
        entry.push({
          name: ds.Name,
          column: ds.RelatedColumnInvariantName,
          displayName: ds.DisplayName,
          values: ds.OptionSetInfoNameMapping,
          isBoolean: !!ds.OptionSetIsBooleanValued,
          isGlobal: !!ds.OptionSetIsGlobal,
        });
        optionSetsByTable.set(ds.RelatedEntityName, entry);
        continue;
      }
      // Power Automate flows (the only `ServiceInfo` + `ConnectedWadl` +
      // `shared_logicflows` combo). These show up as connectors in LCR but
      // semantically they're flows.
      //
      // `FlowNameId` is the cloud-flow GUID — the one `npx power-apps
      // add-flow --flow-id <guid>` consumes in the target environment.
      // `WorkflowEntityId` is the Dataverse `workflow` row GUID and is kept
      // alongside as a secondary handle for plans that bind by Dataverse id.
      if (
        ds.Type === 'ServiceInfo'
        && ds.ServiceKind === 'ConnectedWadl'
        && typeof ds.ApiId === 'string'
        && ds.ApiId.toLowerCase().includes('shared_logicflows')
      ) {
        if (ds.Name) {
          flowsByName.set(ds.Name, {
            name: ds.Name,
            apiId: ds.ApiId,
            displayName: ds.DisplayName || ds.Name,
            id: ds.FlowNameId || null,
            workflowEntityId: ds.WorkflowEntityId || null,
          });
        }
      }
      // SharePoint lists (Get items source).
      if (ds.Type === 'ConnectedDataSourceInfo' && ds.Name) {
        sharepointLists.push({
          name: ds.Name,
          displayName: ds.DisplayName || ds.Name,
          datasetName: ds.DatasetName || null,
          tableName: ds.TableName || null,
          apiId: ds.ApiId || null,
        });
      }
      // Dataverse saved views — typically attached to a Dataverse table via
      // `RelatedEntityName` / `TableName`. We index by both so the table
      // rollup can find them regardless of which field studio populated.
      if (ds.Type === 'ViewInfo' && ds.Name) {
        const tableKey = ds.RelatedEntityName || ds.TableName || null;
        const entry = {
          name: ds.Name,
          displayName: ds.DisplayName || ds.Name,
          tableLogical: tableKey,
        };
        if (tableKey) {
          const list = viewsByLogical.get(tableKey) || [];
          list.push(entry);
          viewsByLogical.set(tableKey, list);
        }
      }
      // Track ServiceInfo (connector) rows for friendly-name join in
      // buildConnectorInventory. The friendly DS name shows up directly as
      // `ds.Name` on the ServiceInfo row (e.g. `Office365Users`) — that's
      // also what LCR's `dataSources[]` references — so we index by that.
      if (ds.Type === 'ServiceInfo' && ds.Name) {
        serviceInfoByDataSource.set(ds.Name, ds);
      }
    }
  }

  return {
    dataverseByDisplay,
    dataverseByLogical: new Map(
      [...dataverseByDisplay.values()].map((d) => [d.logicalName, d])
    ),
    connectors,
    optionSetsByTable,
    flows: [...flowsByName.values()].sort((a, b) => a.name.localeCompare(b.name)),
    flowNames: new Set(flowsByName.keys()),
    sharepointLists: sharepointLists.sort((a, b) => a.name.localeCompare(b.name)),
    viewsByLogical,
    serviceInfoByDataSource,
  };
}

// =============================================================================
// Dataverse schema (full per-table metadata) — Phase 4
// =============================================================================
//
// `References/DataSources.json` carries `NativeCDSDataSourceInfo` entries whose
// `TableDefinition` is a *stringified* JSON wrapper around the full
// `EntityMetadata` (also stringified). Together they pin down everything a
// code-apps-native plugin needs to either (a) provision a new Dataverse table
// to match the original, or (b) detect/reuse an existing one:
//   - Attributes (columns) — type, primary id/name, valid for CRUD, lookup
//     targets, option set values, format/precision/maxLength.
//   - Relationships — many-to-one (outgoing lookup), one-to-many (incoming),
//     many-to-many (with intersect entity), nav property names, cascade.
//   - Table flags — IsActivity, IsAvailableOffline, OwnershipType, etc.
//   - Option sets (picklist/state/status/boolean) with their option labels.
//
// Source attributes can be very wide (>300 cols on standard tables like
// `account`), so we project a *slim* shape per attribute / relationship and
// emit each table to its own sidecar JSON file (`tables/<logical>.json`).
// The app-brief itself carries only a per-table summary + briefPath.
//
// Returns null when no DataSources.json sidecar exists (YAML-only path).

function buildDataverseSchemas(dataSourcesRefs) {
  if (!dataSourcesRefs || !Array.isArray(dataSourcesRefs.DataSources)) return null;
  const schemas = new Map(); // logicalName -> slim schema
  for (const ds of dataSourcesRefs.DataSources) {
    if (ds.Type !== 'NativeCDSDataSourceInfo') continue;
    const td = safeJsonParse(ds.TableDefinition, `TableDefinition[${ds.LogicalName}]`);
    if (!td) continue;
    const em = safeJsonParse(td.EntityMetadata, `EntityMetadata[${ds.LogicalName}]`);
    if (!em) continue;

    // Map option-set attribute logical names to their option lists (Picklist,
    // MultiSelectPicklist, State, Status, Boolean — each kind has its own
    // stringified blob carrying the Options array).
    const optionSetByAttr = collectOptionSetsByAttr(td);

    const attributes = (em.Attributes || [])
      .map((a) => slimAttribute(a, optionSetByAttr))
      .filter(Boolean)
      .sort((a, b) => a.logicalName.localeCompare(b.logicalName));

    const relationships = {
      manyToOne: (em.ManyToOneRelationships || [])
        .map((r) => slimRelationship(r, 'manyToOne'))
        .sort((a, b) => a.schemaName.localeCompare(b.schemaName)),
      oneToMany: (em.OneToManyRelationships || [])
        .map((r) => slimRelationship(r, 'oneToMany'))
        .sort((a, b) => a.schemaName.localeCompare(b.schemaName)),
      manyToMany: (em.ManyToManyRelationships || [])
        .map((r) => slimRelationship(r, 'manyToMany'))
        .sort((a, b) => a.schemaName.localeCompare(b.schemaName)),
    };

    const optionSets = dedupeOptionSets(optionSetByAttr);
    const privileges = rollupPrivileges(em.Privileges);

    schemas.set(em.LogicalName || ds.LogicalName, {
      logicalName: em.LogicalName || ds.LogicalName,
      schemaName: em.SchemaName || ds.Name,
      displayName: extractLocalLabel(em.DisplayName) || ds.PreferredName || ds.Name,
      pluralDisplayName: extractLocalLabel(em.DisplayCollectionName),
      description: extractLocalLabel(em.Description),
      entitySetName: em.EntitySetName || ds.EntitySetName,
      primaryIdAttribute: em.PrimaryIdAttribute,
      primaryNameAttribute: em.PrimaryNameAttribute,
      objectTypeCode: em.ObjectTypeCode,
      tableType: em.TableType || (em.IsCustomEntity ? 'Custom' : 'Standard'),
      ownershipType: em.OwnershipType,
      isCustomEntity: em.TableType === 'Custom' || em.IsCustomEntity === true,
      isActivity: !!em.IsActivity,
      isIntersect: !!em.IsIntersect,
      isManaged: em.IsManaged !== false,
      isAvailableOffline: !!em.IsAvailableOffline,
      isOfflineInMobileClient: !!em.IsOfflineInMobileClient,
      hasNotes: !!em.HasNotes,
      iconUrl: td.IconUrl || null,
      columnDisplayNameMapping: ds.NativeCDSDataSourceInfoNameMapping || {},
      privileges,
      attributes,
      relationships,
      optionSets,
      counts: {
        attributeCount: attributes.length,
        nonLogicalAttributeCount: attributes.filter((a) => !a.isLogical).length,
        customAttributeCount: attributes.filter((a) => a.isCustom).length,
        manyToOneCount: relationships.manyToOne.length,
        oneToManyCount: relationships.oneToMany.length,
        manyToManyCount: relationships.manyToMany.length,
        optionSetCount: optionSets.length,
      },
    });
  }
  return schemas;
}

function safeJsonParse(maybeJsonStr, label) {
  if (maybeJsonStr == null) return null;
  if (typeof maybeJsonStr !== 'string') return maybeJsonStr;
  try {
    return JSON.parse(maybeJsonStr);
  } catch (err) {
    console.warn(`[brief] WARN failed to parse ${label || 'json string'}: ${err.message}`);
    return null;
  }
}

// Localized labels come as { LocalizedLabels: [{ Label, LanguageCode }], UserLocalizedLabel: {...} }.
// Prefer English (1033) → UserLocalizedLabel → first available.
function extractLocalLabel(labelObj) {
  if (!labelObj) return null;
  const all = labelObj.LocalizedLabels || [];
  const en = all.find((l) => l.LanguageCode === 1033);
  if (en && en.Label) return en.Label;
  if (labelObj.UserLocalizedLabel && labelObj.UserLocalizedLabel.Label) {
    return labelObj.UserLocalizedLabel.Label;
  }
  if (all[0] && all[0].Label) return all[0].Label;
  return null;
}

// AttributeType discriminates the projection. Drop anything truly unusable
// (no LogicalName) but keep IsLogical=true rows (with a flag) so consumers can
// see computed columns and decide for themselves.
function resolveAttributeType(a) {
  const typeName = a?.AttributeTypeName?.Value;
  const odataType = String(a?.['@odata.type'] || '');
  if (typeName === 'FileType' || /FileAttributeMetadata$/i.test(odataType)) return 'File';
  if (typeName === 'ImageType' || /ImageAttributeMetadata$/i.test(odataType)) return 'Image';
  return a?.AttributeType || 'Unknown';
}

function slimAttribute(a, optionSetByAttr) {
  if (!a || !a.LogicalName) return null;
  const attributeType = resolveAttributeType(a);
  const requiredLevel = a.RequiredLevel?.Value || null;
  const isRequired = requiredLevel === 'ApplicationRequired'
    || requiredLevel === 'SystemRequired'
    || a.IsRequiredForForm === true;
  const out = {
    logicalName: a.LogicalName,
    schemaName: a.SchemaName,
    displayName: extractLocalLabel(a.DisplayName),
    description: extractLocalLabel(a.Description),
    attributeType,
    isPrimaryId: !!a.IsPrimaryId,
    isPrimaryName: !!a.IsPrimaryName,
    isCustom: !!a.IsCustomAttribute,
    isManaged: a.IsManaged !== false,
    isLogical: !!a.IsLogical,
    isValidForCreate: a.IsValidForCreate !== false,
    isValidForRead: a.IsValidForRead !== false,
    isValidForUpdate: a.IsValidForUpdate !== false,
    requiredLevel,
    isRequired,
    // File columns are written through the Dataverse block-upload API even
    // though metadata reports IsValidForCreate/Update=false for normal row
    // payloads. Do not misclassify them as server-computed/read-only fields.
    isReadOnly: attributeType === 'File'
      ? false
      : a.IsValidForCreate === false && a.IsValidForUpdate === false,
  };
  if (attributeType !== a.AttributeType) {
    out.sourceAttributeType = a.AttributeType || null;
    out.attributeTypeName = a.AttributeTypeName?.Value || null;
    out.odataType = a['@odata.type'] || null;
  }
  // Type-specific fields. Names mirror Dataverse OData metadata where useful.
  switch (attributeType) {
    case 'String':
      if (a.MaxLength != null) out.maxLength = a.MaxLength;
      if (a.Format) out.format = a.Format;
      if (a.FormatName?.Value) out.format = a.FormatName.Value;
      break;
    case 'Memo':
      if (a.MaxLength != null) out.maxLength = a.MaxLength;
      break;
    case 'Integer':
    case 'BigInt':
      if (a.MinValue != null) out.minValue = a.MinValue;
      if (a.MaxValue != null) out.maxValue = a.MaxValue;
      if (a.Format) out.format = a.Format;
      break;
    case 'Decimal':
    case 'Double':
    case 'Money':
      if (a.MinValue != null) out.minValue = a.MinValue;
      if (a.MaxValue != null) out.maxValue = a.MaxValue;
      if (a.Precision != null) out.precision = a.Precision;
      break;
    case 'DateTime':
      if (a.Format) out.format = a.Format;
      if (a.DateTimeBehavior?.Value) out.dateTimeBehavior = a.DateTimeBehavior.Value;
      break;
    case 'File':
      if (a.MaxSizeInKB != null) out.maxSizeInKB = a.MaxSizeInKB;
      out.writeMode = 'block-upload';
      break;
    case 'Image':
      if (a.MaxSizeInKB != null) out.maxSizeInKB = a.MaxSizeInKB;
      if (a.MaxHeight != null) out.maxHeight = a.MaxHeight;
      if (a.MaxWidth != null) out.maxWidth = a.MaxWidth;
      if (a.CanStoreFullImage != null) out.canStoreFullImage = !!a.CanStoreFullImage;
      if (a.IsPrimaryImage != null) out.isPrimaryImage = !!a.IsPrimaryImage;
      break;
    case 'Lookup':
    case 'Customer':
    case 'Owner':
      if (Array.isArray(a.Targets) && a.Targets.length) out.lookup = { targets: a.Targets };
      break;
    case 'Picklist':
    case 'MultiSelectPicklist':
    case 'State':
    case 'Status':
    case 'Boolean':
    case 'EntityName': {
      const os = optionSetByAttr.get(a.LogicalName);
      if (os) out.optionSet = os;
      break;
    }
    default:
      break;
  }
  if (a.DefaultFormValue != null && a.DefaultFormValue !== -1) {
    out.defaultFormValue = a.DefaultFormValue;
  }
  if (a.FormulaDefinition) out.formula = a.FormulaDefinition;
  if (a.ParentPicklistLogicalName) out.parentPicklist = a.ParentPicklistLogicalName;
  return out;
}

function slimRelationship(r, kind) {
  if (kind === 'manyToMany') {
    return {
      schemaName: r.SchemaName,
      kind: 'manyToMany',
      entity1: r.Entity1LogicalName,
      entity2: r.Entity2LogicalName,
      intersectEntity: r.IntersectEntityName,
      entity1NavigationProperty: r.Entity1NavigationPropertyName,
      entity2NavigationProperty: r.Entity2NavigationPropertyName,
      isCustom: !!r.IsCustomRelationship,
      isManaged: r.IsManaged !== false,
    };
  }
  return {
    schemaName: r.SchemaName,
    kind, // 'manyToOne' | 'oneToMany'
    referencedEntity: r.ReferencedEntity,
    referencedAttribute: r.ReferencedAttribute,
    referencingEntity: r.ReferencingEntity,
    referencingAttribute: r.ReferencingAttribute,
    referencedNavigationProperty: r.ReferencedEntityNavigationPropertyName,
    referencingNavigationProperty: r.ReferencingEntityNavigationPropertyName,
    isCustom: !!r.IsCustomRelationship,
    isManaged: r.IsManaged !== false,
    cascade: r.CascadeConfiguration || null,
  };
}

// Each option-set kind (Picklist, MultiSelectPicklist, State, Status, Boolean,
// EntityName) is a separate stringified blob on TableDefinition. Inside,
// `.value[]` is an array of attribute-metadata rows each carrying its
// OptionSet.Options or boolean (TrueOption/FalseOption) descriptors.
function collectOptionSetsByAttr(td) {
  const map = new Map();
  const kinds = [
    ['PicklistOptionSetAttribute', 'picklist'],
    ['MultiSelectPicklistOptionSetAttribute', 'multiSelectPicklist'],
    ['StateOptionSetAttribute', 'state'],
    ['StatusOptionSetAttribute', 'status'],
    ['BooleanOptionSetAttribute', 'boolean'],
    ['EntityNameOptionSetAttribute', 'entityName'],
  ];
  for (const [field, kind] of kinds) {
    const parsed = safeJsonParse(td[field], field);
    const rows = parsed?.value || [];
    for (const row of rows) {
      const attrLogical = row.LogicalName;
      if (!attrLogical) continue;
      const slim = slimOptionSet(row, kind);
      if (slim) map.set(attrLogical, slim);
    }
  }
  return map;
}

function slimOptionSet(row, kind) {
  // Boolean has TrueOption + FalseOption rather than Options[].
  if (kind === 'boolean') {
    const os = row.OptionSet || {};
    const opts = [];
    if (os.TrueOption) opts.push({ value: 1, label: extractLocalLabel(os.TrueOption.Label) });
    if (os.FalseOption) opts.push({ value: 0, label: extractLocalLabel(os.FalseOption.Label) });
    return {
      kind,
      name: os.Name,
      isGlobal: !!os.IsGlobal,
      isCustom: !!os.IsCustomOptionSet,
      options: opts,
    };
  }
  const os = row.OptionSet || {};
  const opts = (os.Options || []).map((o) => {
    const out = { value: o.Value, label: extractLocalLabel(o.Label) };
    if (o.Color) out.color = o.Color;
    if (o.ExternalValue) out.externalValue = o.ExternalValue;
    return out;
  });
  return {
    kind,
    name: os.Name,
    isGlobal: !!os.IsGlobal,
    isCustom: !!os.IsCustomOptionSet,
    options: opts,
  };
}

// Dedupe option sets across attributes within one table — global option sets
// (e.g. statuscode) get referenced by multiple columns.
function dedupeOptionSets(optionSetByAttr) {
  const seen = new Map();
  for (const os of optionSetByAttr.values()) {
    if (!os || !os.name) continue;
    if (!seen.has(os.name)) seen.set(os.name, os);
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

// Roll Dataverse `Privileges[]` (per-action privilege metadata) up to a simple
// boolean map. CRUD plus the common cross-record verbs.
function rollupPrivileges(privileges) {
  const out = {
    create: false,
    read: false,
    write: false,
    delete: false,
    append: false,
    appendTo: false,
    assign: false,
    share: false,
  };
  if (!Array.isArray(privileges)) return out;
  const key = (t) => t && t.charAt(0).toLowerCase() + t.slice(1);
  for (const p of privileges) {
    const k = key(p.PrivilegeType);
    if (k && k in out) out[k] = true;
  }
  return out;
}

// =============================================================================
// Connector inventory — Phase 4
// =============================================================================
//
// Connectors come from two places:
//   - `Properties.json.LocalConnectionReferences` — the canonical inventory
//     when the app was authored ("which connectors did I add"). Already
//     surfaced via `parseDataSources` as `dataSources.connectors`.
//   - `References/DataSources.json` — non-Dataverse `Type` entries
//     (`ServiceProviderDataSource`, `ConnectorDataSource`, etc.) carry the
//     per-action endpoints and operation IDs.
//
// We merge both into a single inventory with enough info for code-apps-native
// to (a) detect already-provisioned connections in the target env by apiId,
// or (b) provision new ones from the connection spec.

function buildConnectorInventory(properties, dataSourcesRefs, dataSources) {
  const byName = new Map(); // connector name -> inventory entry

  // Helper: normalize the LCR `dataSources` field (which can be an array of
  // strings, an object map, or — defensively — already-shaped entry objects)
  // into a stable `[{name, ...}]` list. Pre-fix this code spread a string
  // value with `...info`, which JavaScript decomposes character-by-character
  // and produced entries like `{name:"0",0:"L",1:"i",2:"s",3:"t",...}`.
  function normalizeDsList(rawDs) {
    if (!rawDs) return [];
    if (Array.isArray(rawDs)) {
      return rawDs.map((item) => {
        if (typeof item === 'string') return { name: item };
        if (item && typeof item === 'object') return { name: item.name || '', ...item };
        return { name: String(item) };
      });
    }
    if (typeof rawDs === 'object') {
      return Object.entries(rawDs).map(([dsName, info]) => {
        if (info && typeof info === 'object') return { name: dsName, ...info };
        return { name: dsName };
      });
    }
    return [];
  }

  // Seed from LocalConnectionReferences (parseDataSources already did this).
  // Skip LCR entries whose only `dataSources` are flow names — those LCR
  // entries are the flow's connection reference, not a real connector, and
  // belong in `dataModel.flows` (already populated from ServiceInfo).
  const flowNames = dataSources.flowNames || new Set();
  for (const c of dataSources.connectors.values()) {
    const dsList = normalizeDsList(c.dataSources);
    const onlyFlows = dsList.length > 0 && dsList.every((d) => flowNames.has(d.name));
    if (onlyFlows) continue;
    byName.set(c.name, {
      name: c.name,
      apiId: c.apiId || null,            // e.g. /providers/Microsoft.PowerApps/apis/shared_office365
      connectionId: null,
      sourceConnectionPresent: !!(c.sourceConnectionPresent || c.connectionId),
      connectionRefDisplayName: c.connectionRefDisplayName || null,
      authMode: null,
      isProvisioned: !!(c.sourceConnectionPresent || c.connectionId),
      isCustom: false,
      isPremium: false,
      dataSources: dsList,
      actions: [],
      source: 'LocalConnectionReferences',
    });
  }

  // Augment from DataSources.json connector-typed rows. We also pick up
  // `ServiceInfo` rows so the friendly connector name (e.g. `Office365Users`)
  // and `ApiId` flow into the inventory — without this, LCR-only entries are
  // keyed by a GUID with no `apiId`.
  const connectorTypes = new Set([
    'ServiceProviderDataSource',
    'ConnectorDataSource',
    'ConnectionDataSource',
    'ServiceInfo',
  ]);
  if (dataSourcesRefs && Array.isArray(dataSourcesRefs.DataSources)) {
    for (const ds of dataSourcesRefs.DataSources) {
      if (!connectorTypes.has(ds.Type)) continue;
      // Skip ServiceInfo flow rows — those are surfaced via `dataModel.flows`,
      // not the connector inventory.
      if (
        ds.Type === 'ServiceInfo'
        && ds.ServiceKind === 'ConnectedWadl'
        && typeof ds.ApiId === 'string'
        && ds.ApiId.toLowerCase().includes('shared_logicflows')
      ) {
        continue;
      }
      const name = ds.ConnectorName || ds.Name;
      if (!name) continue;
      let entry = byName.get(name);
      if (!entry) {
        entry = {
          name,
          apiId: ds.ApiId || null,
          connectionId: null,
          authMode: null,
          isProvisioned: false,
          isCustom: !!ds.IsCustomApi,
          isPremium: !!ds.IsPremium,
          dataSources: [],
          actions: [],
          source: ds.Type,
        };
        byName.set(name, entry);
      }
      entry.isCustom = entry.isCustom || !!ds.IsCustomApi;
      entry.isPremium = entry.isPremium || !!ds.IsPremium;
      entry.apiId = entry.apiId || ds.ApiId || null;
      // Add operations / actions if present.
      if (Array.isArray(ds.Operations)) {
        for (const op of ds.Operations) {
          entry.actions.push({
            operationId: op.OperationId || op.Name,
            method: op.Method,
            path: op.Path,
          });
        }
      }
    }
  }

  // Friendly-name join pass: for each LCR-seeded entry whose `name` is a GUID
  // and whose `apiId` is missing, look up its first `dataSources[].name` in
  // the `ServiceInfo` index and replace `name`/`apiId` with the friendly
  // values. This is what surfaces e.g. `Office365Users` instead of the LCR
  // GUID in `dataModel.connectorInventory`.
  const guidLike = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
  const idx = dataSources.serviceInfoByDataSource || new Map();
  for (const entry of [...byName.values()]) {
    if (!guidLike.test(entry.name)) continue;
    let friendly = null;
    let svcApiId = null;
    // First try: match via ServiceInfo row indexed by friendly DS name.
    for (const ds of entry.dataSources) {
      const svc = idx.get(ds.name);
      if (svc) {
        friendly = svc.ConnectorName || svc.Name || null;
        svcApiId = svc.ApiId || null;
        if (friendly) break;
      }
    }
    // Second try: standalone connector LCR (no `dataSources`) — fall back to
    // the `connectionRef.displayName` captured at parse time (e.g. SharePoint
    // connections that don't enumerate their lists at this level).
    if (!friendly && entry.connectionRefDisplayName) {
      friendly = entry.connectionRefDisplayName;
    }
    if (!friendly) continue;
    const guidKey = entry.name;
    const existing = byName.get(friendly);
    if (existing && existing !== entry) {
      existing.sourceConnectionPresent = existing.sourceConnectionPresent || entry.sourceConnectionPresent;
      existing.apiId = existing.apiId || svcApiId || entry.apiId;
      existing.isProvisioned = existing.isProvisioned || entry.isProvisioned;
      for (const d of entry.dataSources) {
        if (!existing.dataSources.find((x) => x.name === d.name)) existing.dataSources.push(d);
      }
      byName.delete(guidKey);
    } else {
      byName.delete(guidKey);
      entry.name = friendly;
      entry.apiId = entry.apiId || svcApiId || null;
      entry.source = `${entry.source || ''}+ServiceInfo`;
      byName.set(friendly, entry);
    }
  }

  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

// =============================================================================
// Asset enrichment — Phase 4
// =============================================================================
//
// `Resources/PublishInfo.json` carries the runtime app icon/logo + brand
// background colors (the values the player chrome uses pre-launch). We merge
// these with the per-image entries we already collected from
// `References/Resources.json` and enrich each entry with on-disk file size
// (when a physical `Assets/Images/<file>` exists).

function enrichAssetSummary(assetSummary, sources, publishInfo, resourcesRefs) {
  const source = sources.sourceReader || createSourceReader(sources.extractedRoot);

  // Per-image enrichment: on-disk size + bundled-vs-uri + path normalization.
  let totalBytesBundled = 0;
  for (const img of assetSummary.images) {
    img.isBundled = img.kind === 'LocalFile';
    if (!img.isBundled) continue;
    // Power Apps writes paths with backslashes (Windows convention).
    const rel = (img.fileName || '').replace(/\\/g, '/');
    const candidate = `Assets/Images/${path.basename(rel)}`;
    const st = source.stat(candidate);
    if (st) {
      img.sizeBytes = st.size;
      img.diskPath = source.displayPath(candidate);
      img.mimeType = mimeFromExt(candidate);
      totalBytesBundled += st.size;
    }
  }

  // App logo (chrome). Stored alongside PublishInfo.json under Resources/.
  let logo = null;
  if (publishInfo && publishInfo.LogoFileName) {
    const logoPath = `Resources/${publishInfo.LogoFileName}`;
    const st = source.stat(logoPath);
    if (st) {
      logo = {
        fileName: publishInfo.LogoFileName,
        diskPath: source.displayPath(logoPath),
        sizeBytes: st.size,
        mimeType: mimeFromExt(logoPath),
      };
    } else {
      logo = { fileName: publishInfo.LogoFileName, diskPath: null };
    }
  }

  const bundledCount = assetSummary.images.filter((i) => i.isBundled).length;
  return {
    ...assetSummary,
    bundledImageCount: bundledCount,
    bundledTotalBytes: totalBytesBundled,
    logo,
    appName: publishInfo?.AppName || null,
    backgroundColor: publishInfo?.BackgroundColor || null,
    iconColor: publishInfo?.IconColor || null,
    iconName: publishInfo?.IconName || null,
    userLocale: publishInfo?.UserLocale || null,
    publishTarget: publishInfo?.PublishTarget || null,
  };
}

function mimeFromExt(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case '.svg': return 'image/svg+xml';
    case '.png': return 'image/png';
    case '.jpg': case '.jpeg': return 'image/jpeg';
    case '.gif': return 'image/gif';
    case '.webp': return 'image/webp';
    case '.pdf': return 'application/pdf';
    case '.mp4': return 'video/mp4';
    case '.mp3': return 'audio/mpeg';
    case '.wav': return 'audio/wav';
    default: return 'application/octet-stream';
  }
}

function formatBytes(n) {
  if (n == null || isNaN(n)) return '0 B';
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / (1024 * 1024)).toFixed(2)} MB`;
}

