function rollupScreen(screen, dataSources, parsedComponents, resources) {
  const dataverseUsed = new Map(); // tableLogical -> { table, displayName, columnsRead:Set, columnsWritten:Set, ops:Set }
  const connectorsUsed = new Map(); // name -> { name, actions:Set }
  const flowsCalled = new Map(); // flowName -> { name, actions:Set }
  const aiCallsMade = new Map(); // connector -> { name, actions:Set }
  const paramsRead = new Set();
  const identitySignals = new Set();
  const nativeCapsSet = new Set();
  const outgoing = []; // { target, viaControl, transition, context }
  const collectionsTouched = new Set();
  const variablesTouched = new Set();
  const unsupported = [];
  const imageAssets = new Set();
  const assetReferences = new Set();

  // Local helper: apply one classified intent to the rollup state.
  // Closes over all the Maps/Sets so we can reuse it for both control events
  // and the Screen's own OnVisible/OnHidden/etc.
  function applyIntent(intent, sourceControlPath) {
    switch (intent.intent) {
      case 'navigate':
        outgoing.push({
          target: intent.target,
          viaControl: sourceControlPath,
          transition: intent.transition,
          context: intent.context,
        });
        break;
      case 'patch':
      case 'update':
      case 'updateIf':
      case 'remove':
      case 'removeIf': {
        const ref = resolveDataverseRef(intent.source, dataSources);
        if (ref) {
          const entry = ensureTableEntry(dataverseUsed, ref);
          entry.ops.add(toOpName(intent.intent));
          const fieldRecord = intent.fields || null;
          if (fieldRecord) {
            for (const k of Object.keys(fieldRecord)) entry.columnsWritten.add(k);
          }
        } else if (intent.source) {
          collectionsTouched.add(intent.source);
        }
        break;
      }
      case 'collect':
      case 'clearCollect':
      case 'clear':
        if (intent.collection) collectionsTouched.add(intent.collection);
        break;
      case 'setVar':
        if (intent.name) variablesTouched.add(intent.name);
        break;
      case 'saveData':
      case 'loadData':
        if (intent.name) collectionsTouched.add(intent.name);
        nativeCapsSet.add('persistence');
        break;
      case 'launch':
        nativeCapsSet.add('launch');
        break;
      case 'notify':
        nativeCapsSet.add('notification');
        break;
      case 'connectorCall':
        if (intent.connector) {
          const entry = connectorsUsed.get(intent.connector) || {
            name: intent.connector,
            actions: new Set(),
          };
          if (intent.action) entry.actions.add(intent.action);
          connectorsUsed.set(intent.connector, entry);
        }
        break;
      case 'flowCall':
        if (intent.flow) {
          const entry = flowsCalled.get(intent.flow) || { name: intent.flow, actions: new Set() };
          if (intent.action) entry.actions.add(intent.action);
          flowsCalled.set(intent.flow, entry);
        }
        break;
      case 'aiCall':
        if (intent.connector) {
          const entry = aiCallsMade.get(intent.connector) || { name: intent.connector, actions: new Set() };
          if (intent.action) entry.actions.add(intent.action);
          aiCallsMade.set(intent.connector, entry);
        }
        break;
      case 'paramRead':
        if (intent.name) paramsRead.add(intent.name);
        break;
      case 'confirm':
        nativeCapsSet.add('dialog');
        break;
      case 'setFocus':
      case 'print':
      case 'download':
      case 'downloadJson':
        if (intent.intent === 'print' || intent.intent === 'download' || intent.intent === 'downloadJson') {
          nativeCapsSet.add('export');
        }
        break;
      case 'refresh': {
        const ref = resolveDataverseRef(intent.source, dataSources);
        if (ref) ensureTableEntry(dataverseUsed, ref).ops.add('Refresh');
        break;
      }
      case 'exitApp':
        nativeCapsSet.add('exit');
        break;
      case 'clearOfflineData':
        if (intent.name) collectionsTouched.add(intent.name);
        nativeCapsSet.add('persistence');
        break;
      case 'showHostInfo':
        nativeCapsSet.add('hostInfo');
        break;
      case 'requestHide':
        nativeCapsSet.add('dialog');
        break;
      case 'unknown':
        unsupported.push({
          screen: screen.name,
          control: sourceControlPath,
          raw: intent.raw,
          call: intent.call,
          reason: 'Could not classify formula statement',
        });
        break;
      default:
        break;
    }
  }

  // Scan the Screen's own top-level properties (OnVisible/OnHidden/Fill/etc.)
  // \u2014 they are not part of controlsFlat but still drive intents like Param() reads.
  for (const [propName, formula] of Object.entries(screen.properties || {})) {
    const fx = stripFormula(formula);
    if (!fx) continue;
    collectTableAndColumnRefs(fx, dataSources, dataverseUsed);
    collectResourceRefs(fx, resources, imageAssets, assetReferences);
    collectParamRefs(fx, paramsRead);
    collectIdentityRefs(fx, identitySignals);
    if (/^On[A-Z]/.test(propName)) {
      const intents = classifyFormulaIntents(formula, dataSources, parsedComponents);
      for (const intent of intents) applyIntent(intent, screen.name);
    }
  }

  // Gather references from properties + events for all controls.
  for (const control of screen.controlsFlat) {
    // Native capabilities by control kind.
    addNativeCapForKind(control.kind, nativeCapsSet);
    // Native capabilities from connector calls happen below.

    // Scan ALL property formulas for table/column refs (not just events).
    for (const [propName, formula] of Object.entries(control.properties || {})) {
      const fx = stripFormula(formula);
      if (!fx) continue;
      collectTableAndColumnRefs(fx, dataSources, dataverseUsed);
      collectResourceRefs(fx, resources, imageAssets, assetReferences);
      collectParamRefs(fx, paramsRead);
      collectIdentityRefs(fx, identitySignals);
      if (propName === 'Items' || propName === 'Default' || propName === 'Text' || propName === 'DataSource') {
        // Mark as 'read' op already happens inside collectTableAndColumnRefs by setting columnsRead.
      }
    }

    // Walk classified events for connector calls, navigation, writes, etc.
    for (const [, intents] of Object.entries(control.events || {})) {
      for (const intent of intents) applyIntent(intent, control.path);
    }

    // Component instances bring in resources their definition references —
    // walk the component's controls and merge image refs into this screen.
    // Without this, a screen that only uses `Navigate_Sidebar_Component_1`
    // (which itself references `mtr_logo`) would have an empty `imageAssets`.
    if (control.isComponentInstance && control.componentName) {
      const compDef = parsedComponents.get(control.componentName);
      if (compDef && Array.isArray(compDef.controlsFlat)) {
        for (const compCtrl of compDef.controlsFlat) {
          for (const formula of Object.values(compCtrl.properties || {})) {
            const fx = stripFormula(formula);
            if (!fx) continue;
            collectResourceRefs(fx, resources, imageAssets, assetReferences);
          }
        }
        // Also walk the component's top-level properties (Image, Fill, etc.).
        for (const formula of Object.values(compDef.properties || {})) {
          const fx = stripFormula(formula);
          if (!fx) continue;
          collectResourceRefs(fx, resources, imageAssets, assetReferences);
        }
      }
    }
  }

  // Convert maps -> arrays.
  const dataverseTablesUsed = [...dataverseUsed.values()].map((e) => ({
    table: e.table,
    displayName: e.displayName,
    columnsRead: [...e.columnsRead].sort(),
    columnsWritten: [...e.columnsWritten].sort(),
    operations: [...e.ops].sort(),
  }));
  const connectorsUsedArr = [...connectorsUsed.values()].map((c) => ({
    name: c.name,
    actions: [...c.actions].sort(),
  }));
  const flowsCalledArr = [...flowsCalled.values()].map((f) => ({
    name: f.name,
    actions: [...f.actions].sort(),
  }));
  const aiCallsArr = [...aiCallsMade.values()].map((a) => ({
    name: a.name,
    actions: [...a.actions].sort(),
  }));

  const layoutKind = classifyLayoutKind(screen);
  const purpose = composeScreenPurpose(screen, layoutKind, dataverseTablesUsed, outgoing);
  const userStory = composeScreenUserStory(
    screen,
    layoutKind,
    dataverseTablesUsed,
    outgoing,
    connectorsUsedArr,
    [...nativeCapsSet]
  );

  return {
    ...screen,
    layoutKind,
    purpose,
    userStory,
    nativeCapabilities: [...nativeCapsSet].sort(),
    connectorsUsed: connectorsUsedArr,
    flowsCalled: flowsCalledArr,
    aiCallsMade: aiCallsArr,
    paramsRead: [...paramsRead].sort(),
    identitySignals: [...identitySignals].sort(),
    dataverseTablesUsed,
    outgoingNavigation: outgoing,
    collectionsTouched: [...collectionsTouched].sort(),
    variablesTouched: [...variablesTouched].sort(),
    imageAssets: [...imageAssets].sort(),
    assetReferences: [...assetReferences].sort(),
    unsupported,
  };
}

function addNativeCapForKind(kind, capsSet) {
  if (!kind) return;
  const k = kind.toLowerCase();
  const map = [
    ['camera', 'camera'],
    ['barcode', 'barcode'],
    ['attachments', 'attachment'],
    ['htmlviewer', 'webview'],
    ['pdf', 'pdf'],
    ['audio', 'audio'],
    ['video', 'video'],
    ['microphone', 'mic'],
    ['mediaplayer', 'video'],
    ['signature', 'signature'],
    ['pen', 'signature'],
    ['addressinput', 'location'],
    ['map', 'map'],
    ['calendar', 'calendar'],
    ['timer', 'timer'],
    ['richtexteditor', 'richtext'],
    ['form', 'form'],
    ['gallery', 'list'],
    ['chart', 'chart'],
    ['datatable', 'dataTable'],
  ];
  for (const [needle, cap] of map) {
    if (k.includes(needle)) capsSet.add(cap);
  }
}

function ensureTableEntry(map, ref) {
  let entry = map.get(ref.logicalName);
  if (!entry) {
    entry = {
      table: ref.logicalName,
      displayName: ref.displayName,
      columnsRead: new Set(),
      columnsWritten: new Set(),
      ops: new Set(),
    };
    map.set(ref.logicalName, entry);
  }
  return entry;
}

function resolveDataverseRef(name, dataSources) {
  if (!name) return null;
  const cleaned = stripQuotes(name.trim());
  if (dataSources.dataverseByDisplay.has(cleaned)) return dataSources.dataverseByDisplay.get(cleaned);
  if (dataSources.dataverseByLogical.has(cleaned)) return dataSources.dataverseByLogical.get(cleaned);
  return null;
}

function toOpName(intent) {
  switch (intent) {
    case 'patch': return 'Patch';
    case 'update': return 'Update';
    case 'updateIf': return 'UpdateIf';
    case 'remove': return 'Remove';
    case 'removeIf': return 'RemoveIf';
    default: return intent;
  }
}

/** Mark each Dataverse table/column referenced in a free-form formula as read. */
function collectTableAndColumnRefs(formula, dataSources, dataverseUsed) {
  // Tables: any 'DisplayName' (quoted) that matches the inventory, OR any
  // unquoted token == displayName w/o spaces.
  const quoted = [...formula.matchAll(/'([^']+)'/g)].map((m) => m[1]);
  const tokens = new Set([...quoted]);
  for (const m of formula.matchAll(/\b([A-Z][A-Za-z0-9_]+)\b/g)) {
    tokens.add(m[1]);
  }
  const tablesInFormula = [];
  for (const token of tokens) {
    const ref = dataSources.dataverseByDisplay.get(token);
    if (ref) {
      ensureTableEntry(dataverseUsed, ref);
      tablesInFormula.push(ref);
    }
  }
  if (tablesInFormula.length === 0) return;

  // Columns: 'Table'.'Column' / 'Table'.Column / Table[@'Column'] / unqualified
  // 'Column' references inside Filter()/LookUp()/Sort()/Search() calls.
  for (const table of tablesInFormula) {
    const entry = ensureTableEntry(dataverseUsed, table);
    const dotPattern = new RegExp(
      `'${escapeRegex(table.displayName)}'\\.(?:'([^']+)'|([A-Za-z_][A-Za-z0-9_]*))`,
      'g'
    );
    for (const match of formula.matchAll(dotPattern)) {
      const col = match[1] || match[2];
      if (col) entry.columnsRead.add(col);
    }
    const bracketPattern = new RegExp(
      `${escapeRegex(table.displayName)}\\[@'([^']+)'\\]`,
      'g'
    );
    for (const match of formula.matchAll(bracketPattern)) {
      entry.columnsRead.add(match[1]);
    }
  }
  // Unqualified column-style refs inside Filter/LookUp/Sort/Search/SortByColumns/AddColumns/ShowColumns/DropColumns:
  // any quoted ident OR Capitalized bareword that isn't itself a table.
  const callPattern = /\b(Filter|LookUp|Sort|SortByColumns|Search|AddColumns|ShowColumns|DropColumns|GroupBy|Ungroup|First|Last|FirstN|LastN|CountIf|CountRows|Sum|Average|Max|Min)\s*\(/g;
  for (const match of formula.matchAll(callPattern)) {
    const argsBlob = sliceBalancedArgs(formula, match.index + match[0].length - 1);
    const args = splitTopLevelArgs(argsBlob);
    if (args.length < 1) continue;
    const sourceName = stripQuotes(args[0].trim().replace(/^Filter\(|\)$/g, '').trim());
    const table = dataSources.dataverseByDisplay.get(sourceName);
    if (!table) continue;
    const entry = ensureTableEntry(dataverseUsed, table);
    for (let argIdx = 1; argIdx < args.length; argIdx += 1) {
      const arg = args[argIdx];
      // 'Column' references inside predicate / column-spec args.
      for (const qm of arg.matchAll(/'([^']+)'/g)) {
        const candidate = qm[1];
        if (!dataSources.dataverseByDisplay.has(candidate)) entry.columnsRead.add(candidate);
      }
    }
  }
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function collectResourceRefs(formula, resources, imageAssets, assetReferences) {
  for (const r of resources) {
    if (!r.name) continue;
    if (formula.includes(r.name)) {
      assetReferences.add(r.name);
      if (r.content === 'Image' || r.schema === 'i') imageAssets.add(r.name);
    }
  }
}

function collectParamRefs(text, set) {
  if (!text) return;
  for (const m of String(text).matchAll(/\bParam\s*\(\s*"([^"]+)"\s*\)/g)) {
    set.add(m[1]);
  }
}

function collectIdentityRefs(text, set) {
  if (!text) return;
  const s = String(text);
  for (const m of s.matchAll(/\bOffice365Users\.([A-Za-z][A-Za-z0-9_]*)/g)) {
    set.add(`Office365Users.${m[1]}`);
  }
  if (/\bUser\s*\(\s*\)/.test(s)) set.add('User()');
}

