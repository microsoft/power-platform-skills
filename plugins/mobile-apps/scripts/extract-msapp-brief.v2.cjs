// =============================================================================
// JSON sidecar enrichment (Controls/*.json + Components/*.json)
//
// `loadJsonSidecar` produced { byScreen: Map<screenName, Map<controlName, e>>,
// defByGuid: Map<guid, {name,...}> }. These functions splice the extra facts
// onto the YAML-derived control objects so downstream rollups can use them.
// All functions are no-ops when `sidecar` is null (YAML-only extract).
// =============================================================================

function enrichControlsFromSidecar(screens, sidecar) {
  if (!sidecar) return;
  for (const screen of screens) {
    const map = sidecar.byScreen.get(screen.name);
    if (!map) continue;

    // Pass 1 — splice sidecar facts onto each YAML control.
    for (const control of screen.controlsFlat) {
      const entry = map.get(control.name);
      if (!entry) continue;
      control.isAutoGenerated = entry.isAutoGenerated;
      control.isDataControl = entry.isDataControl;
      control.isPcf = entry.isPcf;
      control.isPremiumPcf = entry.isPremiumPcf;
      control.isComponentInstance = entry.isComponentInstance;
      control.templateName = entry.templateName;
      control.templateId = entry.templateId;
      // Sidecar wins over the YAML-guessed component name when both exist.
      if (entry.componentDefinitionName) {
        control.componentName = entry.componentDefinitionName;
        control.componentDefinitionGuid = entry.componentDefinitionGuid;
      }
    }

    // Pass 2 — fold DataCard scaffold children into their parent card.
    //
    // A Studio-generated form `<typedDataCard>` ships with auto-generated
    // helper children (`DataCardKey`, `DataCardValue`, `ErrorMessage`,
    // `RequiredStar`, `StarVisible`). Listing them flat causes the converter
    // to think a single bound field is 5-7 React Native views. We collapse
    // them onto the parent DataCard as a `scaffold` summary so no information
    // is lost — the converter still sees the value template, default, items,
    // OnChange, label text, error message, required-state — but emits one
    // `<FormField/>` per card instead of seven nodes.
    //
    // We do NOT drop auto-gen DataCards themselves (Studio also marks the
    // typedDataCards under a `<form>` as auto-generated — those are real form
    // fields the user sees). They stay visible with `isAutoGeneratedFormCard`.
    //
    // NOTE: a child's `c.parent` is the parent's FULL path (e.g.
    // `Screen1/Container/Form1/DataCard1`), not just its leaf name. Match on
    // `c.parent === card.path`. Same caveat applies when we look up a control's
    // parent: `byName` is keyed by the parent's leaf name, so we resolve via
    // a `byPath` map keyed by `card.path`.
    const byPath = new Map(screen.controlsFlat.map((c) => [c.path, c]));
    for (const card of screen.controlsFlat) {
      if (!isDataCardTemplate(card.templateName)) continue;
      const scaffoldChildren = screen.controlsFlat.filter(
        (c) => c.parent === card.path && c.isAutoGenerated
      );
      if (scaffoldChildren.length === 0) continue;
      card.scaffold = summarizeDataCardScaffold(scaffoldChildren);
      for (const child of scaffoldChildren) child.isScaffold = true;
    }

    // Tag auto-gen DataCards under a <form> so the converter knows they map
    // 1:1 to Studio-generated bound fields (vs. user-customized cards).
    for (const c of screen.controlsFlat) {
      if (!c.isAutoGenerated || !isDataCardTemplate(c.templateName)) continue;
      const parent = byPath.get(c.parent);
      if (parent && (parent.templateName === 'form' || parent.template === 'form')) {
        c.isAutoGeneratedFormCard = true;
      }
    }
  }
}

function isDataCardTemplate(templateName) {
  return templateName === 'typedDataCard' || templateName === 'dataCard';
}

/**
 * Reduce a DataCard's auto-gen scaffold children to a single object that the
 * converter can render as one `<FormField/>`. Captures the value-control's
 * template (so the AI knows it's a dropdown vs date vs text vs combobox),
 * its default/items/OnChange formulas, the label text, the error message
 * formula, and required-state — exactly the contract a form field needs.
 */
function summarizeDataCardScaffold(children) {
  const scaffold = {
    labelText: null,
    valueControlName: null,
    valueTemplate: null,
    valueDefault: null,
    valueItems: null,
    valueDataField: null,
    valueOnChange: null,
    errorMessageFormula: null,
    hasErrorMessage: false,
    hasRequiredStar: false,
  };
  for (const c of children) {
    const lname = (c.name || '').toLowerCase();
    const props = c.properties || {};
    if (lname.includes('datacardkey') || (c.templateName === 'label' && /key/i.test(c.name))) {
      scaffold.labelText = props.Text || scaffold.labelText;
    } else if (lname.includes('datacardvalue')) {
      scaffold.valueControlName = c.name;
      scaffold.valueTemplate = c.templateName || c.template || null;
      scaffold.valueDefault = props.Default || null;
      scaffold.valueItems = props.Items || null;
      scaffold.valueDataField = props.DataField || null;
      scaffold.valueOnChange = props.OnChange || null;
    } else if (lname.includes('errormessage')) {
      scaffold.hasErrorMessage = true;
      if (props.Text) scaffold.errorMessageFormula = props.Text;
    } else if (/star|required/i.test(c.name)) {
      scaffold.hasRequiredStar = true;
    }
  }
  return scaffold;
}

function enrichComponentDefsFromSidecar(componentDefs, sidecar, screens) {
  if (!sidecar) return;
  // Build name -> {guid, isPcf, isPremiumPcf} from defByGuid.
  const defByName = new Map();
  for (const [guid, def] of sidecar.defByGuid.entries()) {
    defByName.set(def.name, { guid, isPcf: def.isPcf, isPremiumPcf: def.isPremiumPcf });
  }
  // Build instance index by definition name.
  const instancesByName = new Map(); // name -> [{screen, controlName}]
  for (const screen of screens) {
    for (const c of screen.controlsFlat) {
      if (!c.componentDefinitionGuid) continue;
      const def = sidecar.defByGuid.get(c.componentDefinitionGuid);
      if (!def) continue;
      const arr = instancesByName.get(def.name) || [];
      arr.push({ screen: screen.name, controlName: c.name });
      instancesByName.set(def.name, arr);
    }
  }
  for (const def of componentDefs) {
    const meta = defByName.get(def.name);
    if (meta) {
      def.templateGuid = meta.guid;
      def.isPcf = meta.isPcf;
      def.isPremiumPcf = meta.isPremiumPcf;
    }
    def.instances = instancesByName.get(def.name) || [];
    def.instanceCount = def.instances.length;
  }
}

/**
 * Collect every PCF code component on every screen as a converter-ready spec.
 *
 * Rationale: in a React Native + Tamagui + Expo target, PCF (web-component-
 * based) is never the answer — every PCF either has a first-class native
 * equivalent (date picker, signature pad, calendar, chart, map…) or the AI
 * generator can compose one from primitives. So instead of flagging PCF as
 * `unsupported`, we hand the generator the PCF's contract (template name,
 * I/O properties, premium flag) plus a heuristic native-library hint, and
 * let the generator pick the actual replacement.
 *
 * Output shape per entry: `{ screen, control, templateName, templateId,
 * isPremiumPcf, properties, nativeReplacementHint }`.
 */
function collectPcfControls(screens) {
  const out = [];
  for (const screen of screens) {
    for (const c of screen.controlsFlat) {
      if (!c.isPcf) continue;
      out.push({
        screen: screen.name,
        control: c.name,
        path: c.path,
        templateName: c.templateName || c.template || null,
        templateId: c.templateId || null,
        isPremiumPcf: !!c.isPremiumPcf,
        properties: pickPcfContract(c.properties || {}),
        nativeReplacementHint: guessNativeReplacement(c.templateName || c.template),
      });
    }
  }
  return out;
}

/**
 * Build the app-level summary of external canvas-component libraries.
 *
 * Drives off `ComponentLibraryUniqueName` (official v3 schema) attached to
 * control instances by `parseNamedNode`. Returns one entry per unique library
 * with usage stats so downstream consumers can decide whether to rebuild the
 * component locally or stub it out.
 *
 * Output shape per entry:
 *   `{ uniqueName, instanceCount, components: [{ name, instances }] }`
 */
function buildComponentLibrariesSummary(screensRolled) {
  const byLibrary = new Map(); // uniqueName -> { instanceCount, components: Map<name, count> }
  for (const screen of screensRolled) {
    for (const c of screen.controlsFlat || []) {
      const lib = c.componentLibraryUniqueName;
      if (!lib) continue;
      if (!byLibrary.has(lib)) byLibrary.set(lib, { instanceCount: 0, components: new Map() });
      const entry = byLibrary.get(lib);
      entry.instanceCount += 1;
      const componentName = c.componentName || c.templateName || c.template || '(unknown)';
      entry.components.set(componentName, (entry.components.get(componentName) || 0) + 1);
    }
  }
  return [...byLibrary.entries()]
    .map(([uniqueName, info]) => ({
      uniqueName,
      instanceCount: info.instanceCount,
      components: [...info.components.entries()]
        .map(([name, instances]) => ({ name, instances }))
        .sort((a, b) => b.instances - a.instances || a.name.localeCompare(b.name)),
    }))
    .sort((a, b) => b.instanceCount - a.instanceCount || a.uniqueName.localeCompare(b.uniqueName));
}

/** Keep only the I/O surface — what the PCF reads and what it emits. */
function pickPcfContract(properties) {
  const out = {};
  const keep = [
    'Default', 'Items', 'DataField', 'DataSource', 'Text',
    'OnChange', 'OnSelect', 'DisplayMode', 'Visible', 'Required',
  ];
  for (const k of keep) if (k in properties) out[k] = properties[k];
  return out;
}

/**
 * Heuristic mapping from PCF template name to a likely native replacement.
 * Intentionally conservative — when no pattern matches we return
 * `strategy: 'ai-decide'` so the generator is explicitly prompted to pick a
 * Tamagui/Expo equivalent from the property contract instead of falling back
 * to a webview.
 */
function guessNativeReplacement(templateName) {
  if (!templateName) {
    return { strategy: 'ai-decide', note: 'No template name; infer from properties.' };
  }
  const n = String(templateName).toLowerCase();
  if (/navigation|sidebar|side.?menu|menu/.test(n)) return { strategy: 'native-navigation', candidates: ['Expo Router Drawer', 'Expo Router Tabs'] };
  if (n.includes('calendar')) return { strategy: 'native-library', candidates: ['react-native-calendars'] };
  if (n.includes('chart') || n.includes('graph')) return { strategy: 'review-required', note: 'No chart library is guaranteed by the prebuilt runtime; approve a native summary/list or block.' };
  if (n.includes('map')) return { strategy: 'review-required', note: 'No interactive map library is guaranteed by the prebuilt runtime; approve an external-map/degraded strategy or block.' };
  if (n.includes('signature') || n.includes('penmark')) return { strategy: 'review-required', note: 'Use the Power Apps native pen package only when it is already allowlisted; otherwise block.' };
  if (n.includes('barcode') || n.includes('qr')) return { strategy: 'expo-module', candidates: ['expo-camera'] };
  if (n.includes('richtext') || n.includes('html') || n.includes('editor')) return { strategy: 'review-required', note: 'Approve plain-text/Tamagui composition or block; no rich-text library is guaranteed.' };
  if (n.includes('rating') || n.includes('star')) return { strategy: 'tamagui', candidates: ['Tamagui XStack + @expo/vector-icons'] };
  if (n.includes('slider')) return { strategy: 'tamagui', candidates: ['Tamagui Slider'] };
  if (n.includes('toggle') || n.includes('switch')) return { strategy: 'tamagui', candidates: ['Tamagui Switch'] };
  if (n.includes('image') || n.includes('photo')) return { strategy: 'expo-module', candidates: ['expo-image', 'expo-image-picker'] };
  if (n.includes('pdf')) return { strategy: 'review-required', note: 'Approve validated HTTPS open via expo-web-browser or an already-allowlisted native PDF package; otherwise block.' };
  if (n.includes('file') || n.includes('attachment')) return { strategy: 'expo-module', candidates: ['expo-document-picker', 'expo-file-system'] };
  if (n.includes('audio') || n.includes('voice')) return { strategy: 'expo-module', candidates: ['expo-audio'] };
  if (n.includes('video')) return { strategy: 'expo-module', candidates: ['expo-video'] };
  return { strategy: 'review-required', note: 'No deterministic allowlisted mapping; explicit PCF disposition approval is required.' };
}

