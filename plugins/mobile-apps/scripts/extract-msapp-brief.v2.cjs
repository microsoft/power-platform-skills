function extractAppSettings(sources) {
  const p = sources.properties || {};
  const h = sources.header || {};
  // Studio writes the explicit `OfflineEnabled: true` flag only when the app
  // uses the *legacy* offline profile. Apps bound to a *manual* offline
  // profile (the modern flow) instead carry a `ManualOfflineProfileId` GUID
  // and omit `OfflineEnabled` entirely. Treat either signal as enabled so the
  // downstream `code-apps-native` plugin can pick the right sync template.
  const manualOfflineProfileId = p.ManualOfflineProfileId || null;
  const offlineEnabled = !!p.OfflineEnabled || !!manualOfflineProfileId;
  return {
    // `DocumentAppType` is THE form-factor signal: 'Phone' / 'Tablet' /
    // 'DesktopOrTablet'. Without it the code-apps-native plugin has to guess
    // the layout from `documentLayout.width` heuristics. Surfacing it
    // verbatim lets the plugin pick the right screen template up front.
    documentAppType: p.DocumentAppType || null,
    offlineEnabled,
    offlineMode: manualOfflineProfileId
      ? 'manualProfile'
      : p.OfflineEnabled
        ? 'legacy'
        : 'none',
    hasManualOfflineProfile: !!manualOfflineProfileId,
    enableModernRuntime: !!p.EnableModernRuntime,
    enableModernControls: !!p.EnableModernControls,
    cdsMatchingEnabled: !!p.CdsMatchingEnabled,
    formulasGloballyAvailable: !!p.FormulasGloballyAvailable,
    enableInstrumentation: !!p.EnableInstrumentation,
    hasInstrumentationKey: !!p.InstrumentationKey,
    showStatusBar: p.ShowStatusBar ?? null,
    containsThirdPartyPcfControls: !!p.ContainsThirdPartyPcfControls,
    defaultConnectedDataSourceMaxGetRowsCount:
      p.DefaultConnectedDataSourceMaxGetRowsCount ?? null,
    documentLayoutMaintainAspectRatio: p.DocumentLayoutMaintainAspectRatio ?? null,
    appCopilotSchemaName: p.AppCopilotSchemaName || null,
    appDescription: p.AppDescription || p.Description || null,
    hasAuthorMetadata: !!(p.Author || p.AuthorEmail || h.Author),
    libraryDependencies: Array.isArray(p.LibraryDependencies)
      ? p.LibraryDependencies
      : (p.LibraryDependencies ? [p.LibraryDependencies] : []),
    documentLayout: {
      width: p.DocumentLayoutWidth ?? null,
      height: p.DocumentLayoutHeight ?? null,
      orientation: p.DocumentLayoutOrientation || null,
      scaleToFit: p.DocumentLayoutScaleToFit ?? null,
      lockOrientation: p.DocumentLayoutLockOrientation ?? null,
    },
    appCreatedByVersion: h.AppCreatedByVersion || null,
    docVersion: h.DocVersion || null,
    lastSavedDateTimeUTC: h.LastSavedDateTimeUTC || null,
    msAppStructureVersion: h.MSAppStructureVersion || null,
  };
}

function buildIdentitySurface(parsedScreens, appNode) {
  const signals = new Set();
  function scanProps(props) {
    for (const v of Object.values(props || {})) collectIdentityRefs(stripFormula(v), signals);
  }
  if (appNode) scanProps(appNode.properties);
  for (const screen of parsedScreens.screens) {
    scanProps(screen.properties);
    for (const c of screen.controlsFlat) scanProps(c.properties);
  }
  return {
    requiresUserProfile: signals.has('User()') || signals.has('Office365Users.MyProfile'),
    usesManagerHierarchy: signals.has('Office365Users.Manager') || signals.has('Office365Users.DirectReports'),
    usesPeopleSearch: signals.has('Office365Users.SearchUser')
      || signals.has('Office365Users.UserProfileV2')
      || signals.has('Office365Users.SearchUserV2'),
    signals: [...signals].sort(),
  };
}

function extractDeepLinkParams(parsedScreens, appNode) {
  const params = new Map(); // name -> Set(location)
  function scanNode(node, prefix) {
    for (const [k, v] of Object.entries(node.properties || {})) {
      const fx = stripFormula(v);
      if (!fx) continue;
      for (const m of fx.matchAll(/\bParam\s*\(\s*"([^"]+)"\s*\)/g)) {
        const name = m[1];
        if (!params.has(name)) params.set(name, new Set());
        params.get(name).add(`${prefix}.${k}`);
      }
    }
  }
  if (appNode) scanNode(appNode, 'App');
  for (const screen of parsedScreens.screens) {
    scanNode(screen, screen.name);
    for (const c of screen.controlsFlat) scanNode(c, c.path);
  }
  return [...params.entries()]
    .map(([name, locs]) => ({ name, usedIn: [...locs].sort() }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function inferPermissions(nativeCaps, identity) {
  const perms = new Set();
  const caps = new Set(nativeCaps);
  if (caps.has('camera') || caps.has('barcode') || caps.has('video')) perms.add('camera');
  if (caps.has('mic') || caps.has('audio')) perms.add('microphone');
  if (caps.has('location') || caps.has('map')) perms.add('location');
  if (caps.has('attachment') || caps.has('pdf') || caps.has('export')) perms.add('storage');
  if (caps.has('notification')) perms.add('notifications');
  if (identity && identity.requiresUserProfile) perms.add('userProfile');
  return [...perms].sort();
}

function extractFlowsCalled(screensRolled, appIntents, dataSources) {
  const map = new Map();
  // Side map of declared flow metadata keyed by name, so formula-discovered
  // flows can pick up `id` / `apiId` / `displayName` / `workflowEntityId`
  // from the `ServiceInfo` rows captured in `parseDataSources`.
  const declaredMeta = new Map();
  if (dataSources && Array.isArray(dataSources.flows)) {
    for (const flow of dataSources.flows) {
      declaredMeta.set(flow.name, flow);
    }
  }
  function add(flow, action, screen) {
    if (!flow) return;
    const entry = map.get(flow) || (() => {
      const meta = declaredMeta.get(flow) || {};
      return {
        name: flow,
        id: meta.id || null,
        workflowEntityId: meta.workflowEntityId || null,
        apiId: meta.apiId || null,
        displayName: meta.displayName || flow,
        actions: new Set(),
        screens: new Set(),
      };
    })();
    if (action) entry.actions.add(action);
    if (screen) entry.screens.add(screen);
    map.set(flow, entry);
  }
  for (const intent of [...(appIntents.OnStart || []), ...(appIntents.OnError || [])]) {
    if (intent.intent === 'flowCall') add(intent.flow, intent.action, 'App');
  }
  for (const screen of screensRolled) {
    for (const f of screen.flowsCalled || []) {
      for (const action of f.actions) add(f.name, action, screen.name);
    }
  }
  // Seed any flows declared via `LocalConnectionReferences` + `ServiceInfo`
  // (`shared_logicflows`) that are NOT invoked from any formula — they're
  // still real flows wired into the app and the native-shell plugin needs to
  // know they exist so deploy plans can carry them along.
  if (dataSources && Array.isArray(dataSources.flows)) {
    for (const flow of dataSources.flows) {
      if (!map.has(flow.name)) {
        map.set(flow.name, {
          name: flow.name,
          id: flow.id || null,
          workflowEntityId: flow.workflowEntityId || null,
          apiId: flow.apiId || null,
          displayName: flow.displayName || flow.name,
          actions: new Set(),
          screens: new Set(),
        });
      }
    }
  }
  return [...map.values()]
    .map((f) => ({
      name: f.name,
      id: f.id || null,
      workflowEntityId: f.workflowEntityId || null,
      apiId: f.apiId || null,
      displayName: f.displayName || f.name,
      actions: [...f.actions].sort(),
      screens: [...f.screens].sort(),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function extractAiCalls(screensRolled, appIntents) {
  const map = new Map();
  function add(connector, action, screen) {
    if (!connector) return;
    const entry = map.get(connector) || { name: connector, actions: new Set(), screens: new Set() };
    if (action) entry.actions.add(action);
    if (screen) entry.screens.add(screen);
    map.set(connector, entry);
  }
  for (const intent of [...(appIntents.OnStart || []), ...(appIntents.OnError || [])]) {
    if (intent.intent === 'aiCall') add(intent.connector, intent.action, 'App');
  }
  for (const screen of screensRolled) {
    for (const a of screen.aiCallsMade || []) {
      for (const action of a.actions) add(a.name, action, screen.name);
    }
  }
  return [...map.values()]
    .map((a) => ({ name: a.name, actions: [...a.actions].sort(), screens: [...a.screens].sort() }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function extractConnections(sources) {
  const out = [];
  for (const file of sources.connectionFiles || []) {
    try {
      const j = JSON.parse(readSourceText(file));
      out.push({
        name: path.basename(file, '.json'),
        apiId: j.ApiId || j.apiId || null,
        sourceConnectionPresent: !!(j.ConnectionId || j.id),
        sourceAccountPresent: !!(j.AccountName || j.account),
        kind: classifyConnectorKind(j.ApiId || j.apiId || ''),
      });
    } catch (_err) {
      // skip unreadable
    }
  }
  return out.sort((a, b) => (a.name || '').localeCompare(b.name || ''));
}

function classifyConnectorKind(apiId) {
  if (!apiId) return 'unknown';
  const s = String(apiId).toLowerCase();
  if (s.includes('commondataservice') || s.includes('shared_cds')) return 'dataverse';
  if (s.includes('logicflows') || s.includes('shared_flowmanagement')) return 'flow';
  if (s.includes('cognitiveservice') || s.includes('aibuilder') || s.includes('formrecognizer')) return 'ai';
  if (s.includes('shared_office365')) return 'office365';
  if (s.includes('shared_sharepoint')) return 'sharepoint';
  if (s.includes('custom') || s.includes('shared_logicapps')) return 'custom';
  return 'standard';
}

function isGuid(value) {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(value || ''));
}

function resolveConnectorDisplayName(connector, dataSources) {
  const idx = dataSources.serviceInfoByDataSource || new Map();
  for (const dsName of connector.dataSources || []) {
    const svc = idx.get(dsName);
    if (svc) return svc.ConnectorName || svc.Name || null;
  }
  return connector.connectionRefDisplayName || null;
}

function extractCustomConnectors(connectorsRolled, connections, connectorInventory) {
  const customNames = new Set();
  for (const c of connections) {
    if (c.kind === 'custom') customNames.add(c.displayName || c.name);
  }
  for (const c of connectorInventory || []) {
    const kind = classifyConnectorKind(c.apiId);
    if (c.isCustom || kind === 'custom') customNames.add(c.name);
  }
  for (const connector of connectorsRolled) {
    const kind = classifyConnectorKind(connector.apiId);
    if (connector.isCustom || kind === 'custom') customNames.add(connector.name);
  }
  return [...customNames].filter(Boolean).sort();
}

function extractPcfComponents(sources) {
  const out = [];
  for (const dir of sources.pcfDirs || []) {
    const name = path.basename(dir);
    let manifest = null;
    let manifestFile = null;
    try {
      const files = fs.readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.json'));
      if (files.length > 0) {
        manifestFile = files[0];
        manifest = JSON.parse(readSourceText(path.join(dir, files[0])));
      }
    } catch (_err) { /* ignore */ }
    out.push({
      name,
      namespace: name.includes('.') ? name.split('.')[0] : null,
      shortName: name.includes('.') ? name.split('.').slice(1).join('.') : name,
      version: manifest && (manifest.Version || manifest.version) || null,
      manifestFile,
    });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

function extractTestInventory(sources) {
  const out = [];
  for (const file of sources.testFiles || []) {
    try {
      const text = readSourceText(file);
      const caseCount = (text.match(/^\s+TestCase\w*\s*:/gm) || []).length;
      const stepCount = (text.match(/^\s+Steps:\s*\|/gm) || []).length;
      const suiteMatch = text.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*$/m);
      out.push({
        file: path.basename(file),
        suite: suiteMatch ? suiteMatch[1] : null,
        caseCount,
        stepCount,
      });
    } catch (_err) { /* skip */ }
  }
  return out.sort((a, b) => a.file.localeCompare(b.file));
}

function extractFormMappings(parsedScreens, dataSources) {
  const out = [];
  for (const screen of parsedScreens.screens) {
    for (const c of screen.controlsFlat) {
      const t = (c.template || '').toLowerCase();
      const k = (c.kind || '').toLowerCase();
      // EditForm / DisplayForm controls only — not function names like FormulaText.
      const isForm = (t === 'form' || k === 'form' || k === 'editform' || k === 'displayform' || k === 'viewform');
      if (!isForm) continue;
      const dsExpr = stripFormula(c.properties?.DataSource || '').trim();
      const dsName = stripQuotes(dsExpr);
      const ref = dataSources.dataverseByDisplay.get(dsName)
        || dataSources.dataverseByLogical.get(dsName)
        || null;
      const fields = [];
      const prefix = c.path + '/';
      for (const child of screen.controlsFlat) {
        if (!child.path.startsWith(prefix)) continue;
        const df = stripFormula(child.properties?.DataField || '').trim();
        if (df) fields.push({ control: child.path, dataField: stripQuotes(df) });
      }
      out.push({
        screen: screen.name,
        formControl: c.path,
        formKind: c.kind,
        dataSource: dsName || null,
        table: ref ? ref.logicalName : null,
        tableDisplay: ref ? ref.displayName : null,
        fields,
      });
    }
  }
  return out;
}

function inferCollectionSchemas(screensRolled, appIntents) {
  const map = new Map(); // name -> { firstSchema, firstFrom, screens:Set }
  function consider(intent, screenName) {
    if (intent.intent !== 'clearCollect' && intent.intent !== 'collect') return;
    if (!intent.collection) return;
    let entry = map.get(intent.collection);
    if (!entry) {
      entry = { name: intent.collection, firstSchema: null, firstFrom: null, screens: new Set() };
      map.set(intent.collection, entry);
    }
    if (screenName) entry.screens.add(screenName);
    if (!entry.firstSchema && intent.inferredSchema) entry.firstSchema = intent.inferredSchema;
    if (!entry.firstFrom && intent.from) entry.firstFrom = intent.from;
  }
  for (const intent of [...(appIntents.OnStart || []), ...(appIntents.OnError || [])]) {
    consider(intent, 'App');
  }
  for (const screen of screensRolled) {
    for (const c of screen.controlsFlat) {
      for (const intents of Object.values(c.events || {})) {
        for (const i of intents) consider(i, screen.name);
      }
    }
  }
  return map;
}

function inferVariableShapes(screensRolled, appIntents) {
  const map = new Map(); // name -> { kind, firstAssignment, screens:Set }
  function consider(intent, screenName) {
    if (intent.intent !== 'setVar' || !intent.name) return;
    let entry = map.get(intent.name);
    if (!entry) {
      entry = { name: intent.name, kind: null, firstAssignment: null, screens: new Set() };
      map.set(intent.name, entry);
    }
    if (screenName) entry.screens.add(screenName);
    if (!entry.firstAssignment && intent.expression) {
      const expr = intent.expression.trim();
      entry.firstAssignment = expr;
      if (expr.startsWith('{') && expr.endsWith('}')) entry.kind = 'record';
      else if (expr.startsWith('[') && expr.endsWith(']')) entry.kind = 'table';
      else if (/^"/.test(expr) || /^Text\(/.test(expr) || /^Concatenate\(/.test(expr)) entry.kind = 'text';
      else if (/^(true|false)$/i.test(expr)) entry.kind = 'boolean';
      else if (/^-?\d+(\.\d+)?$/.test(expr)) entry.kind = 'number';
      else if (/^(Today|Now|DateAdd|DateValue)\(/.test(expr)) entry.kind = 'date';
      else entry.kind = 'expression';
    }
  }
  for (const intent of [...(appIntents.OnStart || []), ...(appIntents.OnError || [])]) {
    consider(intent, 'App');
  }
  for (const screen of screensRolled) {
    for (const c of screen.controlsFlat) {
      for (const intents of Object.values(c.events || {})) {
        for (const i of intents) consider(i, screen.name);
      }
    }
  }
  return map;
}

// Component I/O typed contract enrichment from ComponentsMetadata.json.
function enrichComponentContract(parsedComponents, componentMetadata) {
  if (!componentMetadata || !parsedComponents) return;
  const byTemplate = new Map();
  const meta = Array.isArray(componentMetadata) ? componentMetadata : componentMetadata.Components || componentMetadata.components || [];
  if (!Array.isArray(meta)) return;
  for (const item of meta) {
    if (item && item.TemplateName) byTemplate.set(item.TemplateName, item);
    if (item && item.Name) byTemplate.set(item.Name, item);
  }
  for (const comp of parsedComponents.components || []) {
    const info = byTemplate.get(comp.name) || byTemplate.get(comp.templateName);
    if (!info) continue;
    const props = info.CustomProperties || info.customProperties || info.Properties || [];
    if (Array.isArray(props)) {
      comp.typedProperties = props.map((p) => ({
        name: p.Name || p.name,
        kind: p.PropertyKind || p.propertyKind || p.Kind || null,
        type: p.DataType || p.dataType || p.Type || null,
        isInput: !!(p.PropertyKind === 'Input' || p.propertyKind === 'Input' || p.Direction === 'Input'),
        isOutput: !!(p.PropertyKind === 'Output' || p.propertyKind === 'Output' || p.Direction === 'Output'),
      }));
    }
  }
}

