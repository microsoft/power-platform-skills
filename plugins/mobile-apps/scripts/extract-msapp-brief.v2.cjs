#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * extract-msapp-brief.v2.cjs
 * ---------------------------------------------------------------
 * Scan an unpacked .msapp and emit a single canonical "app brief"
 * consumable by an AI mobile-app generator (and by humans).
 *
 *   runs/<app>/outputs/app-brief/
 *     app-brief.json              ← top-level brief (data model, brand,
 *                                   nav, assets, screen index)
 *     app-brief.md                ← PM-readable summary
 *     screens/<ScreenName>.json   ← per-screen control tree + intents
 *     screens/<ScreenName>.md     ← per-screen user story + intents
 *
 * Generic — works against any extracted .msapp directory with the
 * standard layout (Src/*.pa.yaml, References/, Properties.json,
 * Header.json, Components/, Resources/). Also handles PAC SourceCode
 * layout where those sidecars stay packed under <app>.msapr/msapp/.
 *
 * Deterministic only — no LLM call. Anything we can't classify lands
 * in `unsupported[]` with the raw Power Fx so a human or follow-up AI
 * pass can fix it.
 *
 * Usage:
 *   node scripts/extract-msapp-brief.v2.cjs \
 *     --extracted <unpacked-or-downloaded-canvas-source> \
 *     [--out <migration-workspace>/app-brief] \
 *     [--app-name "Field Operations"]
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { buildArtifactNameMap, pathContains } = require('./lib/modernizer-paths.js');
const {
  formatValidationReport,
  listPowerAppsYamlSourceFiles,
  validatePowerAppsYamlSource,
} = require('./lib/power-apps-yaml-schema.js');
const { openZipReader } = require('./lib/safe-zip.js');

const MAX_SOURCE_TEXT_BYTES = 64 * 1024 * 1024;
const MAX_SOURCE_ENTRIES = 100000;
const DETERMINISTIC_EPOCH = '1970-01-01T00:00:00.000Z';

// =============================================================================
// CLI
// =============================================================================

function parseArgs(argv) {
  const args = { extracted: null, out: null, appName: null };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--extracted') {
      args.extracted = argv[++i];
    } else if (arg === '--out') {
      args.out = argv[++i];
    } else if (arg === '--app-name') {
      args.appName = argv[++i];
    } else if (arg === '--help' || arg === '-h') {
      printUsageAndExit(0);
    } else {
      console.error(`Unknown argument: ${arg}`);
      printUsageAndExit(1);
    }
  }
  if (!args.extracted) {
    printUsageAndExit(1);
  }
  args.extracted = path.resolve(args.extracted);
  if (!args.out) {
    args.out = path.resolve(args.extracted, '..', 'outputs', 'app-brief');
  } else {
    args.out = path.resolve(args.out);
  }
  return args;
}

function printUsageAndExit(code) {
  console.log(
    'Usage: node scripts/extract-msapp-brief.v2.cjs --extracted <dir> [--out <dir>] [--app-name <name>]'
  );
  process.exit(code);
}

function canonicalSourceTimestamp(value) {
  const parsed = Date.parse(String(value || ''));
  return Number.isFinite(parsed) ? new Date(parsed).toISOString() : DETERMINISTIC_EPOCH;
}

// =============================================================================
// Main
// =============================================================================

function main() {
  const args = parseArgs(process.argv.slice(2));
  assertDir(args.extracted, 'extracted folder');
  args.extracted = fs.realpathSync(args.extracted);
  assertSourceTreeSafe(args.extracted);
  if (pathContains(args.out, args.extracted)) {
    throw new Error('app-brief output must not contain the extracted source directory');
  }

  console.log(`[brief] extracted = ${args.extracted}`);
  console.log(`[brief] out       = ${args.out}`);

  // Source files are untrusted and the semantic scanner intentionally accepts
  // only a strict subset of Power Apps YAML. Validate the complete source
  // against the immutable official schema before reading formulas or controls.
  const schemaValidation = validatePowerAppsYamlSource(args.extracted);
  console.log(`[brief] schema    = ${formatValidationReport(schemaValidation)}`);

  const sources = loadSources(args.extracted);
  const parsedScreens = parseAllScreens(sources.screenFiles);
  const parsedComponents = parseAllComponents(sources.componentFiles);
  // Merge raw .msapp sidecar facts (IsAutoGenerated / PCF flags / authoritative
  // component-instance ↔ definition GUID join) onto YAML controls when present.
  // No-op when the extracted dir is YAML-only.
  enrichControlsFromSidecar(parsedScreens.screens, sources.jsonSidecar);
  const dataSources = parseDataSources(sources.properties, sources.dataSourcesRefs);
  // Phase 4: full per-table Dataverse schema (attributes / relationships /
  // option sets), the connector inventory (LocalConnectionReferences merged
  // with non-Dataverse DataSources rows), and the Dataverse environment
  // descriptor (instance URL + Web API version).
  const dataverseSchemas = buildDataverseSchemas(sources.dataSourcesRefs);
  const connectorInventory = buildConnectorInventory(
    sources.properties,
    sources.dataSourcesRefs,
    dataSources
  );
  const dataverseEnv = parseDataverseEnvironment(sources.properties);
  const publishInfo = sources.publishInfo;
  const resources = parseResources(sources.resourcesRefs);
  const componentDefs = parseComponentDefinitions(sources.componentMetadata, parsedComponents);
  enrichComponentContract(parsedComponents, sources.componentMetadata);
  enrichComponentDefsFromSidecar(componentDefs, sources.jsonSidecar, parsedScreens.screens);
  // Apply canonical authoring order from `_EditorState.pa.yaml`.
  const orderedDefs = applyAuthoringOrder(
    componentDefs,
    sources.editorState?.componentDefinitionsOrder || []
  );
  componentDefs.length = 0;
  componentDefs.push(...orderedDefs);
  const themeInfo = parseThemes(sources.themesRefs, sources.modernThemesRefs, parsedScreens.appNode);

  const intentByControlPath = new Map();
  const allIntents = [];
  for (const screen of parsedScreens.screens) {
    for (const control of screen.controlsFlat) {
      const events = classifyControlEvents(control, dataSources, parsedComponents);
      control.events = events;
      for (const event of Object.values(events).flat()) {
        allIntents.push({ screen: screen.name, control: control.path, ...event });
      }
      intentByControlPath.set(control.path, events);
    }
  }

  // App-level intents from App.OnStart, App.OnError, App.Formulas.
  const appIntents = parsedScreens.appNode
    ? classifyAppEvents(parsedScreens.appNode)
    : { OnStart: [], OnError: [], Formulas: [] };

  // Per-screen rollups.
  const screensRolled = parsedScreens.screens.map((screen) =>
    rollupScreen(screen, dataSources, parsedComponents, resources)
  );

  // Honor canonical authoring order from `_EditorState.pa.yaml`. Falls back to
  // file order when EditorState is absent or empty.
  const orderedScreensRolled = applyAuthoringOrder(
    screensRolled,
    sources.editorState?.screensOrder || []
  );
  // Mutate in place so downstream consumers (which keep a reference to
  // `screensRolled`) iterate in author order too.
  screensRolled.length = 0;
  screensRolled.push(...orderedScreensRolled);

  // App-level rollups.
  const dataModel = buildDataModelRollup(
    screensRolled,
    dataSources,
    appIntents,
    parsedScreens.appNode
  );
  for (const table of dataModel.dataverseTables) {
    if (!/^[A-Za-z][A-Za-z0-9_]{0,127}$/.test(String(table.logicalName || ''))) {
      throw new Error(`Unsafe Dataverse logical name in Canvas source: ${table.logicalName}`);
    }
  }
  const nativeCapabilities = unionStrings(screensRolled.flatMap((s) => s.nativeCapabilities));
  const navigationEdges = buildNavigationEdges(screensRolled);
  const startScreen = inferStartScreen(parsedScreens.appNode, parsedScreens.screens, navigationEdges);
  const assetSummary = enrichAssetSummary(
    buildAssetSummary(resources, screensRolled),
    sources,
    publishInfo,
    sources.resourcesRefs
  );
  const localization = buildLocalizationSummary(parsedScreens, dataSources);
  const unsupported = collectUnsupported(screensRolled, parsedComponents);

  // Extended extractors (16-gap fill).
  const settings = extractAppSettings(sources);
  const identity = buildIdentitySurface(parsedScreens, parsedScreens.appNode);
  const deepLinks = extractDeepLinkParams(parsedScreens, parsedScreens.appNode);
  const permissions = inferPermissions(nativeCapabilities, identity);
  const flowsCalled = extractFlowsCalled(screensRolled, appIntents, dataSources);
  const aiCalls = extractAiCalls(screensRolled, appIntents);
  const connections = extractConnections(sources);
  const customConnectors = extractCustomConnectors(
    dataModel.connectors,
    connections,
    connectorInventory
  );
  const pcfComponents = extractPcfComponents(sources);
  const tests = extractTestInventory(sources);
  const formMappings = extractFormMappings(parsedScreens, dataSources);

  // Augment dataModel with new derived sections.
  dataModel.flows = flowsCalled;
  dataModel.aiCalls = aiCalls;
  dataModel.customConnectors = customConnectors;
  dataModel.connections = connections;

  // Phase 4: env descriptor, slim connector inventory, per-table schema
  // summary. Per-table sidecars are written below in the output phase.
  dataModel.dataverseEnvironment = dataverseEnv;
  dataModel.connectorInventory = connectorInventory;
  if (dataverseSchemas) {
    for (const t of dataModel.dataverseTables) {
      const schema = dataverseSchemas.get(t.logicalName);
      if (!schema) continue;
      t.schemaSummary = {
        attributeCount: schema.counts.attributeCount,
        nonLogicalAttributeCount: schema.counts.nonLogicalAttributeCount,
        customAttributeCount: schema.counts.customAttributeCount,
        manyToOneCount: schema.counts.manyToOneCount,
        oneToManyCount: schema.counts.oneToManyCount,
        manyToManyCount: schema.counts.manyToManyCount,
        optionSetCount: schema.counts.optionSetCount,
        isCustomEntity: schema.isCustomEntity,
        isActivity: schema.isActivity,
        isOfflineInMobileClient: schema.isOfflineInMobileClient,
        ownershipType: schema.ownershipType,
        primaryIdAttribute: schema.primaryIdAttribute,
        primaryNameAttribute: schema.primaryNameAttribute,
        privileges: schema.privileges,
      };
      t.briefPath = `tables/${t.logicalName}.json`;
    }
  }

  // Infer collection schemas + variable shapes; attach to existing arrays.
  const collectionSchemas = inferCollectionSchemas(screensRolled, appIntents);
  for (const c of dataModel.localCollections) {
    const schemaEntry = collectionSchemas.get(c.name);
    if (schemaEntry) {
      c.firstSchema = schemaEntry.firstSchema;
      c.firstFrom = schemaEntry.firstFrom;
      c.screens = [...schemaEntry.screens].sort();
    }
  }
  const variableShapes = inferVariableShapes(screensRolled, appIntents);
  for (const v of dataModel.globalVariables) {
    const shapeEntry = variableShapes.get(v.name);
    if (shapeEntry) {
      v.kind = shapeEntry.kind;
      v.firstAssignment = shapeEntry.firstAssignment;
      v.screens = [...shapeEntry.screens].sort();
    }
  }
  const screenArtifactNames = buildArtifactNameMap(screensRolled.map((screen) => screen.name), 'screen');

  const appBrief = {
    $schema: 'https://raw.githubusercontent.com/microsoft/power-platform-skills/main/plugins/mobile-apps/scripts/schemas/app-brief.v1.schema.json',
    version: '1',
    generatedAt: canonicalSourceTimestamp(sources.header?.LastSavedDateTimeUTC),
    source: {
      extractedPath: 'local-canvas-source',
      msappName: sources.header?.Name,
      msappVersion: sources.header?.DocVersion,
      msappLastSavedUtc: sources.header?.LastSavedDateTimeUTC,
      format: sources.format,
      schemaValidation: {
        schema: schemaValidation.$schema,
        version: schemaValidation.schema.version,
        id: schemaValidation.schema.id,
        sourceCommit: schemaValidation.schema.sourceCommit,
        sha256: schemaValidation.schema.sha256,
        sourceFileCount: schemaValidation.sourceFileCount,
        sectionCounts: schemaValidation.sectionCounts,
      },
    },
    app: {
      name: args.appName || deriveAppName(sources) || 'UnknownApp',
      displayName: themeInfo.displayName,
      startScreen,
      documentLayout: parsedScreens.documentLayout,
      brand: themeInfo.brand,
      auth: dataModel.dataverseTables.length > 0 ? 'entra' : 'none',
      onStartIntents: appIntents.OnStart,
      onErrorIntents: appIntents.OnError,
      globalFormulas: appIntents.Formulas,
      onStartRaw: stripFormula(parsedScreens.appNode?.properties?.OnStart) || null,
      onErrorRaw: stripFormula(parsedScreens.appNode?.properties?.OnError) || null,
      namedFormulasRaw: stripFormula(parsedScreens.appNode?.properties?.Formulas) || null,
      settings,
      identity,
      permissions,
      deepLinks,
      pcfControls: collectPcfControls(parsedScreens.screens),
      // External canvas-component libraries referenced by the app. Derived
      // from `ComponentLibraryUniqueName` on control instances (official
      // schema field). Empty when the app uses only local components.
      componentLibraries: buildComponentLibrariesSummary(screensRolled),
      userStory: composeAppUserStory(args.appName || deriveAppName(sources) || 'this app', screensRolled, dataModel),
    },
    dataModel,
    nativeCapabilities,
    pcfComponents,
    tests,
    forms: formMappings,
    assets: assetSummary,
    localization,
    navigation: { startScreen, edges: navigationEdges },
    components: componentDefs,
    screens: screensRolled.map((screen) => ({
      name: screen.name,
      file: path.relative(args.extracted, screen.file).replace(/\\/g, '/'),
      purpose: screen.purpose,
      userStory: screen.userStory,
      layoutKind: screen.layoutKind,
      controlCount: screen.controlsFlat.length,
      scaffoldControlCount: screen.controlsFlat.filter((c) => c.isScaffold).length,
      autoGenFormCardCount: screen.controlsFlat.filter((c) => c.isAutoGeneratedFormCard).length,
      nativeCapabilities: screen.nativeCapabilities,
      connectorsUsed: screen.connectorsUsed,
      flowsCalled: screen.flowsCalled || [],
      aiCallsMade: screen.aiCallsMade || [],
      paramsRead: screen.paramsRead || [],
      identitySignals: screen.identitySignals || [],
      dataverseTablesUsed: screen.dataverseTablesUsed.map((t) => t.table),
      outgoingTo: screen.outgoingNavigation.map((n) => n.target),
      incomingFrom: [], // filled below from navigationEdges
      briefPath: `screens/${screenArtifactNames.get(screen.name)}.json`,
    })),
    unsupported,
  };

  // Fill incomingFrom.
  for (const screenEntry of appBrief.screens) {
    screenEntry.incomingFrom = navigationEdges
      .filter((edge) => edge.to === screenEntry.name)
      .map((edge) => edge.from);
  }

  // Write outputs.
  recreateDir(args.out);
  writeJson(path.join(args.out, 'app-brief.json'), appBrief);
  writeText(path.join(args.out, 'app-brief.md'), renderAppBriefMarkdown(appBrief));

  const screensDir = path.join(args.out, 'screens');
  recreateDir(screensDir);
  for (const screen of screensRolled) {
    const artifactName = screenArtifactNames.get(screen.name);
    const screenBrief = buildScreenBrief(screen, dataModel, args.extracted);
    writeJson(path.join(screensDir, `${artifactName}.json`), screenBrief);
    writeText(path.join(screensDir, `${artifactName}.md`), renderScreenBriefMarkdown(screenBrief));
  }

  // Phase 4: per-table Dataverse schema sidecars. We emit one file per table
  // *referenced by the app* so the brief stays small while the converter (or
  // code-apps-native plugin) can lazily pull full schema for the tables it
  // needs to scaffold/detect. Tables only reachable via lookup targets (not
  // directly used) are not emitted to keep the surface tight.
  let tableSidecarCount = 0;
  if (dataverseSchemas) {
    const tablesDir = path.join(args.out, 'tables');
    recreateDir(tablesDir);
    for (const t of dataModel.dataverseTables) {
      const schema = dataverseSchemas.get(t.logicalName);
      if (!schema) continue;
      writeJson(path.join(tablesDir, `${t.logicalName}.json`), schema);
      tableSidecarCount += 1;
    }
  }

  console.log(
    `[brief] wrote ${1 /* app-brief.json */ + 1 /* app-brief.md */ + screensRolled.length * 2 + tableSidecarCount} files to ${relForLog(args.out)}`
  );
  console.log(
    `[brief] summary: ${screensRolled.length} screens, ${dataModel.dataverseTables.length} dataverse tables (${tableSidecarCount} schema sidecars), ${dataModel.connectors.length} connectors, ${nativeCapabilities.length} native caps, ${unsupported.length} unsupported items`
  );
}

// =============================================================================
// Source loading
// =============================================================================

function loadSources(extractedRoot) {
  const source = createSourceReader(extractedRoot);
  // Power Apps source exports have appeared with both `Src` and `src` casing.
  // macOS often masks that difference, but Linux CI and customer repos do not,
  // so resolve observed variants rather than making extraction OS-dependent.
  const srcRoot = firstExistingDir(extractedRoot, ['Src', 'src']) || path.join(extractedRoot, 'Src');
  const componentsRoot = firstExistingDir(srcRoot, ['Components', 'components']) || path.join(srcRoot, 'Components');
  const connectionsRoot = firstExistingDir(extractedRoot, ['Connections', 'connections']) || path.join(extractedRoot, 'Connections');
  const testsRoot = firstExistingDir(extractedRoot, ['Tests', 'tests']) || path.join(extractedRoot, 'Tests');
  const pkgsRoot = path.join(extractedRoot, 'pkgs');

  // Use the same recursive inventory that passed schema validation. Parsing
  // every logical module for each supported top-level section ensures nested
  // official layouts cannot validate successfully and then disappear from the
  // semantic brief.
  const sourceFiles = listPowerAppsYamlSourceFiles(extractedRoot);
  const screenFiles = sourceFiles.filter((file) => path.basename(file) !== '_EditorState.pa.yaml');
  const componentFiles = screenFiles;
  const editorStateFile = sourceFiles.find((file) => path.basename(file) === '_EditorState.pa.yaml');
  const editorState = editorStateFile
    ? parseEditorStateYaml(readSourceText(editorStateFile))
    : { screensOrder: [], componentDefinitionsOrder: [] };
  // Tests may be `.fx.yaml` (Test Studio) or `.pa.yaml` (newer).
  const testFiles = fs.existsSync(testsRoot)
    ? [...listFiles(testsRoot, '.fx.yaml'), ...listFiles(testsRoot, '.pa.yaml')]
    : [];
  const connectionFiles = fs.existsSync(connectionsRoot)
    ? listFiles(connectionsRoot, '.json')
    : [];
  // PCF code components live under pkgs/Components/<namespace>.<name>/
  const pcfComponentsRoot = path.join(pkgsRoot, 'Components');
  const pcfDirs = fs.existsSync(pcfComponentsRoot) ? listSubdirs(pcfComponentsRoot) : [];
  const jsonSidecar = loadJsonSidecar(source);

  return {
    extractedRoot,
    sourceReader: source,
    format: jsonSidecar
      ? (source.msaprPath ? 'unpacked-msapp+msapr-sidecar' : 'unpacked-msapp+json-sidecar')
      : 'unpacked-msapp-yaml-only',
    screenFiles,
    editorState,
    componentFiles,
    testFiles,
    connectionFiles,
    pcfDirs,
    properties: source.readJson('Properties.json'),
    header: source.readJson('Header.json'),
    componentMetadata: source.readJson('ComponentsMetadata.json'),
    dataSourcesRefs: source.readJson('References/DataSources.json'),
    resourcesRefs: source.readJson('References/Resources.json'),
    themesRefs: source.readJson('References/Themes.json'),
    modernThemesRefs: source.readJson('References/ModernThemes.json'),
    templatesRefs: source.readJson('References/Templates.json'),
    publishInfo: source.readJson('Resources/PublishInfo.json'),
    jsonSidecar,
  };
}

function firstExistingDir(parent, names) {
  for (const name of names) {
    const candidate = path.join(parent, name);
    if (fs.existsSync(candidate) && fs.lstatSync(candidate).isDirectory()) return candidate;
  }
  return null;
}

function createSourceReader(extractedRoot) {
  const msaprPath = findMsaprPackage(extractedRoot);
  const archive = msaprPath ? openZipReader(msaprPath, {
    label: 'MSAPR',
    unsupportedMethod: 'skip',
    onWarning(message) {
      console.warn(`[brief] WARN ${message}`);
    },
  }) : null;
  const prefix = 'msapp/';

  function safeRelative(relPath) {
    const raw = String(relPath || '').replace(/\\/g, '/');
    if (!raw || raw.startsWith('/') || /^[A-Za-z]:/.test(raw) || /[\u0000-\u001f\u007f]/.test(raw)) {
      throw new Error(`unsafe source-relative path: ${relPath}`);
    }
    const segments = raw.split('/');
    if (segments.some((segment) => segment === '..')) throw new Error(`source-relative path escapes root: ${relPath}`);
    return path.posix.normalize(raw).replace(/^\.\//, '');
  }

  function archivePath(relPath) {
    return prefix + safeRelative(relPath);
  }

  function diskPath(relPath) {
    const resolved = path.resolve(extractedRoot, safeRelative(relPath));
    if (!pathContains(extractedRoot, resolved)) throw new Error(`source-relative path escapes root: ${relPath}`);
    return resolved;
  }

  function readText(relPath) {
    const file = diskPath(relPath);
    if (fs.existsSync(file)) return readSourceText(file);
    if (!archive) return null;
    const data = archive.readEntry(archivePath(relPath));
    return data ? data.toString('utf8') : null;
  }

  return {
    extractedRoot,
    msaprPath,
    readJson(relPath) {
      const text = readText(relPath);
      if (text == null) return null;
      try {
        return JSON.parse(text);
      } catch (err) {
        console.warn(`[brief] WARN failed to parse ${relPath}: ${err.message}`);
        return null;
      }
    },
    hasDir(relDir) {
      if (fs.existsSync(diskPath(relDir)) && fs.lstatSync(diskPath(relDir)).isDirectory()) return true;
      return archive ? archive.hasPrefix(archivePath(relDir).replace(/\/$/, '') + '/') : false;
    },
    listFiles(relDir, suffix) {
      const out = new Set();
      const dir = diskPath(relDir);
      if (fs.existsSync(dir) && fs.lstatSync(dir).isDirectory()) {
        for (const file of listFiles(dir, suffix)) out.add(path.relative(extractedRoot, file).replace(/\\/g, '/'));
      }
      if (archive) {
        const base = archivePath(relDir).replace(/\/$/, '') + '/';
        for (const name of archive.listEntries(base, suffix)) out.add(name.slice(prefix.length));
      }
      return [...out].sort();
    },
    stat(relPath) {
      const file = diskPath(relPath);
      if (fs.existsSync(file)) {
        const stat = fs.lstatSync(file);
        if (stat.isSymbolicLink() || !stat.isFile()) return null;
        return stat;
      }
      if (!archive) return null;
      const entry = archive.getEntry(archivePath(relPath));
      return entry ? { size: entry.uncompressedSize } : null;
    },
    displayPath(relPath) {
      const file = diskPath(relPath);
      if (fs.existsSync(file) && fs.lstatSync(file).isFile() && !fs.lstatSync(file).isSymbolicLink()) {
        return path.relative(extractedRoot, file).replace(/\\/g, '/');
      }
      return archive ? `msapr:${archivePath(relPath)}` : null;
    },
  };
}

function findMsaprPackage(extractedRoot) {
  if (!fs.existsSync(extractedRoot)) return null;
  const candidates = fs
    .readdirSync(extractedRoot)
    .filter((name) => name.toLowerCase().endsWith('.msapr'))
    .map((name) => path.join(extractedRoot, name))
    .filter((file) => fs.lstatSync(file).isFile() && !fs.lstatSync(file).isSymbolicLink())
    .sort();
  return candidates[0] || null;
}

/**
 * Optional raw .msapp JSON sidecar loader.
 *
 * `pasopa` / some `pac canvas unpack` layouts emit both `Src/*.pa.yaml`
 * (which we parse) and `Controls/*.json` + `Components/*.json` (raw studio
 * format). PAC SourceCode layout can instead leave those JSON files inside
 * `<app>.msapr/msapp/`; `createSourceReader` makes both shapes look the same.
 * Newer source-first / git-tracked Power Apps ship YAML only.
 *
 * When sidecar dirs exist we extract three fields not present in YAML:
 *  - `IsAutoGenerated`              — form sub-controls Studio generates
 *                                     automatically; the converter should
 *                                     skip these.
 *  - `Template.FirstParty`           — `false` ⇒ PCF code component.
 *  - `Template.IsPremiumPcfControl` — premium PCF (license-gated → unsupported).
 *  - `Template.Name` (GUID) for component instances → resolves to a
 *    `Components/*.json` definition by GUID match, giving an authoritative
 *    instance → definition link.
 *
 * Returns `null` when either dir is absent so callers can stay YAML-only.
 */
function loadJsonSidecar(source) {
  if (!source.hasDir('Controls') || !source.hasDir('Components')) return null;

  // Pass 1: scan Components/*.json to build a GUID → definition-name map.
  const defByGuid = new Map(); // guid -> { name, file, isPcf, isPremiumPcf }
  const defFiles = source.listFiles('Components', '.json');
  for (const file of defFiles) {
    const j = source.readJson(file);
    const tp = j?.TopParent;
    if (!tp) continue;
    const guid = tp.Template?.Name;
    if (!guid || !tp.Template?.IsComponentDefinition) continue;
    defByGuid.set(guid, {
      name: tp.Name,
      file: path.basename(file),
      isPcf: tp.Template?.FirstParty === false,
      isPremiumPcf: !!tp.Template?.IsPremiumPcfControl,
    });
  }

  // Pass 2: scan Controls/*.json. Each top-level node is a screen (or `App`).
  // Build per-screen Map<controlName, sidecarEntry>.
  const byScreen = new Map(); // screenName -> Map<controlName, entry>
  const ctrlFiles = source.listFiles('Controls', '.json');
  for (const file of ctrlFiles) {
    const j = source.readJson(file);
    const tp = j?.TopParent;
    if (!tp || !tp.Name) continue;
    const screenName = tp.Name;
    const map = byScreen.get(screenName) || new Map();
    walkSidecarNode(tp, map, defByGuid);
    byScreen.set(screenName, map);
  }

  return { byScreen, defByGuid };
}

function walkSidecarNode(node, outMap, defByGuid) {
  if (!node || !node.Name) return;
  const t = node.Template || {};
  const guid = t.Name;
  const matchedDef = guid && defByGuid.get(guid);
  outMap.set(node.Name, {
    isAutoGenerated: !!node.IsAutoGenerated,
    isDataControl: !!node.IsDataControl,
    isPcf: t.FirstParty === false,
    isPremiumPcf: !!t.IsPremiumPcfControl,
    isComponentInstance: !!matchedDef,
    componentDefinitionName: matchedDef ? matchedDef.name : null,
    componentDefinitionGuid: matchedDef ? guid : null,
    templateId: t.Id || null,
    templateName: t.Name || null,
  });
  for (const child of (node.Children || [])) walkSidecarNode(child, outMap, defByGuid);
}

function listFiles(dir, suffix) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith(suffix))
    .map((name) => path.join(dir, name))
    .filter((file) => fs.lstatSync(file).isFile())
    .sort();
}

function listSubdirs(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => path.join(dir, d.name))
    .sort();
}

function readJsonIfExists(file) {
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(readSourceText(file));
  } catch (err) {
    console.warn(`[brief] WARN failed to parse ${file}: ${err.message}`);
    return null;
  }
}

function assertDir(p, label) {
  if (!fs.existsSync(p) || !fs.statSync(p).isDirectory()) {
    console.error(`[brief] ERROR ${label} not found: ${p}`);
    process.exit(2);
  }
}

function readSourceText(file) {
  const stat = fs.lstatSync(file);
  if (stat.isSymbolicLink() || !stat.isFile()) throw new Error(`source artifact must be a regular file: ${file}`);
  if (stat.size > MAX_SOURCE_TEXT_BYTES) throw new Error(`source artifact exceeds ${MAX_SOURCE_TEXT_BYTES} bytes: ${file}`);
  return fs.readFileSync(file, 'utf8');
}

function assertSourceTreeSafe(root) {
  let entries = 0;
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      entries += 1;
      if (entries > MAX_SOURCE_ENTRIES) throw new Error(`source tree exceeds ${MAX_SOURCE_ENTRIES} entries`);
      if (/[\u0000-\u001f\u007f]/.test(entry.name)) throw new Error('control characters are not allowed in Canvas source paths');
      const full = path.join(dir, entry.name);
      if (entry.isSymbolicLink()) {
        throw new Error(`symbolic links are not allowed in Canvas source: ${path.relative(root, full).replace(/\\/g, '/')}`);
      }
      if (entry.isDirectory()) walk(full);
    }
  }
  walk(root);
}

// =============================================================================
// YAML scanner — purpose-built for canvas .pa.yaml
//
// We don't need a general YAML parser. The canvas YAML has a strict shape:
//   App:
//     Properties:
//       PropName: =formula
//       PropName: |-
//         =multi-line-formula
//     ...
//   Screens:
//     ScreenName:
//       Properties: {...}
//       Children:
//         - ControlName:
//             Control: ClassicButton@2.2.0
//             Variant: ManualLayout
//             ComponentName: HeaderComponent       (only when Control: CanvasComponent)
//             Properties: {...}
//             Children: [...recursive...]
// =============================================================================

function parseAllScreens(files) {
  const allScreens = [];
  let appNode = null;
  let documentLayout = { width: 1366, height: 768, orientation: 'landscape' };

  for (const file of files) {
    const text = readSourceText(file);
    const parsed = parseCanvasYaml(text, file);
    if (parsed.app) {
      appNode = parsed.app;
      // Document layout from App.Properties.
      const props = parsed.app.properties || {};
      const heightFx = stripFormula(props.MinScreenHeight || props.SizeBreakpoints || '');
      const widthFx = stripFormula(props.MinScreenWidth || '');
      const h = parseFloat(heightFx);
      const w = parseFloat(widthFx);
      if (Number.isFinite(h)) documentLayout.height = h;
      if (Number.isFinite(w)) documentLayout.width = w;
      documentLayout.orientation = documentLayout.height >= documentLayout.width ? 'portrait' : 'landscape';
    }
    for (const screen of parsed.screens) {
      allScreens.push({
        ...screen,
        file,
        controlsFlat: flattenControls(screen.controls, screen.name),
      });
    }
  }
  return { screens: allScreens, appNode, documentLayout };
}

function parseAllComponents(files) {
  const components = new Map(); // ComponentName -> { name, controls, properties }
  for (const file of files) {
    const text = readSourceText(file);
    const parsed = parseCanvasYaml(text, file);
    for (const component of parsed.components) {
      components.set(component.name, {
        ...component,
        file,
        controlsFlat: flattenControls(component.controls, component.name),
      });
    }
  }
  return components;
}

/**
 * Parse the optional `Src/_EditorState.pa.yaml` and return the canonical
 * authoring order for screens and component definitions. Returning empty
 * arrays signals "no preference" so callers fall back to file order.
 *
 * Schema (v3 official):
 *   EditorState:
 *     ScreensOrder: [Screen1, Screen2, ...]
 *     ComponentDefinitionsOrder: [Component1, ...]
 */
function parseEditorStateYaml(text) {
  const out = { screensOrder: [], componentDefinitionsOrder: [] };
  const lines = text.split(/\r?\n/);
  let mode = null;
  let inEditorState = false;
  for (const raw of lines) {
    const line = raw.replace(/\s+$/, '');
    if (line === '' || /^\s*#/.test(line)) continue;
    if (/^EditorState\s*:\s*$/.test(line)) { inEditorState = true; continue; }
    if (!inEditorState) continue;
    const sectionMatch = /^\s{2}(ScreensOrder|ComponentDefinitionsOrder)\s*:\s*$/.exec(line);
    if (sectionMatch) {
      mode = sectionMatch[1] === 'ScreensOrder' ? 'screens' : 'components';
      continue;
    }
    if (mode) {
      const itemMatch = /^\s{4}-\s+(.+?)\s*$/.exec(line);
      if (itemMatch) {
        const name = stripYamlQuotes(itemMatch[1]);
        if (mode === 'screens') out.screensOrder.push(name);
        else out.componentDefinitionsOrder.push(name);
        continue;
      }
      // Any other line at indent <= 2 ends the current section.
      const indent = line.match(/^(\s*)/)[1].length;
      if (indent <= 2) mode = null;
    }
  }
  return out;
}

/**
 * Reorder an array of `{ name }` records using a name-ordered list.
 * Items not present in `order` are appended at the end in their original order.
 */
function applyAuthoringOrder(items, order) {
  // Callers replace their original arrays in place after ordering. Returning
  // the same array here would make `items.length = 0; items.push(...ordered)`
  // erase every item when EditorState is absent, so always return a new array.
  if (!Array.isArray(order) || order.length === 0) return items.slice();
  const pos = new Map(order.map((name, idx) => [name, idx]));
  const decorated = items.map((item, originalIdx) => ({
    item,
    primary: pos.has(item.name) ? pos.get(item.name) : order.length,
    secondary: originalIdx,
  }));
  decorated.sort((a, b) => a.primary - b.primary || a.secondary - b.secondary);
  return decorated.map((d) => d.item);
}

/**
 * Parse a single .pa.yaml file. Returns { app: AppNode|null, screens: ScreenNode[], components: ComponentNode[] }
 * where each Node has { name, properties: {prop: formulaString}, controls: ControlNode[] }
 */
function parseCanvasYaml(text, filePath) {
  const lines = text.split(/\r?\n/);
  // Strip leading comment block.
  let i = 0;
  while (i < lines.length && (lines[i].startsWith('#') || lines[i].trim() === '')) i += 1;

  const result = { app: null, screens: [], components: [] };
  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#')) {
      i += 1;
      continue;
    }
    if (/^App\s*:/.test(trimmed)) {
      const node = parseNamedNode(lines, i + 1, 2);
      result.app = { name: 'App', ...node.node, file: filePath };
      i = node.nextIndex;
      continue;
    }
    if (/^Screens\s*:/.test(trimmed)) {
      const block = parseChildrenAtIndent(lines, i + 1, 2);
      for (const child of block.children) {
        // Each child here is a screen.
        result.screens.push({ name: child.name, ...child, file: filePath });
      }
      i = block.nextIndex;
      continue;
    }
    if (/^ComponentDefinitions\s*:/.test(trimmed) || /^Components\s*:/.test(trimmed)) {
      const block = parseChildrenAtIndent(lines, i + 1, 2);
      for (const child of block.children) {
        result.components.push({ name: child.name, ...child, file: filePath });
      }
      i = block.nextIndex;
      continue;
    }
    i += 1;
  }
  return result;
}

/**
 * Parse a node header that's been keyed at the parent indent.
 * Reads optional `Properties:`, `Children:`, `Control:`, `Variant:`, `ComponentName:`,
 * plus official-schema fields: `Group`, `MetadataKey`, `Layout`, `IsLocked`,
 * `ComponentLibraryUniqueName` (control instances) and `DefinitionType`,
 * `Description`, `AccessAppScope`, `AllowCustomization`, `CustomProperties`
 * (component definitions).
 * `lines[startIndex]` is the first line inside the node body.
 */
function parseNamedNode(lines, startIndex, indent) {
  let i = startIndex;
  const node = {
    properties: {},
    controls: [],
    control: null,
    variant: null,
    componentName: null,
    // Optional control-instance fields (canvas YAML v3 official schema).
    componentLibraryUniqueName: null,
    metadataKey: null,
    layout: null,
    isLocked: null,
    group: null,
    // Optional ComponentDefinition fields.
    definitionType: null,
    description: null,
    accessAppScope: null,
    allowCustomization: null,
    customProperties: null,
  };
  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();
    if (trimmed === '') {
      i += 1;
      continue;
    }
    const lineIndent = countIndent(line);
    if (lineIndent < indent) break;
    if (lineIndent > indent) {
      i += 1;
      continue;
    }
    // exactly at indent.
    if (/^Properties\s*:\s*$/.test(trimmed)) {
      const block = parsePropertyBlock(lines, i + 1, indent + 2);
      node.properties = block.properties;
      i = block.nextIndex;
      continue;
    }
    if (/^Children\s*:\s*$/.test(trimmed)) {
      const block = parseChildrenList(lines, i + 1, indent + 2);
      node.controls = block.children;
      i = block.nextIndex;
      continue;
    }
    if (/^CustomProperties\s*:\s*$/.test(trimmed)) {
      const block = parseCustomPropertiesBlock(lines, i + 1, indent + 2);
      node.customProperties = block.properties;
      i = block.nextIndex;
      continue;
    }
    // Simple-scalar fields. Use a single regex + a switch on the key so we
    // pick up every official-schema string/boolean field with no extra parsing.
    const scalarMatch = /^([A-Za-z][A-Za-z0-9]*)\s*:\s*(.+?)\s*$/.exec(trimmed);
    if (scalarMatch) {
      const key = scalarMatch[1];
      const valueRaw = scalarMatch[2];
      switch (key) {
        case 'Control': node.control = valueRaw; break;
        case 'Variant': node.variant = valueRaw; break;
        case 'ComponentName': node.componentName = valueRaw; break;
        case 'ComponentLibraryUniqueName': node.componentLibraryUniqueName = valueRaw; break;
        case 'MetadataKey': node.metadataKey = valueRaw; break;
        case 'Layout': node.layout = valueRaw; break;
        case 'Group': node.group = valueRaw; break;
        case 'IsLocked': node.isLocked = /^true$/i.test(valueRaw); break;
        case 'DefinitionType': node.definitionType = valueRaw; break;
        case 'Description': node.description = stripYamlQuotes(valueRaw); break;
        case 'AccessAppScope': node.accessAppScope = /^true$/i.test(valueRaw); break;
        case 'AllowCustomization': node.allowCustomization = /^true$/i.test(valueRaw); break;
        default: /* unknown sibling key — leave untouched */ break;
      }
    }
    i += 1;
  }
  return { node, nextIndex: i };
}

function stripYamlQuotes(s) {
  if (typeof s !== 'string') return s;
  if (s.length >= 2 && ((s[0] === '"' && s.endsWith('"')) || (s[0] === "'" && s.endsWith("'")))) {
    return s.slice(1, -1);
  }
  return s;
}

/**
 * Parse a `CustomProperties:` block (component definition).
 *   prop_foo:
 *     PropertyKind: Input
 *     DataType: Number
 *     Default: =0
 *     RaiseOnReset: true
 *     Description: ...
 *     ReturnType: Number   # only for *Function/Event/Action kinds
 *     Parameters:          # ditto — keep verbatim as a YAML-shaped array
 *       - p1:
 *           DataType: Text
 *
 * Returns `{ properties: { [name]: { propertyKind, dataType, returnType, default, raiseOnReset, description, parameters } }, nextIndex }`.
 * Parameters preserved as raw YAML-line strings (we don't need to deeply parse them today).
 */
function parseCustomPropertiesBlock(lines, startIndex, indent) {
  const properties = {};
  let i = startIndex;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === '') { i += 1; continue; }
    const lineIndent = countIndent(line);
    if (lineIndent < indent) break;
    if (lineIndent > indent) { i += 1; continue; }
    const trimmed = line.trim();
    const propMatch = /^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*$/.exec(trimmed);
    if (!propMatch) { i += 1; continue; }
    const propName = propMatch[1];
    const propBlockIndent = indent + 2;
    const entry = {
      propertyKind: null,
      dataType: null,
      returnType: null,
      default: null,
      raiseOnReset: null,
      description: null,
      parameters: null,
    };
    let j = i + 1;
    while (j < lines.length) {
      const inner = lines[j];
      if (inner.trim() === '') { j += 1; continue; }
      const innerIndent = countIndent(inner);
      if (innerIndent < propBlockIndent) break;
      if (innerIndent > propBlockIndent) { j += 1; continue; }
      const innerTrimmed = inner.trim();
      const m = /^([A-Za-z][A-Za-z0-9]*)\s*:\s*(.*)$/.exec(innerTrimmed);
      if (m) {
        const k = m[1];
        const v = m[2];
        switch (k) {
          case 'PropertyKind': entry.propertyKind = v; break;
          case 'DataType': entry.dataType = v; break;
          case 'ReturnType': entry.returnType = v; break;
          case 'Default':
            entry.default = v.startsWith('=') ? v : (v ? `=${v}` : null);
            break;
          case 'RaiseOnReset': entry.raiseOnReset = /^true$/i.test(v); break;
          case 'Description': entry.description = stripYamlQuotes(v); break;
          case 'Parameters': {
            // Slurp the sub-list verbatim so we can render it later.
            const paramIndent = propBlockIndent + 2;
            const params = [];
            j += 1;
            while (j < lines.length) {
              const pl = lines[j];
              if (pl.trim() === '') { j += 1; continue; }
              const pi = countIndent(pl);
              if (pi < paramIndent) break;
              params.push(pl.slice(paramIndent));
              j += 1;
            }
            entry.parameters = params.length ? params.join('\n') : null;
            continue;
          }
          default: /* ignore unknown */ break;
        }
      }
      j += 1;
    }
    properties[propName] = entry;
    i = j;
  }
  return { properties, nextIndex: i };
}

/** Properties block: lines like `PropName: =formula` or `PropName: |-` followed by block. */
function parsePropertyBlock(lines, startIndex, indent) {
  const properties = {};
  let i = startIndex;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === '') {
      i += 1;
      continue;
    }
    const lineIndent = countIndent(line);
    if (lineIndent < indent) break;
    if (lineIndent > indent) {
      i += 1;
      continue;
    }
    const trimmed = line.trim();
    const inlineMatch = /^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*=(.*)$/.exec(trimmed);
    const blockMatch = /^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(\|-|\|\+|\|)\s*$/.exec(trimmed);
    const quotedScalarMatch = /^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*"((?:[^"\\]|\\.)*)"\s*$/.exec(trimmed);
    const simpleScalarMatch = /^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.+?)\s*$/.exec(trimmed);
    if (inlineMatch) {
      properties[inlineMatch[1]] = `=${inlineMatch[2]}`;
      i += 1;
      continue;
    }
    if (quotedScalarMatch) {
      // Decode YAML double-quoted escapes (\n, \r, \t, \", \\).
      const decoded = quotedScalarMatch[2]
        .replace(/\\n/g, '\n')
        .replace(/\\r/g, '\r')
        .replace(/\\t/g, '\t')
        .replace(/\\"/g, '"')
        .replace(/\\\\/g, '\\');
      properties[quotedScalarMatch[1]] = decoded.startsWith('=') ? decoded : `=${decoded}`;
      i += 1;
      continue;
    }
    if (blockMatch) {
      const blockProp = blockMatch[1];
      const blockLines = [];
      i += 1;
      const blockIndent = indent + 2;
      while (i < lines.length) {
        const nextLine = lines[i];
        if (nextLine.trim() === '') {
          blockLines.push('');
          i += 1;
          continue;
        }
        const nextIndent = countIndent(nextLine);
        if (nextIndent < blockIndent) break;
        blockLines.push(nextLine.slice(blockIndent));
        i += 1;
      }
      const formula = blockLines.join('\n').replace(/\s+$/, '');
      properties[blockProp] = formula.startsWith('=') ? formula : `=${formula}`;
      continue;
    }
    if (simpleScalarMatch) {
      properties[simpleScalarMatch[1]] = simpleScalarMatch[2];
      i += 1;
      continue;
    }
    i += 1;
  }
  return { properties, nextIndex: i };
}

/** Children list: list of `- Name:` blocks. */
function parseChildrenList(lines, startIndex, indent) {
  const children = [];
  let i = startIndex;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === '') {
      i += 1;
      continue;
    }
    const lineIndent = countIndent(line);
    if (lineIndent < indent) break;
    const trimmed = line.trim();
    const childMatch = /^-\s*([^:]+?)\s*:\s*$/.exec(trimmed);
    if (!childMatch) {
      i += 1;
      continue;
    }
    const childName = childMatch[1];
    // Body lines (Control:, Properties:, Children:, ...) sit four spaces in
    // from the dash — two for the "- ", two for the standard indent step.
    const headerIndent = lineIndent + 4;
    const inner = parseNamedNode(lines, i + 1, headerIndent);
    children.push({ name: childName, ...inner.node });
    i = inner.nextIndex;
  }
  return { children, nextIndex: i };
}

/** Like parseChildrenList but for map-style children (no `- ` prefix), e.g. Screens block. */
function parseChildrenAtIndent(lines, startIndex, indent) {
  const children = [];
  let i = startIndex;
  while (i < lines.length) {
    const line = lines[i];
    if (line.trim() === '') {
      i += 1;
      continue;
    }
    const lineIndent = countIndent(line);
    if (lineIndent < indent) break;
    if (lineIndent > indent) {
      i += 1;
      continue;
    }
    const trimmed = line.trim();
    const named = /^([^:\s-][^:]*?)\s*:\s*$/.exec(trimmed);
    const dashed = /^-\s*([^:]+?)\s*:\s*$/.exec(trimmed);
    if (named) {
      const inner = parseNamedNode(lines, i + 1, indent + 2);
      children.push({ name: named[1], ...inner.node });
      i = inner.nextIndex;
      continue;
    }
    if (dashed) {
      const inner = parseNamedNode(lines, i + 1, indent + 4);
      children.push({ name: dashed[1], ...inner.node });
      i = inner.nextIndex;
      continue;
    }
    i += 1;
  }
  return { children, nextIndex: i };
}

function countIndent(line) {
  let count = 0;
  while (count < line.length && line[count] === ' ') count += 1;
  return count;
}

function stripFormula(value) {
  if (!value) return '';
  return String(value).replace(/^=/, '').trim();
}

/** Flatten a nested control tree into a path-keyed list for easy iteration. */
function flattenControls(controls, screenName, parentPath = '') {
  const flat = [];
  for (const control of controls || []) {
    const myPath = parentPath
      ? `${parentPath}/${control.name}`
      : `${screenName}/${control.name}`;
    flat.push({
      ...control,
      path: myPath,
      parent: parentPath || screenName,
      kind: deriveControlKind(control),
      template: control.control || null,
    });
    if (control.controls && control.controls.length > 0) {
      flat.push(...flattenControls(control.controls, screenName, myPath));
    }
  }
  return flat;
}

function deriveControlKind(control) {
  const c = control.control || '';
  if (!c) return 'Unknown';
  if (c === 'CanvasComponent') return 'Component';
  const bare = c.split('@')[0]; // strip @version
  // Classic/Button -> Button, Classic/ComboBox -> ComboBox, etc.
  const parts = bare.split('/');
  return parts[parts.length - 1];
}

