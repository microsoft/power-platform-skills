function parseComponentDefinitions(componentMetadata, parsedComponents) {
  const out = [];
  // componentMetadata is an array of { Name, NameInvariant, ComponentType, ... }
  if (componentMetadata && Array.isArray(componentMetadata)) {
    for (const def of componentMetadata) {
      const name = def.Name || def.NameInvariant;
      const parsed = parsedComponents.get(name);
      out.push(buildComponentDefEntry(name, def, parsed));
    }
  }
  // Add any components seen in YAML but not in metadata.
  for (const [name, parsed] of parsedComponents.entries()) {
    if (out.find((c) => c.name === name)) continue;
    out.push(buildComponentDefEntry(name, null, parsed));
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Build one entry. Prefers the YAML `CustomProperties` block (authoritative
 * per the official v3 schema) over name-pattern matching on `prop_` / `out_` /
 * `on*` keys, which are author conventions rather than schema-enforced.
 * Falls back to name-pattern matching when CustomProperties is absent (older
 * msapp formats or fully-classic components).
 */
function buildComponentDefEntry(name, metadataDef, parsed) {
  // YAML-level fields take precedence over the metadata file when both exist.
  const yamlDefinitionType = parsed?.definitionType || null;
  const metadataType = metadataDef?.ComponentType || null;
  const definitionType = yamlDefinitionType || metadataType || 'CanvasComponent';

  // CustomProperties (authoritative). Bucket by PropertyKind.
  const cp = parsed?.customProperties || null;
  let inputs = [];
  let outputs = [];
  let events = [];
  let inputFunctions = [];
  let outputFunctions = [];
  let actions = [];
  if (cp && Object.keys(cp).length > 0) {
    for (const [propName, info] of Object.entries(cp)) {
      const shape = {
        name: propName,
        kind: (info.propertyKind || '').toLowerCase() || 'input',
        dataType: info.dataType || info.returnType || null,
        defaultFormula: info.default || null,
      };
      if (info.raiseOnReset === true) shape.raiseOnReset = true;
      if (info.description) shape.description = info.description;
      if (info.parameters) shape.parameters = info.parameters;
      switch (info.propertyKind) {
        case 'Input': inputs.push(shape); break;
        case 'Output': outputs.push(shape); break;
        case 'Event': events.push(shape); break;
        case 'InputFunction': inputFunctions.push(shape); break;
        case 'OutputFunction': outputFunctions.push(shape); break;
        case 'Action': actions.push(shape); break;
        default: inputs.push(shape); break;
      }
    }
  } else {
    // Legacy fallback — name-pattern matching on prop_/out_/on* keys.
    inputs = collectComponentProps(parsed, /^prop_/i, 'input');
    outputs = collectComponentProps(parsed, /^out_|^output_/i, 'output');
    events = collectComponentProps(parsed, /^evt_|^on[A-Z]/, 'event');
  }

  const entry = {
    name,
    type: definitionType,
    definitionType,
    isClassic: !!(metadataDef && metadataDef.IsClassic),
    description: parsed?.description || null,
    accessAppScope: parsed?.accessAppScope === true ? true : undefined,
    allowCustomization: parsed?.allowCustomization === true ? true : undefined,
    controlCount: parsed?.controlsFlat?.length || 0,
    inputs,
    outputs,
    events,
  };
  if (inputFunctions.length) entry.inputFunctions = inputFunctions;
  if (outputFunctions.length) entry.outputFunctions = outputFunctions;
  if (actions.length) entry.actions = actions;
  // Strip `undefined` keys so JSON output stays tidy.
  for (const k of Object.keys(entry)) if (entry[k] === undefined) delete entry[k];
  return entry;
}

function collectComponentProps(parsedComponent, namePattern, kind) {
  if (!parsedComponent) return [];
  const props = parsedComponent.properties || {};
  return Object.entries(props)
    .filter(([propName]) => namePattern.test(propName))
    .map(([propName, formula]) => ({
      name: propName,
      kind,
      defaultFormula: formula,
    }));
}

// =============================================================================
// Theme palette helpers
//
// `References/Themes.json` ships:
//   CurrentTheme:  string id of the active palette (e.g. "defaultTheme")
//   CustomThemes[{name, palette[{name,value,type}], styles}]
//
// Palette entry `type` markers:
//   "c"   color (RGBA(...) / %Color.RESERVED%.Foo / ColorFade(RGBA(...), ...))
//   "n"   number (size in px/pt)
//   "e"   enum (%FontWeight.RESERVED%.Semibold / %Font.RESERVED%.'Open Sans')
//   "![]" array literal (chart color palette)
//
// We project the raw palette into a structured `brand.palette` so the native
// generator can map design tokens 1:1 instead of guessing from formulas.
// =============================================================================

function normalizeRgba(raw) {
  if (typeof raw !== 'string') return null;
  const m = raw.match(/RGBA\s*\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\)/i);
  if (!m) return null;
  return `rgba(${Number(m[1])}, ${Number(m[2])}, ${Number(m[3])}, ${Number(m[4])})`;
}

function parseColorValue(raw) {
  if (typeof raw !== 'string') return { value: null, raw };
  const rgba = normalizeRgba(raw);
  if (rgba) return { value: rgba, raw };
  const reserved = raw.match(/%Color\.RESERVED%\.(\w+)/);
  if (reserved) return { value: reserved[1].toLowerCase(), raw };
  // Leave ColorFade(...) and other expressions as-is so the generator can resolve them.
  return { value: null, raw };
}

function parseChartPalette(raw) {
  if (typeof raw !== 'string') return [];
  const matches = [...raw.matchAll(/RGBA\s*\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\)/gi)];
  return matches.map((m) => `rgba(${Number(m[1])}, ${Number(m[2])}, ${Number(m[3])}, ${Number(m[4])})`);
}

function parseEnumValue(raw) {
  if (typeof raw !== 'string') return raw;
  // %FontWeight.RESERVED%.Semibold → "Semibold"
  // %Font.RESERVED%.'Open Sans'    → "Open Sans"
  const m = raw.match(/%\w+\.RESERVED%\.'?([^']+)'?\s*$/);
  return m ? m[1] : raw;
}

function buildPaletteFromCustomTheme(customTheme) {
  const palette = {
    colors: [],
    sizes: [],
    fontFaces: [],
    fontWeights: [],
    chartPalette: [],
    other: [],
  };
  const items = customTheme?.palette;
  if (!Array.isArray(items)) return palette;

  for (const entry of items) {
    const name = entry?.name;
    const raw = entry?.value;
    const type = entry?.type;
    if (!name) continue;

    if (type === 'c') {
      const { value } = parseColorValue(raw);
      palette.colors.push({ name, value: value || raw, raw });
    } else if (type === 'n') {
      const n = Number(raw);
      palette.sizes.push({ name, value: Number.isFinite(n) ? n : raw });
    } else if (type === 'e') {
      const v = parseEnumValue(raw);
      if (/Font\.RESERVED/.test(String(raw))) {
        palette.fontFaces.push({ name, value: v });
      } else if (/FontWeight\.RESERVED/.test(String(raw))) {
        palette.fontWeights.push({ name, value: v });
      } else {
        palette.other.push({ name, value: v, raw });
      }
    } else if (type === '![]') {
      palette.chartPalette = parseChartPalette(raw);
    } else {
      palette.other.push({ name, value: raw });
    }
  }
  return palette;
}

// Resolve the "primary" brand color by checking common semantic names in order
// of preference, falling back to the first concrete RGBA we find.
function pickSemanticColor(colors, candidateNames) {
  if (!Array.isArray(colors)) return null;
  for (const name of candidateNames) {
    const hit = colors.find((c) => c.name === name && /^rgba\(/.test(c.value || ''));
    if (hit) return hit.value;
  }
  const firstRgba = colors.find((c) => /^rgba\(/.test(c.value || ''));
  return firstRgba ? firstRgba.value : null;
}

function parseThemes(themesRefs, modernThemesRefs, appNode) {
  const brand = {
    primaryColor: null,
    backgroundColor: null,
    textColor: null,
    fonts: [],
    themeName: 'PowerAppsTheme',
    themeId: null,
    palette: null,
  };
  let displayName = null;

  if (themesRefs?.Themes?.length) {
    brand.themeName = themesRefs.Themes[0].ThemeName || brand.themeName;
  }
  if (modernThemesRefs?.CurrentTheme?.Name) {
    brand.themeName = modernThemesRefs.CurrentTheme.Name;
  }

  // Themes.json: CurrentTheme is a string id pointing at one of CustomThemes[].name.
  if (typeof themesRefs?.CurrentTheme === 'string') {
    brand.themeId = themesRefs.CurrentTheme;
  }
  const customThemes = Array.isArray(themesRefs?.CustomThemes) ? themesRefs.CustomThemes : [];
  const activeTheme =
    customThemes.find((t) => t?.name === brand.themeId) || customThemes[0] || null;
  if (activeTheme) {
    if (!brand.themeId) brand.themeId = activeTheme.name || null;
    const palette = buildPaletteFromCustomTheme(activeTheme);
    brand.palette = palette;
    brand.primaryColor = pickSemanticColor(palette.colors, [
      'PrimaryColor1',
      'InvertedBkgColor',
      'PrimaryColor2',
    ]);
    brand.backgroundColor = pickSemanticColor(palette.colors, [
      'ScreenBkgColor',
      'InputBkgColor',
    ]);
    brand.textColor = pickSemanticColor(palette.colors, [
      'TextMainColor',
      'InputTextColor',
    ]);
    brand.fonts = palette.fontFaces.map((f) => f.value).filter(Boolean);
  }

  // Fallback formula scrape for apps that don't ship a custom theme palette.
  if (!brand.primaryColor && appNode?.properties?.Formulas) {
    const formulas = appNode.properties.Formulas;
    const colorMatches = [...formulas.matchAll(/RGBA\s*\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)/g)];
    if (colorMatches.length > 0) {
      const [, r, g, b] = colorMatches[0];
      brand.primaryColor = `rgba(${r}, ${g}, ${b}, 1)`;
    }
  }
  if (brand.fonts.length === 0 && appNode?.properties?.Formulas) {
    const fontMatches = [...appNode.properties.Formulas.matchAll(/Font\.'([^']+)'/g)];
    brand.fonts = [...new Set(fontMatches.map((m) => m[1]))];
  }
  return { brand, displayName };
}

// =============================================================================
// Intent classifier
//
// For every control we walk its known event/lifecycle properties and classify
// each top-level statement in the Power Fx formula into a closed verb set.
// Anything we can't classify lands in an `unknown` entry with the raw text.
// =============================================================================

const CONTROL_EVENT_PROPERTIES = new Set([
  'OnSelect',
  'OnChange',
  'OnVisible',
  'OnHidden',
  'OnReset',
  'OnCheck',
  'OnUncheck',
  'OnSuccess',
  'OnFailure',
  'OnSave',
  'OnNew',
  'OnEdit',
  'OnView',
  'OnCancel',
  'OnAddFile',
  'OnRemoveFile',
  'OnTimerEnd',
  'OnTimerStart',
  'OnScan',
  'OnSearch',
  'OnLoad',
  'OnError',
  'OnStart',
]);

function classifyControlEvents(control, dataSources, parsedComponents) {
  const events = {};
  const props = control.properties || {};
  for (const [propName, formula] of Object.entries(props)) {
    if (!CONTROL_EVENT_PROPERTIES.has(propName)) continue;
    events[propName] = classifyFormulaIntents(formula, dataSources, parsedComponents);
  }
  return events;
}

function classifyAppEvents(appNode) {
  const out = { OnStart: [], OnError: [], Formulas: [] };
  const props = appNode.properties || {};
  for (const propName of ['OnStart', 'OnError']) {
    if (props[propName]) {
      out[propName] = classifyFormulaIntents(props[propName], null, null);
    }
  }
  if (props.Formulas) {
    // App.Formulas defines named formulas (`nf_*`); capture them as global definitions.
    out.Formulas = parseNamedFormulas(props.Formulas);
  }
  return out;
}

function parseNamedFormulas(blob) {
  const formulas = [];
  const stripped = stripFormula(blob);
  // Split on ; not inside parens or quotes — a soft splitter is good enough for V1.
  const segments = splitTopLevelStatements(stripped, ';');
  for (const seg of segments) {
    const m = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([\s\S]+)$/.exec(seg.trim());
    if (m) formulas.push({ name: m[1], expression: m[2].trim() });
  }
  return formulas;
}

function classifyFormulaIntents(formulaText, _dataSources, _parsedComponents) {
  const stripped = stripBlockComments(stripFormula(formulaText));
  if (!stripped) return [];
  const statements = splitTopLevelStatements(stripped, ';');
  const intents = [];
  for (let statementIndex = 0; statementIndex < statements.length; statementIndex += 1) {
    const statement = statements[statementIndex];
    const trimmed = statement.trim();
    if (!trimmed || trimmed.startsWith('//')) continue;
    intents.push(...classifyStatement(trimmed).map((intent) => ({
      ...intent,
      sourceStatement: intent.sourceStatement || trimmed,
      sourceStatementIndex: statementIndex,
    })));
  }
  return intents;
}

/** Remove Power Fx block AND line comments BEFORE statement-splitting so `;`
 * inside comments doesn't split the statement, and so a leading line comment
 * doesn't make `classifyFormulaIntents` skip the actual call that follows it.
 * Respects quoted strings. */
function stripBlockComments(text) {
  if (!text) return text;
  // NOTE: do NOT early-exit when `/*` is absent — many Power Fx bodies use
  // only `//` line comments and we still need to remove those.
  let out = '';
  let i = 0;
  let inSingle = false;
  let inDouble = false;
  while (i < text.length) {
    const ch = text[i];
    const next = text[i + 1];
    if (inSingle) {
      out += ch;
      if (ch === "'" && next === "'") {
        out += next;
        i += 2;
        continue;
      }
      if (ch === "'") inSingle = false;
      i += 1;
      continue;
    }
    if (inDouble) {
      out += ch;
      if (ch === '"' && next === '"') {
        out += next;
        i += 2;
        continue;
      }
      if (ch === '"') inDouble = false;
      i += 1;
      continue;
    }
    if (ch === "'") { inSingle = true; out += ch; i += 1; continue; }
    if (ch === '"') { inDouble = true; out += ch; i += 1; continue; }
    if (ch === '/' && next === '*') {
      const close = text.indexOf('*/', i + 2);
      if (close === -1) return out; // unterminated — drop the rest
      i = close + 2;
      continue;
    }
    if (ch === '/' && next === '/') {
      const eol = text.indexOf('\n', i + 2);
      i = eol === -1 ? text.length : eol;
      continue;
    }
    out += ch;
    i += 1;
  }
  return out;
}

const QUALIFIED_CALL_PART = "(?:[A-Za-z_][A-Za-z0-9_]*|'(?:[^']|'')+')";
const QUALIFIED_CALL_RE = new RegExp(`^(${QUALIFIED_CALL_PART}(?:\\.${QUALIFIED_CALL_PART})*)\\s*\\(`);

function parseQualifiedCallName(rawName) {
  const parts = [];
  let current = '';
  let inSingle = false;
  for (let i = 0; i < rawName.length; i += 1) {
    const ch = rawName[i];
    const next = rawName[i + 1];
    if (inSingle) {
      if (ch === "'" && next === "'") {
        current += "'";
        i += 1;
      } else if (ch === "'") {
        inSingle = false;
      } else {
        current += ch;
      }
      continue;
    }
    if (ch === "'") {
      inSingle = true;
      continue;
    }
    if (ch === '.') {
      parts.push(current);
      current = '';
      continue;
    }
    current += ch;
  }
  if (current || rawName.endsWith("''")) parts.push(current);
  return parts.filter((part) => part !== '');
}

function withControlFlow(intents, frame, sourceStatement) {
  return intents.map((intent) => ({
    ...intent,
    controlFlow: [frame, ...(Array.isArray(intent.controlFlow) ? intent.controlFlow : [])],
    sourceStatement: intent.sourceStatement || String(sourceStatement || '').trim() || null,
  }));
}

function classifyControlledStatement(statement, frame) {
  return withControlFlow(classifyFormulaIntents(statement), frame, statement);
}

function controlFlowId(kind, statement) {
  const text = `${kind}:${String(statement || '')}`;
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return `${kind}-${(hash >>> 0).toString(16).padStart(8, '0')}`;
}

function parseForAllSource(rawSource) {
  const text = String(rawSource || '').trim();
  const match = /^([\s\S]*?)\s+As\s+([A-Za-z_][A-Za-z0-9_]*)\s*$/i.exec(text);
  return match
    ? { source: match[1].trim(), alias: match[2] }
    : { source: text, alias: null };
}

function classifyStatement(statement) {
  // Use the quote-aware scanner here too. A second regex-based comment pass
  // used to turn Launch("https://...") into Launch("https: before parsing.
  const cleaned = stripBlockComments(String(statement || '')).trim();
  if (!cleaned) return [];
  // Bare literal expressions (numbers, booleans, blank) — not actions.
  if (/^(true|false|Blank\(\)|-?\d+(?:\.\d+)?)$/.test(cleaned)) {
    return [{ intent: 'literal', value: cleaned }];
  }
  // Top-level record literal — typically a ForAll projection or With binding.
  if (cleaned.startsWith('{') && cleaned.endsWith('}')) {
    return [{ intent: 'projection', fields: parseRecordLiteral(cleaned) }];
  }
  // Bare property read (Control.Property or 'Source'.Column). No side effect.
  if (!cleaned.includes('(') && /[A-Za-z_].*\./.test(cleaned)) {
    return [{ intent: 'read', expression: cleaned }];
  }
  // Handle a top-level call, including quoted Power Fx identifiers such as
  // 'My Approval Flow'.Run(...).
  const callMatch = QUALIFIED_CALL_RE.exec(cleaned);
  if (!callMatch) {
    return [{ intent: 'unknown', raw: cleaned }];
  }
  const rawName = callMatch[1];
  const nameParts = parseQualifiedCallName(rawName);
  const name = nameParts.join('.');
  const argsBlob = sliceBalancedArgs(cleaned, callMatch.index + rawName.length);
  const args = splitTopLevelArgs(argsBlob);
  const flowId = (kind) => controlFlowId(kind, cleaned);

  switch (name) {
    case 'Navigate':
      return [{
        intent: 'navigate',
        target: argName(args[0]),
        transition: args[1] ? stripQuotes(args[1].trim()) : null,
        context: args[2] ? parseRecordLiteral(args[2]) : null,
      }];
    case 'Back':
      return [{ intent: 'back', transition: args[0] ? args[0].trim() : null }];
    case 'NewForm':
    case 'EditForm':
    case 'ViewForm':
    case 'SubmitForm':
    case 'ResetForm':
      return [{ intent: lowerFirst(name), form: argName(args[0]) }];
    case 'Patch':
      return [{
        intent: 'patch',
        source: argName(args[0]),
        baseRecord: args[1] ? args[1].trim() : null,
        fields: parseRecordLiteral(args[2]) || parseRecordLiteral(args[1]),
        rawArgs: args.length,
      }];
    case 'Update':
    case 'UpdateIf':
      return [{ intent: name === 'Update' ? 'update' : 'updateIf', source: argName(args[0]) }];
    case 'Remove':
    case 'RemoveIf':
      return [{ intent: name === 'Remove' ? 'remove' : 'removeIf', source: argName(args[0]) }];
    case 'Collect':
    case 'ClearCollect': {
      const fromArg = args[1] ? args[1].trim() : null;
      const inferredSchema = fromArg ? parseRecordLiteral(fromArg) : null;
      return [{
        intent: name === 'Collect' ? 'collect' : 'clearCollect',
        collection: argName(args[0]),
        from: fromArg ? fromArg : null,
        inferredSchema,
      }];
    }
    case 'Clear':
      return [{ intent: 'clear', collection: argName(args[0]) }];
    case 'Set': {
      const exprArg = args[1] ? args[1].trim() : null;
      const inferredSchema = exprArg && exprArg.startsWith('{') && exprArg.endsWith('}')
        ? parseRecordLiteral(exprArg)
        : null;
      return [{
        intent: 'setVar',
        name: argName(args[0]),
        expression: exprArg ? exprArg : null,
        inferredSchema,
      }];
    }
    case 'UpdateContext':
      return [{ intent: 'setContext', context: parseRecordLiteral(args[0]) }];
    case 'SaveData': {
      const key = args[1] ? stripQuotes(args[1].trim()) : null;
      return [{
        intent: 'saveData',
        collection: argName(args[0]),
        name: key,
        key,
      }];
    }
    case 'LoadData': {
      const key = args[1] ? stripQuotes(args[1].trim()) : null;
      return [{
        intent: 'loadData',
        collection: argName(args[0]),
        name: key,
        key,
        ignoreNonexistentFile: args[2] ? args[2].trim() : null,
      }];
    }
    case 'Launch':
      return [{ intent: 'launch', target: args[0] ? truncate(args[0].trim(), 200) : null }];
    case 'Notify':
      return [{ intent: 'notify', message: args[0] ? truncate(args[0].trim(), 200) : null, type: args[1] ? args[1].trim() : null }];
    case 'Refresh':
      return [{ intent: 'refresh', source: argName(args[0]) }];
    case 'Exit':
      // `Exit()` / `Exit(true)` — closes the player. Native shells need to
      // map this to platform-specific close behavior (background vs kill).
      return [{ intent: 'exitApp', signOut: args[0] ? args[0].trim() : null }];
    case 'ClearData':
      // `ClearData()` clears ALL persisted SaveData buffers; with an arg it
      // targets a single collection. Critical for offline-aware native shells.
      return [{
        intent: 'clearOfflineData',
        name: args[0] ? argName(args[0]) : null,
      }];
    case 'ShowHostInfo':
      // `ShowHostInfo("OfflineSync")` (and other tokens) opens host-provided
      // UI panes. Native shells often need to wire these to bespoke screens.
      return [{
        intent: 'showHostInfo',
        target: args[0] ? stripQuotes(args[0].trim()) : null,
      }];
    case 'RequestHide':
      // Mainly used in custom pages to dismiss the modal. Worth surfacing so
      // native shells can mirror the close affordance.
      return [{ intent: 'requestHide' }];
    case 'Select':
      return [{ intent: 'select', target: argName(args[0]) }];
    case 'Reset':
      return [{ intent: 'reset', target: argName(args[0]) }];
    case 'SetProperty':
      return [{ intent: 'setProperty', target: argName(args[0]), value: args[1] ? args[1].trim() : null }];
    case 'SetFocus':
      return [{ intent: 'setFocus', target: argName(args[0]) }];
    case 'Disable':
    case 'Enable':
      return [{ intent: lowerFirst(name), target: argName(args[0]) }];
    case 'Confirm':
      return [{ intent: 'confirm', message: args[0] ? truncate(args[0].trim(), 160) : null }];
    case 'Print':
      return [{ intent: 'print' }];
    case 'Download':
      return [{ intent: 'download', target: args[0] ? truncate(args[0].trim(), 200) : null }];
    case 'DownloadJSON':
      return [{ intent: 'downloadJson', source: args[0] ? truncate(args[0].trim(), 200) : null }];
    case 'Param':
      return [{ intent: 'paramRead', name: args[0] ? stripQuotes(args[0].trim()) : null }];
    case 'Concurrent':
      return args.flatMap((arg, branchIndex) => classifyControlledStatement(arg, {
        kind: 'concurrent',
        id: flowId('concurrent'),
        branchIndex,
      }));
    case 'With': {
      // With(bindings, body) — only the body is interesting; bindings are
      // record-literal scope, but retain them as control-flow context.
      if (args.length >= 2) {
        return classifyControlledStatement(args[1], {
          kind: 'with',
          id: flowId('with'),
          bindingsExpression: args[0].trim(),
          bindings: parseRecordLiteral(args[0]),
        });
      }
      return [{ intent: 'unknown', raw: cleaned }];
    }
    case 'IfError': {
      // IfError(value1, fallback1[, value2, fallback2, ...][, default]).
      if (args.length < 2) return [{ intent: 'unknown', raw: cleaned }];
      const out = [];
      const hasDefault = args.length % 2 === 1;
      const pairEnd = hasDefault ? args.length - 1 : args.length;
      for (let i = 0; i + 1 < pairEnd; i += 2) {
        const clauseIndex = i / 2;
        out.push(...classifyControlledStatement(args[i], {
          kind: 'ifError', id: flowId('ifError'), clauseIndex, role: 'try',
        }));
        out.push(...classifyControlledStatement(args[i + 1], {
          kind: 'ifError', id: flowId('ifError'), clauseIndex, role: 'fallback',
        }));
      }
      if (hasDefault) {
        out.push(...classifyControlledStatement(args[args.length - 1], {
          kind: 'ifError', id: flowId('ifError'), role: 'default',
        }));
      }
      return out;
    }
    case 'If': {
      if (args.length < 2) return [{ intent: 'unknown', raw: cleaned }];
      const out = [];
      const hasElse = args.length % 2 === 1;
      const branchEnd = hasElse ? args.length - 1 : args.length;
      for (let i = 0; i + 1 < branchEnd; i += 2) {
        out.push(...classifyControlledStatement(args[i + 1], {
          kind: 'if',
          id: flowId('if'),
          branchIndex: i / 2,
          role: 'then',
          condition: args[i].trim(),
        }));
      }
      if (hasElse) {
        out.push(...classifyControlledStatement(args[args.length - 1], {
          kind: 'if', id: flowId('if'), role: 'else',
        }));
      }
      return out;
    }
    case 'Switch': {
      if (args.length < 3) return [{ intent: 'unknown', raw: cleaned }];
      const out = [];
      const expression = args[0].trim();
      const remaining = args.slice(1);
      const hasDefault = remaining.length % 2 === 1;
      const caseEnd = hasDefault ? remaining.length - 1 : remaining.length;
      for (let i = 0; i + 1 < caseEnd; i += 2) {
        out.push(...classifyControlledStatement(remaining[i + 1], {
          kind: 'switch',
          id: flowId('switch'),
          expression,
          caseIndex: i / 2,
          role: 'case',
          match: remaining[i].trim(),
        }));
      }
      if (hasDefault) {
        out.push(...classifyControlledStatement(remaining[remaining.length - 1], {
          kind: 'switch', id: flowId('switch'), expression, role: 'default',
        }));
      }
      return out;
    }
    case 'ForAll': {
      // Preserve the source table and optional `As` alias around every body
      // action so the adapter can reconstruct loop semantics.
      if (args.length >= 2) {
        const source = parseForAllSource(args[0]);
        return classifyControlledStatement(args[1], {
          kind: 'forAll',
          id: flowId('forAll'),
          source: source.source,
          alias: source.alias,
        });
      }
      return [{ intent: 'unknown', raw: cleaned }];
    }
    case 'Trace':
    case 'Validate':
      return [{ intent: 'diagnostic', call: name, raw: cleaned }];
    default:
      // Possibly a connector / flow / AI call: Identifier.Method(...).
      if (nameParts.length > 1) {
        const action = nameParts[nameParts.length - 1];
        const connector = nameParts.slice(0, -1).join('.');
        // Power Automate flow calls are typically `.Run` / `.RunAsync`.
        if (action === 'Run' || action === 'RunAsync') {
          return [{
            intent: 'flowCall',
            flow: connector,
            action,
            // Keep arguments in full — they are the payload the AI must rewire
            // (e.g. what a flow/connector call actually sends). No truncation.
            args: args.map((a) => a.trim()),
          }];
        }
        // AI Builder + Azure Cognitive Services calls.
        if (/^(Predict|Classify|Extract|Summarize|Score|Recognize|Detect|Translate)$/.test(action)
            || /^(AIBuilder|FormRecognizer|TextAnalytics|ComputerVision|CognitiveServices)/i.test(connector)) {
          return [{
            intent: 'aiCall',
            connector,
            action,
            args: args.map((a) => a.trim()),
          }];
        }
        return [{
          intent: 'connectorCall',
          connector,
          action,
          args: args.map((a) => a.trim()),
        }];
      }
      return [{ intent: 'unknown', call: name, raw: cleaned }];
  }
}

function argName(arg) {
  if (arg === undefined || arg === null) return null;
  const trimmed = String(arg).trim();
  if (!trimmed) return null;
  // Trim wrappers and quotes.
  return stripQuotes(trimmed);
}

function stripQuotes(value) {
  if (value.length >= 2 && ((value[0] === '"' && value[value.length - 1] === '"') || (value[0] === "'" && value[value.length - 1] === "'"))) {
    return value.slice(1, -1);
  }
  return value;
}

function lowerFirst(value) {
  return value.charAt(0).toLowerCase() + value.slice(1);
}

function truncate(value, max) {
  const s = String(value).replace(/\s+/g, ' ');
  return s.length > max ? s.slice(0, max) + '…' : s;
}

function parseRecordLiteral(text) {
  if (!text) return null;
  const trimmed = text.trim();
  if (!trimmed.startsWith('{') || !trimmed.endsWith('}')) return null;
  const body = trimmed.slice(1, -1);
  const parts = splitTopLevelArgs(body);
  const record = {};
  for (const part of parts) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*|'[^']+')\s*:\s*([\s\S]+)$/.exec(part);
    if (m) {
      const k = stripQuotes(m[1]).trim();
      record[k] = m[2].trim();
    }
  }
  return Object.keys(record).length ? record : null;
}

function splitTopLevelStatements(text, separator) {
  return splitRespectingDepth(text, separator, /* keepSeparator */ false);
}

function splitTopLevelArgs(text) {
  return splitRespectingDepth(text, ',', false);
}

function splitRespectingDepth(text, separator) {
  if (!text) return [];
  const out = [];
  let buffer = '';
  let depth = 0;
  let inSingle = false;
  let inDouble = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    const next = text[i + 1];
    if (inSingle) {
      buffer += ch;
      if (ch === "'" && next === "'") {
        buffer += next;
        i += 1;
      } else if (ch === "'") {
        inSingle = false;
      }
      continue;
    }
    if (inDouble) {
      buffer += ch;
      if (ch === '"' && next === '"') {
        buffer += next;
        i += 1;
      } else if (ch === '"') {
        inDouble = false;
      }
      continue;
    }
    if (ch === "'") {
      inSingle = true;
      buffer += ch;
      continue;
    }
    if (ch === '"') {
      inDouble = true;
      buffer += ch;
      continue;
    }
    if (ch === '(' || ch === '{' || ch === '[') {
      depth += 1;
      buffer += ch;
      continue;
    }
    if (ch === ')' || ch === '}' || ch === ']') {
      depth -= 1;
      buffer += ch;
      continue;
    }
    if (depth === 0 && ch === separator) {
      if (buffer.trim()) out.push(buffer);
      buffer = '';
      continue;
    }
    buffer += ch;
  }
  if (buffer.trim()) out.push(buffer);
  return out;
}

function sliceBalancedArgs(text, openIndex) {
  // `openIndex` is typically the index right after the call's identifier, which
  // may be whitespace because Power Fx allows `Concurrent (...)` with a space
  // before the open paren. Skip forward to the actual `(` first; otherwise the
  // returned slice keeps a stray leading `(` and downstream argument splitting
  // sees the whole body as one un-splittable unknown arg.
  let start = openIndex;
  while (start < text.length && text[start] !== '(') start += 1;
  if (start >= text.length) return '';
  let depth = 0;
  let inSingle = false;
  let inDouble = false;
  for (let i = start; i < text.length; i += 1) {
    const ch = text[i];
    const next = text[i + 1];
    if (inSingle) {
      if (ch === "'" && next === "'") i += 1;
      else if (ch === "'") inSingle = false;
      continue;
    }
    if (inDouble) {
      if (ch === '"' && next === '"') i += 1;
      else if (ch === '"') inDouble = false;
      continue;
    }
    if (ch === "'") { inSingle = true; continue; }
    if (ch === '"') { inDouble = true; continue; }
    if (ch === '(') depth += 1;
    else if (ch === ')') {
      depth -= 1;
      if (depth === 0) return text.slice(start + 1, i);
    }
  }
  return text.slice(start + 1);
}

