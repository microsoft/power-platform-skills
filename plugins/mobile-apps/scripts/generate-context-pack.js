#!/usr/bin/env node
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const directionCatalogue = require('./lib/design-direction-catalogue');

const PLUGIN_ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(PLUGIN_ROOT, 'shared', 'context-pack.md');
const SOURCES = {
  screens: path.join(PLUGIN_ROOT, 'shared', 'references', 'screen-templates.md'),
  derivation: path.join(PLUGIN_ROOT, 'shared', 'references', 'derivation-contract.md'),
  i18n: path.join(PLUGIN_ROOT, 'shared', 'references', 'i18n-rtl.md'),
  planSchema: path.join(PLUGIN_ROOT, 'shared', 'contracts', 'plan.schema.json'),
  components: path.join(PLUGIN_ROOT, 'shared', 'samples', 'src', 'components', 'index.tsx'),
  package: path.join(PLUGIN_ROOT, 'template', 'package.json'),
  templateConfig: path.join(PLUGIN_ROOT, 'template', 'tamagui.config.ts'),
  directions: directionCatalogue.DIRECTIONS_DIR,
  directionCatalogue: directionCatalogue.CATALOGUE_PATH,
};

const read = (filePath) => fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
const hash = (contents) => crypto.createHash('sha256').update(contents).digest('hex');

function section(markdown, heading) {
  const start = markdown.indexOf(`${heading}\n`);
  if (start < 0) return '';
  const level = heading.match(/^#+/)?.[0].length || 1;
  const body = markdown.slice(start + heading.length + 1);
  const next = body.search(new RegExp(`^#{1,${level}}\\s+`, 'm'));
  return `${heading}\n${next < 0 ? body : body.slice(0, next)}`.trim();
}

function catalogueKeys(markdown) {
  return [...new Set([...markdown.matchAll(/^\|\s*`([^`]+)`\s*\|/gm)].map((match) => match[1]))].sort();
}

function componentExports(source) {
  return [...new Set([...source.matchAll(/^export\s+(?:async\s+)?(?:function|const|class|type|interface)\s+([A-Za-z_$][A-Za-z0-9_$]*)/gm)].map((match) => match[1]))].sort();
}

function directionNames() {
  return directionCatalogue.load().map((entry) => entry.slug);
}

function generate() {
  const screens = read(SOURCES.screens);
  const components = read(SOURCES.components);
  const packageJson = JSON.parse(read(SOURCES.package));
  const derivation = read(SOURCES.derivation);
  const i18n = read(SOURCES.i18n);
  const planSchema = JSON.parse(read(SOURCES.planSchema));
  const directions = directionCatalogue.load();
  const dependencies = Object.keys({ ...packageJson.dependencies, ...packageJson.devDependencies }).sort();
  const inputs = [SOURCES.screens, SOURCES.components, SOURCES.package, SOURCES.templateConfig, SOURCES.planSchema, SOURCES.directionCatalogue, ...directions.map((entry) => path.join(SOURCES.directions, entry.source)), ...(derivation ? [SOURCES.derivation] : []), ...(i18n ? [SOURCES.i18n] : [])];
  return `<!-- GENERATED by scripts/generate-context-pack.js. DO NOT EDIT. -->
# Mobile Planner Context Pack

Use this as the first and normally only plugin-reference read in prototype mode.
Project-local plans, contracts, vocabulary, and brand artifacts remain authoritative.

## Source Digests
${inputs.map((filePath) => `- \`${path.relative(PLUGIN_ROOT, filePath)}\`: \`${hash(read(filePath))}\``).join('\n')}

## Template Contract
- Expo Router + React Native + TypeScript + Tamagui Config v5.
- Fresh markers: \`package.json\`, \`app.config.js\`, \`auth.config.json\`, \`tamagui.config.ts\`.
- Data imports: \`@/generated/services\`; native wrappers: \`@/native\`.
- \`PowerAppsProvider\` owns Tamagui, auth, host, and React Query infrastructure.
- Prototype mode performs zero environment, PAC, Azure, Dataverse HTTP, or connection operations.

## Template Dependency Allowlist
${dependencies.map((name) => `- \`${name}\``).join('\n')}

Runtime-banned even if present: \`expo-haptics\`. Missing native packages are dropped transparently.

## Catalogue Keys
${catalogueKeys(screens).map((key) => `- \`${key}\``).join('\n')}

${section(screens, '### Cardinality pattern defaults')}

${section(screens, '### Hero type keys (Detail screens)')}

${section(screens, '### Operational pattern keys (Home + workflow screens)')}

## Shared Component Inventory
${componentExports(components).map((name) => `- \`${name}\``).join('\n')}

## Design Directions
${directions.map((entry) => `- \`${entry.slug}\` — ${entry.summary}`).join('\n')}

## Derivation Contract
${derivation ? derivation.replace(/^#.+\n/, '').trim() : 'Not yet authored. Apply current subject/data-binding rules until the generated source exists.'}

## Internationalization And RTL
${i18n ? i18n.replace(/^#.+\n/, '').trim() : 'Use locale-aware messages and logical layout.'}

## Structured Plan Contract
- Required screen fields: ${planSchema.$defs.screen.required.map((name) => `\`${name}\``).join(', ')}.
- Home additionally requires \`hero\`.
- Schema-complete plans build at concurrency 3; thin plans build serially and return \`DONE_WITH_CONCERNS\`.
`;
}

function main() {
  const expected = generate();
  if (process.argv.includes('--check')) {
    if (read(OUTPUT) !== expected) { console.error('shared/context-pack.md is stale; run node scripts/generate-context-pack.js'); process.exit(1); }
    console.log('context-pack: current');
    return;
  }
  fs.writeFileSync(OUTPUT, expected);
  console.log(`context-pack: wrote ${path.relative(PLUGIN_ROOT, OUTPUT)}`);
}

if (require.main === module) main();
module.exports = { OUTPUT, SOURCES, catalogueKeys, componentExports, generate, section };