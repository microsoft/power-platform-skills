#!/usr/bin/env node
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { navigationContractRevision } = require('./resolve-navigation-contract');
const { resolveIconName } = require('./lib/navigation-icons');
const { stableStringify } = require('./resolve-context-enrichment');

const GENERATED_MARKER = '// Generated by apply-navigation-shell.js. Do not edit directly.';

function sha256(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

function topLevelEntry(route) {
  return String(route || '').split('/').filter(Boolean).filter((segment) => segment !== '(app)')[0] || 'home';
}

function componentName(value) {
  return String(value || '').split(/[^A-Za-z0-9]+/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join('') || 'Navigation';
}

function shellSource(contract, screenContract) {
  const destinationEntries = contract.destinations.map((destination) => ({ ...destination, entry: topLevelEntry(destination.route) }));
  const destinationEntryNames = new Set(destinationEntries.map((destination) => destination.entry));
  const hiddenEntries = [...new Set((screenContract.screens || []).map((screen) => topLevelEntry(screen.route)).filter((entry) => !destinationEntryNames.has(entry)))];
  if (contract.model === 'tabs-stack') {
    const destinationScreens = destinationEntries.map((destination) => `      <Tabs.Screen
        name="${destination.entry}"
        options={{
          title: ${JSON.stringify(destination.label)},
          tabBarAccessibilityLabel: ${JSON.stringify(destination.label)},
          tabBarButtonTestID: ${JSON.stringify(destination.testId)},
          tabBarIcon: ({ color, size }) => <Ionicons name="${resolveIconName(destination.iconIntent)}" color={color} size={size} />,
        }}
      />`).join('\n');
    const hiddenScreens = hiddenEntries.map((entry) => `      <Tabs.Screen name="${entry}" options={{ href: null }} />`).join('\n');
    return `${GENERATED_MARKER}
import { Tabs } from 'expo-router/tabs';
import { Ionicons } from '@expo/vector-icons';

export function AppNavigationShell() {
  return (
    <Tabs screenOptions={{ headerShown: false }}>
${destinationScreens}${hiddenScreens ? `\n${hiddenScreens}` : ''}
    </Tabs>
  );
}
`;
  }
  if (contract.model === 'drawer') {
    const destinationScreens = destinationEntries.map((destination) => `      <Drawer.Screen
        name="${destination.entry}"
        options={{
          title: ${JSON.stringify(destination.label)},
          drawerLabel: ${JSON.stringify(destination.label)},
          drawerItemStyle: { minHeight: ${contract.accessibility.minimumTouchTarget} },
          drawerIcon: ({ color, size }) => <Ionicons name="${resolveIconName(destination.iconIntent)}" color={color} size={size} />,
        }}
      />`).join('\n');
    const hiddenScreens = hiddenEntries.map((entry) => `      <Drawer.Screen name="${entry}" options={{ drawerItemStyle: { display: 'none' } }} />`).join('\n');
    return `${GENERATED_MARKER}
import { Drawer } from 'expo-router/drawer';
import { Ionicons } from '@expo/vector-icons';

export function AppNavigationShell() {
  return (
    <Drawer screenOptions={{ headerShown: false }}>
${destinationScreens}${hiddenScreens ? `\n${hiddenScreens}` : ''}
    </Drawer>
  );
}
`;
  }
  const screenRows = (screenContract.screens || []).map((screen) => {
    const relative = String(screen.route).split('/').filter(Boolean).filter((segment) => segment !== '(app)').join('/');
    return `      <Stack.Screen name="${relative}" options={{ headerShown: false${screen.navigation?.kind === 'modal' ? ", presentation: 'modal'" : ''} }} />`;
  }).join('\n');
  return `${GENERATED_MARKER}
import { Stack } from 'expo-router/stack';

export function AppNavigationShell() {
  return (
    <Stack screenOptions={{ headerShown: false }}>
${screenRows}
    </Stack>
  );
}
`;
}

function innerStackArtifacts(contract, screenContract) {
  const byId = new Map((screenContract.screens || []).map((screen) => [screen.id, screen]));
  const artifacts = {};
  for (const destination of contract.destinations) {
    const root = byId.get(destination.rootScreenId);
    if (!root) continue;
    const rootEntry = topLevelEntry(root.route);
    const nested = destination.nestedScreenIds.map((screenId) => byId.get(screenId)).filter((screen) => screen && topLevelEntry(screen.route) === rootEntry);
    if (!nested.length || !root.file.includes(`/${rootEntry}/`)) continue;
    const rows = nested.map((screen) => {
      const relative = screen.file.split(`/${rootEntry}/`)[1].replace(/\.tsx$/, '').replace(/\/index$/, '');
      const presentation = screen.navigation?.presentation;
      return `      <Stack.Screen name="${relative}"${presentation && presentation !== 'nested-stack' ? ` options={{ presentation: '${presentation === 'full-screen-modal' ? 'fullScreenModal' : 'modal'}' }}` : ''} />`;
    }).join('\n');
    artifacts[`app/(app)/${rootEntry}/_layout.tsx`] = `${GENERATED_MARKER}
import { Stack } from 'expo-router/stack';

export default function ${componentName(rootEntry)}StackLayout() {
  return (
    <Stack screenOptions={{ headerShown: false }}>
      <Stack.Screen name="index" />
${rows}
    </Stack>
  );
}
`;
  }
  return artifacts;
}

function navigationShellArtifacts(contract, screenContract) {
  return {
    'src/navigation/AppNavigationShell.tsx': shellSource(contract, screenContract),
    ...innerStackArtifacts(contract, screenContract),
  };
}

function shellFingerprint(artifacts) {
  return sha256(stableStringify(Object.fromEntries(Object.entries(artifacts).sort(([left], [right]) => left.localeCompare(right)).map(([file, content]) => [file, sha256(content)]))));
}

function patchAppLayout(content) {
  if (content.includes("from '../../src/navigation/AppNavigationShell'") && /<AppNavigationShell\s*\/>/.test(content)) return content;
  if (/<(?:Tabs|Drawer)\b/.test(content)) throw new Error('app/(app)/_layout.tsx contains user-owned navigation; explicit navigation restructuring approval is required');
  const imports = [...content.matchAll(/\bimport\s+[^;]+;/g)];
  if (!imports.length) throw new Error('app/(app)/_layout.tsx import block was not found');
  const lastImport = imports.at(-1);
  let patched = `${content.slice(0, lastImport.index + lastImport[0].length)}\nimport { AppNavigationShell } from '../../src/navigation/AppNavigationShell';${content.slice(lastImport.index + lastImport[0].length)}`;
  const functionEnd = patched.lastIndexOf('\n}');
  const start = patched.lastIndexOf('\n  return ', functionEnd);
  const end = patched.lastIndexOf(';', functionEnd);
  if (start < 0 || end < start) throw new Error('app/(app)/_layout.tsx final return block was not found');
  patched = `${patched.slice(0, start)}\n  return <AppNavigationShell />;${patched.slice(end + 1)}`;
  return patched;
}

function assertOwnedOrMissing(filePath) {
  if (!fs.existsSync(filePath)) return;
  if (!fs.readFileSync(filePath, 'utf8').startsWith(GENERATED_MARKER)) throw new Error(`refusing to overwrite user-owned navigation file ${filePath}`);
}

function writeAtomic(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const temporaryPath = `${filePath}.tmp-${process.pid}-${Date.now()}`;
  fs.writeFileSync(temporaryPath, content, { flag: 'wx' });
  fs.renameSync(temporaryPath, filePath);
}

function applyNavigationShell(projectRoot, contract, screenContract) {
  const root = path.resolve(projectRoot);
  const layoutPath = path.join(root, 'app', '(app)', '_layout.tsx');
  if (!fs.existsSync(layoutPath)) throw new Error('app/(app)/_layout.tsx is missing');
  const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  if (!packageJson.dependencies?.['expo-router']) throw new Error('project must install expo-router before applying a navigation shell');
  if (contract.model !== 'stack' && !packageJson.dependencies?.['@expo/vector-icons']) throw new Error('project must install @expo/vector-icons before applying a labeled navigation shell');
  if (contract.model === 'drawer' && packageJson.dependencies?.['@react-navigation/drawer'] !== '7.9.4') throw new Error('template must install @react-navigation/drawer@7.9.4 before applying a drawer shell');
  const artifacts = navigationShellArtifacts(contract, screenContract);
  for (const relativePath of Object.keys(artifacts)) assertOwnedOrMissing(path.join(root, relativePath));
  const patchedLayout = patchAppLayout(fs.readFileSync(layoutPath, 'utf8'));
  for (const [relativePath, content] of Object.entries(artifacts)) writeAtomic(path.join(root, relativePath), content);
  writeAtomic(layoutPath, patchedLayout);
  const fingerprintArtifacts = { ...artifacts, 'app/(app)/_layout.tsx': patchedLayout };
  const manifest = {
    schemaVersion: 1,
    navigationContractRevision: navigationContractRevision(contract),
    model: contract.model,
    files: Object.keys(fingerprintArtifacts).sort(),
    shellFingerprint: shellFingerprint(fingerprintArtifacts),
  };
  writeAtomic(path.join(root, '.mobile-app', 'navigation-shell.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

function main(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--project-root') args.projectRoot = argv[++index];
    else if (argv[index] === '--navigation-contract') args.navigationContract = argv[++index];
    else if (argv[index] === '--screen-contract') args.screenContract = argv[++index];
  }
  if (!args.projectRoot) {
    process.stderr.write('Usage: node apply-navigation-shell.js --project-root <dir> [--navigation-contract .tmp/navigation-contract.json] [--screen-contract .tmp/experience-screen-contract.json]\n');
    return 2;
  }
  try {
    const root = path.resolve(args.projectRoot);
    const readJson = (value, fallback) => JSON.parse(fs.readFileSync(path.resolve(root, value || fallback), 'utf8'));
    const result = applyNavigationShell(root, readJson(args.navigationContract, '.tmp/navigation-contract.json'), readJson(args.screenContract, '.tmp/experience-screen-contract.json'));
    process.stdout.write(`${JSON.stringify({ status: 'ok', ...result }, null, 2)}\n`);
    return 0;
  } catch (error) {
    process.stderr.write(`apply-navigation-shell: ${error.message}\n`);
    return 2;
  }
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { GENERATED_MARKER, applyNavigationShell, navigationShellArtifacts, patchAppLayout, shellFingerprint };